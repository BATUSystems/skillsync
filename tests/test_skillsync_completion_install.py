def snapshot_paths(paths):
    """exists + mtime of each path; read only (guard of K14)."""
    result = {}
    for path in paths:
        try:
            result[str(path)] = (True, os.lstat(path).st_mtime_ns)
        except OSError:
            result[str(path)] = (False, None)
    return result


def tree(root):
    """Whole content of a directory tree: kind, bytes, mtime, mode, link target."""
    out = {}
    root = Path(root)
    for path in sorted(root.rglob('*')):
        rel = str(path.relative_to(root))
        st = os.lstat(path)
        if stat.S_ISLNK(st.st_mode):
            out[rel] = ('link', os.readlink(path))
        elif stat.S_ISDIR(st.st_mode):
            out[rel] = ('dir', stat.S_IMODE(st.st_mode))
        else:
            out[rel] = ('file', path.read_bytes(), st.st_mtime_ns, stat.S_IMODE(st.st_mode))
    return out


class Result:
    def __init__(self, proc, report):
        self.rc = proc.returncode
        self.out = proc.stdout.decode('utf-8', 'replace')
        self.err = proc.stderr.decode('utf-8', 'replace')
        self.report = report

    def action(self, path):
        want = Path(path).resolve()
        for item in (self.report or {}).get('actions', []):
            if Path(item['path']).resolve() == want:
                return item
        raise AssertionError(f'no action for {path}; actions={json.dumps((self.report or {}).get("actions"), indent=1)}\nerr={self.err}')

    def results(self):
        return [a['result'] for a in (self.report or {}).get('actions', [])]


class Sandbox:
    def __init__(self, root):
        self.root = Path(root).resolve()
        self.home = self.root / 'home'
        self.xdg = self.root / 'xdg'
        self.local = self.root / 'local'
        self.appdata = self.root / 'appdata'
        self.tools = self.root / 'tools'
        self.cwd = self.root / 'cwd'
        self.profile = self.home / 'Documents' / 'PowerShell' / 'profile.ps1'
        for path in (self.home, self.xdg, self.local, self.appdata, self.tools, self.cwd, self.profile.parent):
            path.mkdir(parents=True, exist_ok=True)
        self.extra = {}

    # fake tools
    def tool(self, name, body=''):
        if WIN:
            (self.tools / f'{name}.bat').write_text('@echo off\r\n' + body, encoding='ascii')
        else:
            path = self.tools / name
            path.write_text('#!/bin/sh\n' + body, encoding='utf-8')
            path.chmod(0o755)

    def shells(self, *names):
        for name in names:
            if name in ('pwsh', 'powershell'):
                var = 'FAKE_PS64' if name == 'pwsh' else 'FAKE_PS64_5'
                self.tool(name, f'echo P64:%{var}%\r\nif defined FAKE_POLICY echo POLICY:%FAKE_POLICY%\r\n' if WIN else
                          f'[ -n "$FAKE_LOG" ] && printf \'%s\\n\' "$*" >> "$FAKE_LOG"\nprintf \'P64:%s\\n\' "${var}"\n'
                          f'if [ -n "$FAKE_POLICY" ]; then printf \'POLICY:%s\\n\' "$FAKE_POLICY"; fi\n')
            else:
                self.tool(name)
        self.extra.setdefault('FAKE_PROFILE', str(self.profile))

    def env(self, **over):
        env = {'HOME': str(self.home), 'USERPROFILE': str(self.home), 'XDG_DATA_HOME': str(self.xdg),
               'XDG_CONFIG_HOME': str(self.home / '.config'), 'XDG_CACHE_HOME': str(self.root / 'cache'),
               'APPDATA': str(self.appdata), 'LOCALAPPDATA': str(self.local), 'PATH': str(self.tools),
               'SKILLSYNC_CONFIG': str(self.root / 'no-config.yaml'), 'PYTHONUTF8': '1',
               'SKILLSYNC_TEST_LIBRARY': os.environ['SKILLSYNC_TEST_LIBRARY']}
        for key in ('SYSTEMROOT', 'TEMP', 'TMP'):
            if key in os.environ:
                env[key] = os.environ[key]
        env.update(self.extra)
        for key, value in over.items():
            if value is None:
                env.pop(key, None)
            else:
                env[key] = value
        for source, target in (('FAKE_PROFILE', 'FAKE_PS64'), ('FAKE_PROFILE_5', 'FAKE_PS64_5')):
            if source in env:
                env[target] = base64.b64encode(env[source].encode('utf-8')).decode()
        return env

    def run(self, action, *args, json_out=True, **over):
        cmd = [sys.executable, str(ROOT / 'skillsync'), 'completion', action, *args]
        if json_out:
            cmd.append('--json')
        proc = subprocess.run(cmd, env=self.env(**over), cwd=self.cwd, capture_output=True, timeout=120)
        report = None
        if json_out:
            try:
                report = json.loads(proc.stdout.decode('utf-8'))
            except ValueError:
                report = None
        return Result(proc, report)

    def install(self, *args, **kw):
        return self.run('install', *args, **kw)

    def uninstall(self, *args, **kw):
        return self.run('uninstall', *args, **kw)

    # expected paths
    @property
    def bash_file(self):
        return self.xdg / 'bash-completion' / 'completions' / 'skillsync'

    @property
    def zsh_file(self):
        return self.xdg / 'zsh' / 'site-functions' / '_skillsync'

    @property
    def zshrc(self):
        return self.home / '.zshrc'

    @property
    def ps_script(self):
        return (self.local if WIN else self.xdg) / 'skillsync' / 'completion' / 'skillsync-completion.ps1'


def block_of(data):
    start = data.index(START)
    return data[start:data.index(END) + len(END)]


class Base(unittest.TestCase):
    def setUp(self):
        tmp = tempfile.TemporaryDirectory()
        self.addCleanup(tmp.cleanup)
        self.sb = Sandbox(tmp.name)
        self._guard = snapshot_paths(REAL_PATHS)

    def tearDown(self):
        self.assertEqual(snapshot_paths(REAL_PATHS), self._guard, 'a test touched the real HOME (K14)')

    def assertOk(self, res):
        self.assertEqual(res.rc, 0, f'rc={res.rc}\nout={res.out}\nerr={res.err}')
        self.assertIsNotNone(res.report, f'no JSON: {res.out}\n{res.err}')

    def prepare_zshrc(self, content):
        self.sb.zshrc.write_bytes(content)
        self.sb.shells('zsh')


class IsolationGuardTest(Base):
    def test_guard_detects_a_change(self):
        # proof that the K14 guard can fail: a touched and a created path both differ from the snapshot
        existing = self.sb.root / 'rc'
        existing.write_bytes(b'x')
        before = snapshot_paths([existing, self.sb.root / 'new'])
        os.utime(existing, ns=(1, 1))
        (self.sb.root / 'new').write_bytes(b'y')
        self.assertNotEqual(snapshot_paths([existing, self.sb.root / 'new']), before)


