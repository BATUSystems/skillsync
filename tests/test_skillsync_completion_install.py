    @unittest.skipUnless(hasattr(os, 'chown'), 'POSIX only: file ownership')
    def test_the_owner_is_carried_over_only_when_it_differs_and_errors_are_ignored(self):
        import types
        target, tmp = self.sb.root / 'rc', self.sb.root / 'tmp'
        target.write_bytes(b'a')
        tmp.write_bytes(b'b')
        mine = os.stat(tmp)
        other = types.SimpleNamespace(st_uid=mine.st_uid + 4242, st_gid=mine.st_gid)
        same = types.SimpleNamespace(st_uid=mine.st_uid, st_gid=mine.st_gid)
        with mock.patch.object(os, 'chown') as chown:
            completion_install._carry_attributes(str(target), str(tmp), same, 0o600)
            chown.assert_not_called()
            completion_install._carry_attributes(str(target), str(tmp), other, 0o600)
            chown.assert_called_once_with(str(tmp), other.st_uid, other.st_gid)
        with mock.patch.object(os, 'chown', side_effect=PermissionError('no')):
            completion_install._carry_attributes(str(target), str(tmp), other, 0o600)   # must not raise
        self.assertEqual(stat.S_IMODE(tmp.stat().st_mode), 0o600)


