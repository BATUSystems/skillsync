class UninstallTest(Base):
    def roundtrip(self, original, shell='zsh', path=None):
        path = path or self.sb.zshrc
        path.write_bytes(original)
        self.sb.shells('zsh', 'pwsh')
        self.assertOk(self.sb.install('--shell', shell))
        self.assertNotEqual(path.read_bytes(), original)
        res = self.sb.uninstall('--shell', shell)
        self.assertOk(res)
        self.assertEqual(path.read_bytes(), original)
        self.assertIn(res.action(path)['result'], ('updated', 'removed'))
        self.assertTrue(Path(str(path) + '.skillsync-bak').exists(), 'the backup stays')

    def test_zsh_rc_is_byte_identical_after_install_and_uninstall(self):
        cases = {'lf': b'export A=1\nalias x=y\n', 'crlf': b'export A=1\r\nalias x=y\r\n', 'bom': BOM + b'a=1\n',
                 'no newline at end': b'export A=1\nalias x=y', 'mixed': b'a\r\nb\r\nc\r\nd\n', 'crlf no newline at end': b'a\r\nb\r\nc'}
        for name, original in cases.items():
            with self.subTest(name):
                shutil.rmtree(self.sb.xdg, ignore_errors=True)
                for leftover in self.sb.home.glob('.zshrc*'):
                    leftover.unlink()
                self.roundtrip(original)

    def test_powershell_profile_is_byte_identical_after_install_and_uninstall(self):
        self.roundtrip(BOM + b'# profile\r\nSet-Alias a b\r\n', shell='powershell', path=self.sb.profile)

    def test_uninstall_removes_only_our_files_and_never_shared_directories(self):
        self.sb.shells('bash', 'zsh', 'pwsh')
        self.assertOk(self.sb.install())
        foreign_bash = self.sb.bash_file.with_name('other')
        foreign_zsh = self.sb.zsh_file.with_name('_other')
        foreign_bash.write_text('mine\n')
        foreign_zsh.write_text('mine\n')
        self.assertOk(self.sb.uninstall())
        self.assertFalse(self.sb.bash_file.exists())
        self.assertFalse(self.sb.zsh_file.exists())
        self.assertFalse(self.sb.ps_script.exists())
        self.assertEqual(foreign_bash.read_text(), 'mine\n')
        self.assertEqual(foreign_zsh.read_text(), 'mine\n')
        self.assertFalse(self.sb.ps_script.parent.exists(), 'our own empty directory skillsync/completion is removed')
        foreign_bash.unlink()
        foreign_zsh.unlink()
        self.assertOk(self.sb.install())
        self.assertOk(self.sb.uninstall())
        self.assertTrue(self.sb.bash_file.parent.is_dir(), 'bash-completion/completions is never removed')
        self.assertTrue(self.sb.zsh_file.parent.is_dir(), 'zsh/site-functions is never removed')

    def test_own_directory_with_a_foreign_file_stays(self):
        self.sb.shells('pwsh')
