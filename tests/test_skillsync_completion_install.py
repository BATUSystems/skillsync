class BlockInRcTest(Base):
    def test_second_install_is_unchanged_and_leaves_bytes_and_mtime(self):
        self.prepare_zshrc(b'export A=1\n')
        self.assertOk(self.sb.install())
        old = 10**9
        for path in (self.sb.zshrc, self.sb.zsh_file, self.sb.zshrc.with_name('.zshrc.skillsync-bak')):
            os.utime(path, ns=(old, old))
        bytes_before = self.sb.zshrc.read_bytes()
        second = self.sb.install()
        self.assertOk(second)
        self.assertEqual(second.action(self.sb.zshrc)['result'], 'unchanged')
        self.assertEqual(second.action(self.sb.zsh_file)['result'], 'unchanged')
        self.assertEqual(self.sb.zshrc.read_bytes(), bytes_before)
        self.assertEqual(self.sb.zshrc.stat().st_mtime_ns, old)
        self.assertEqual(self.sb.zsh_file.stat().st_mtime_ns, old)
        self.assertEqual(self.sb.zshrc.read_bytes().count(START), 1)

    def test_block_is_appended_at_the_end(self):
        original = b'export A=1\nalias x=y\n'
        self.prepare_zshrc(original)
        self.assertOk(self.sb.install())
        data = self.sb.zshrc.read_bytes()
        self.assertTrue(data.startswith(original))
        self.assertTrue(data[len(original):].startswith(START))
        self.assertTrue(data.rstrip(b'\r\n').endswith(END))

    def test_file_without_final_newline_gets_one_before_the_block(self):
        original = b'export A=1\nalias x=y'
        self.prepare_zshrc(original)
        self.assertOk(self.sb.install())
        data = self.sb.zshrc.read_bytes()
        self.assertTrue(data.startswith(original + b'\n' + START), data[:80])

    def test_changed_block_is_replaced_in_place(self):
        self.prepare_zshrc(b'before=1\n')
        self.assertOk(self.sb.install())
        data = self.sb.zshrc.read_bytes()
        self.sb.zshrc.write_bytes(data + b'after=2\n')
        other = self.sb.root / 'other-data'
        res = self.sb.install(XDG_DATA_HOME=str(other))
        self.assertOk(res)
        self.assertEqual(res.action(self.sb.zshrc)['result'], 'updated')
        new = self.sb.zshrc.read_bytes()
        self.assertEqual(new.count(START), 1)
        self.assertTrue(new.startswith(b'before=1\n' + START))
        self.assertTrue(new.endswith(END + b'\nafter=2\n'))
        self.assertIn(str(other).encode(), block_of(new))
        self.assertNotIn(str(self.sb.xdg).encode(), new)

    def test_two_blocks_fail_without_writing(self):
        block = START + b'\nx=1\n' + END + b'\n'
        original = b'a=1\n' + block + b'b=2\n' + block
