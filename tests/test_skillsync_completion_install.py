    def test_json_report_schema(self):
        self.sb.shells('bash', 'zsh')
        for run in (lambda: self.sb.install(), lambda: self.sb.install('--dry-run'), lambda: self.sb.uninstall()):
            report = run().report
            self.assertEqual(set(report), {'schema', 'status', 'dry_run', 'actions', 'warnings'})
            self.assertEqual(report['schema'], 1)
            self.assertIn(report['status'], ('PASS', 'FAIL', 'BLOCKED', 'NOT_RUN'))
            self.assertIsInstance(report['dry_run'], bool)
            self.assertIsInstance(report['warnings'], list)
            self.assertTrue(report['actions'])
            for item in report['actions']:
                self.assertEqual(set(item), {'shell', 'path', 'result', 'detail'})
                self.assertIn(item['result'], ('created', 'updated', 'unchanged', 'removed', 'skipped', 'failed'))
                self.assertIn(item['shell'], ('bash', 'zsh', 'powershell'))

    def test_dry_run_changes_nothing_and_reports_planned_actions(self):
        self.sb.shells('bash', 'zsh', 'pwsh')
        self.sb.zshrc.write_bytes(b'export A=1\n')
