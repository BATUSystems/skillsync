        plain = self.sb.install('--dry-run', json_out=False)
        self.assertEqual(plain.rc, 0)
        for path in (self.sb.bash_file, self.sb.zsh_file, self.sb.zshrc, self.sb.ps_script, self.sb.profile):
            self.assertIn(str(path), plain.out, f'dry-run output lists {path}')
        self.assertEqual(tree(self.sb.root), before)

