def tree(path):
    """Snapshot of a directory: relative path -> kind and content (no following of links)."""
    result = {}
    path = Path(path)
    if not os.path.lexists(path):
        return None
    for current, dirs, files in os.walk(path):
        for name in dirs + files:
            full = Path(current) / name
            rel = full.relative_to(path).as_posix()
            if full.is_symlink():
                result[rel] = ('l', os.readlink(full))
            elif full.is_dir():
                result[rel] = ('d',)
            else:
                result[rel] = ('f', full.read_bytes())
    return result


def scan_blocks(text):
    """Top-level (selector, body) pairs of a CSS text without comments; brace matching honours strings and parens."""
    text = re.sub(r'/\*.*?\*/', '', text, flags=re.S)
    blocks, prelude, body, depth, quote = [], '', '', 0, None
    for char in text:
        if quote:
            if depth:
                body += char
            else:
                prelude += char
            if char == quote:
                quote = None
            continue
        if char in '"\'':
            quote = char
        if char == '{' and depth == 0:
            depth = 1
            continue
        if char == '{':
            depth += 1
        elif char == '}':
            depth -= 1
            if depth == 0:
                blocks.append((' '.join(prelude.split()), body))
                prelude, body = '', ''
                continue
        if depth:
            body += char
        else:
            prelude += char
    return blocks


def declarations(body):
    """Custom-property declarations (name, value) of one block body, split on ';' outside strings and parens."""
    parts, current, quote, parens = [], '', None, 0
    for char in body:
        if quote:
            current += char
            quote = None if char == quote else quote
            continue
        if char in '"\'':
            quote = char
        elif char == '(':
            parens += 1
        elif char == ')':
            parens -= 1
        elif char == ';' and parens == 0:
            parts.append(current)
            current = ''
            continue
        current += char
    parts.append(current)
    result = []
    for part in parts:
        part = part.strip()
        if part.startswith('--') and ':' in part:
            name, value = part.split(':', 1)
            result.append((name.strip(), value.strip()))
    return result


def layers(tokens_css, default_css):
    """(light, dark) lists of project declarations that follow the unchanged default theme in tokens.css."""
    assert default_css in tokens_css, 'tokens.css must contain theme/default.css unchanged'
    rest = tokens_css.split(default_css, 1)[1]
    light, dark, media = [], [], []
    for selector, body in scan_blocks(rest):
        if selector == ':root':
            light += declarations(body)
        elif selector == ':root[data-theme="dark"]':
            dark += declarations(body)
        elif selector == '@media (prefers-color-scheme: dark)':
            for inner, inner_body in scan_blocks(body):
                assert inner == ':root:not([data-theme])', f'unexpected selector in the dark @media block: {inner!r}'
                media += declarations(inner_body)
        else:
            raise AssertionError(f'unexpected selector in tokens.css: {selector!r}')
    assert media == dark, 'project dark tokens must repeat in @media (prefers-color-scheme: dark) :root:not([data-theme])'
    return light, dark


class TagCollector(HTMLParser):
    def __init__(self):
        super().__init__()
        self.tags, self.hrefs, self.text = [], [], []

    def handle_starttag(self, tag, attrs):
        self.tags.append(tag)
        self.hrefs += [value for name, value in attrs if name == 'href']

    def handle_data(self, data):
        self.text.append(data)


def parse_html(text):
    collector = TagCollector()
    collector.feed(text)
    return collector


