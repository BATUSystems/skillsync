    # -- CLI -------------------------------------------------------------
    def proto(self, action, *args, code=0, assets=True, env=None, umask=None):
        argv = [sys.executable, str(CLI), 'prototype', action, str(self.root), *map(str, args), '--json']
        if assets and action in ('init', 'sync') and '--assets' not in args:
            argv += ['--assets', str(self.assets)]
        environ = {key: value for key, value in os.environ.items() if key != NOW_ENV}
        environ.update(env or {})
        extra = {'preexec_fn': lambda: os.umask(umask)} if umask is not None else {}
        result = subprocess.run(argv, capture_output=True, text=True, timeout=60, cwd=self.base, env=environ, **extra)
        self.assertNotIn('Traceback', result.stderr, result.stderr)
        self.assertEqual(result.returncode, code, result.stdout + result.stderr)
        report = json.loads(result.stdout)
        expected = {0: ('PASS', 'NOT_RUN'), 1: ('FAIL',), 2: ('BLOCKED',)}[code]
        self.assertIn(report['status'], expected, report)
        return report

