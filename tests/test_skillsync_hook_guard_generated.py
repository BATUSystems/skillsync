"""CLAUDE-3 / F3: the PreToolUse hook `library/hooks/guard-generated.py` (spec K4, A3).

The hook reads the PreToolUse payload (`tool_name` Write|Edit|NotebookEdit, `tool_input.file_path` absolute, `cwd`) and recognises files
generated by skillsync ONLY by explicit rules: path patterns relative to the git root, a symlink into a library layer, the Codex block of
AGENTS.md, CLAUDE.md with the BASE-END marker and the `Generated by skillsync` header. Modes: `warn` (additionalContext, exit 0), `deny`
(exit 2 and a message on stderr), `off` (nothing). Every other failure is fail-open (exit 0). The script is taken from the repository.
"""
import json
import subprocess
import sys
import unittest
from pathlib import Path

import sys as _sys_tmp_paths  # noqa: E402
from pathlib import Path as _Path_tmp_paths  # noqa: E402
_sys_tmp_paths.path.insert(0, str(_Path_tmp_paths(__file__).resolve().parent))  # noqa: E402
from tmp_paths import child, descend  # noqa: E402
from layers_helpers import IsolatedTestCase, needs_os_symlinks  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
HOOK = ROOT / 'library' / 'hooks' / 'guard-generated.py'
BEGIN, END = '<!-- SKILLSYNC:CODEX-BEGIN -->', '<!-- SKILLSYNC:CODEX-END -->'
AGENTS = f'# Projekt\n\nwłasny wstęp\n\n{BEGIN}\ngenerated codex line\n{END}\n\nwłasny koniec\n'
GENERATED_PATHS = ['.claude/agents/implementer.md', '.claude/skills/feature/SKILL.md', '.agents/skills/feature/SKILL.md',
                   '.codex/agents/implementer.toml', '.codex/config.toml', '.github/copilot-instructions.md',
                   '.github/skills/feature/SKILL.md', '.github/agents/implementer.md']
EDITABLE_PATHS = ['docs/guide.md', 'src/app.py', 'README.md', '.github/workflows/ci.yml', '.github/.skillsync.yaml',
                  '.claude/settings.local.json', 'tests/test_x.py']


class GuardGeneratedHook(IsolatedTestCase):
    def setUp(self):
        super().setUp()
        self.repo = self.make_repo('proj')

    # --- helpers -------------------------------------------------------------------------------------------------------
    def put(self, relative, text):
        path = descend(self.repo, relative)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding='utf-8', newline='')
        return path

    def run_hook(self, payload=None, mode='warn', raw=None, extra=None):
        self.assertTrue(HOOK.is_file(), f'{HOOK} does not exist yet (expected red until F4)')
        data = raw if raw is not None else json.dumps(payload, ensure_ascii=False)
        args = [sys.executable, str(HOOK)] + (extra if extra is not None else (['--mode', mode] if mode else []))
        done = subprocess.run(args, input=data.encode('utf-8'), capture_output=True, timeout=30, cwd=str(self.repo))
        self.stderr = done.stderr.decode('utf-8', 'replace')
        return done

    def write_payload(self, path, tool='Write', **tool_input):
        tool_input = {'file_path': str(path), **({'content': 'x'} if tool == 'Write' and not tool_input else {}), **tool_input}
        return {'session_id': 's', 'hook_event_name': 'PreToolUse', 'tool_name': tool, 'tool_input': tool_input, 'cwd': str(self.repo)}

    def context(self, done):
        """The additionalContext of a warn result ('' when nothing was printed); exit must be 0."""
        self.assertEqual(done.returncode, 0, self.stderr)
        text = done.stdout.decode('utf-8').strip()
        if not text:
            return ''
        special = json.loads(text)['hookSpecificOutput']
        self.assertEqual(special['hookEventName'], 'PreToolUse')
        return special['additionalContext']

    def assertFlagged(self, payload, mode='warn'):
        done = self.run_hook(payload, mode=mode)
        if mode == 'deny':
            self.assertEqual(done.returncode, 2, self.stderr)
            self.assertTrue(self.stderr.strip(), 'deny must explain itself on stderr')
            return self.stderr
        text = self.context(done)
        self.assertIn('skillsync link', text)
        return text

    def assertClean(self, payload, mode='warn'):
        done = self.run_hook(payload, mode=mode)
        self.assertEqual(done.returncode, 0, self.stderr)
        self.assertEqual(done.stdout.decode('utf-8').strip(), '')

    # --- (a) path patterns ---------------------------------------------------------------------------------------------
    def test_generated_paths_are_flagged_in_warn_mode_for_all_three_tools(self):
        for relative in GENERATED_PATHS:
            for tool in ('Write', 'Edit', 'NotebookEdit'):
                with self.subTest(path=relative, tool=tool):
                    extra = {'old_string': 'a', 'new_string': 'b'} if tool == 'Edit' else {'new_source': 'b'} if tool == 'NotebookEdit' else {}
                    self.assertFlagged(self.write_payload(descend(self.repo, relative), tool, **extra))

    def test_generated_paths_are_refused_in_deny_mode(self):
        for relative in GENERATED_PATHS:
            with self.subTest(path=relative):
                self.assertFlagged(self.write_payload(descend(self.repo, relative)), mode='deny')

    def test_instruction_files_point_to_skillsync_push_too(self):
        for relative in ('.github/copilot-instructions.md', '.claude/agents/implementer.md'):
            with self.subTest(path=relative):
                text = self.assertFlagged(self.write_payload(descend(self.repo, relative)))
                if relative.endswith('copilot-instructions.md'):
                    self.assertIn('skillsync push', text)

    def test_editable_paths_are_left_alone_in_every_mode(self):
        for relative in EDITABLE_PATHS:
            for mode in ('warn', 'deny', 'off'):
                with self.subTest(path=relative, mode=mode):
                    self.assertClean(self.write_payload(descend(self.repo, relative)), mode=mode)

    def test_patterns_are_relative_to_the_git_root_also_from_a_subdirectory_cwd(self):
        sub = child(self.repo, 'sub')
        sub.mkdir()
        payload = self.write_payload(descend(self.repo, '.claude/agents/x.md'))
        payload['cwd'] = str(sub)
        self.assertFlagged(payload)

    def test_the_same_names_below_another_directory_are_not_generated(self):
        for relative in ('docs/.claude/agents/x.md', 'docs/.codex/config.toml', 'vendor/.github/copilot-instructions.md'):
            with self.subTest(path=relative):
                self.assertClean(self.write_payload(descend(self.repo, relative)), mode='deny')

    def test_paths_outside_the_repository_are_left_alone(self):
        outside = descend(self.root, 'elsewhere/.claude/agents/x.md')
        self.assertClean(self.write_payload(outside), mode='deny')

    # --- (b) symlink into a library layer ------------------------------------------------------------------------------
    @needs_os_symlinks
    def test_symlink_into_a_library_layer_is_flagged_and_points_to_the_library(self):
        layer = child(self.root, 'library')
        layer.mkdir()
        target = child(layer, 'shared.md')
        target.write_text('from the library\n', encoding='utf-8')
        link = descend(self.repo, 'notes/shared.md')
        link.parent.mkdir()
        link.symlink_to(target)
        text = self.assertFlagged(self.write_payload(link, 'Edit', old_string='a', new_string='b'))
        self.assertRegex(text.lower(), r'bibliotek|librar|skillsync push')
        self.assertFlagged(self.write_payload(link), mode='deny')

    @needs_os_symlinks
    def test_symlink_into_skills_of_a_library_keeps_the_layer_message_with_push(self):
        target = descend(child(self.root, 'library'), 'skills/feature/SKILL.md')
        target.parent.mkdir(parents=True)
        target.write_text('from the library\n', encoding='utf-8')
        link = descend(self.repo, 'notes/skill.md')
        link.parent.mkdir()
        link.symlink_to(target)
        text = self.assertFlagged(self.write_payload(link))
        self.assertIn('dowiązaniem do warstwy biblioteki', text)
        self.assertIn('skillsync push', text)

    @needs_os_symlinks
    def test_symlink_outside_the_project_to_a_plain_directory_gets_the_general_message(self):
        target = child(child(self.root, 'plain'), 'notes.md')
        target.parent.mkdir()
        target.write_text('x\n', encoding='utf-8')
        link = descend(self.repo, 'notes/plain.md')
        link.parent.mkdir()
        link.symlink_to(target)
        text = self.assertFlagged(self.write_payload(link))
        self.assertIn('wychodzi poza projekt', text)
        self.assertNotIn('dowiązaniem do warstwy biblioteki', text)
        self.assertNotIn('skillsync push', text)

    @needs_os_symlinks
    def test_symlink_that_stays_inside_the_project_is_not_a_layer_link(self):
        target = self.put('docs/real.md', 'text\n')
        link = descend(self.repo, 'docs/alias.md')
        link.symlink_to(target)
        self.assertClean(self.write_payload(link), mode='deny')

    # --- (c) AGENTS.md ---------------------------------------------------------------------------------------------------
    def test_agents_md_edit_inside_the_block_is_flagged(self):
        path = self.put('AGENTS.md', AGENTS)
        payload = self.write_payload(path, 'Edit', old_string='generated codex line', new_string='changed')
        text = self.assertFlagged(payload)
        self.assertIn('skillsync push', text)
        self.assertFlagged(payload, mode='deny')

    def test_agents_md_edit_touching_a_marker_is_flagged(self):
        path = self.put('AGENTS.md', AGENTS)
        self.assertFlagged(self.write_payload(path, 'Edit', old_string=END, new_string=''))
        self.assertFlagged(self.write_payload(path, 'Edit', old_string='własny koniec', new_string=f'{BEGIN}\nx\n{END}'))

    def test_agents_md_edit_outside_the_block_is_allowed(self):
        path = self.put('AGENTS.md', AGENTS)
        for old in ('własny wstęp', 'własny koniec'):
            with self.subTest(old=old):
                self.assertClean(self.write_payload(path, 'Edit', old_string=old, new_string='nowy tekst'), mode='deny')

    def test_agents_md_write_that_changes_the_block_is_flagged_one_that_keeps_it_is_not(self):
        path = self.put('AGENTS.md', AGENTS)
        changed = AGENTS.replace('generated codex line', 'tampered line')
        self.assertFlagged(self.write_payload(path, content=changed))
        self.assertFlagged(self.write_payload(path, content='# bez bloku\n'), mode='deny')
        self.assertClean(self.write_payload(path, content=AGENTS.replace('własny koniec', 'inny koniec')), mode='deny')

    def test_agents_md_without_a_block_is_fully_editable(self):
        path = self.put('AGENTS.md', '# Projekt\n\ntylko własny tekst\n')
        self.assertClean(self.write_payload(path, 'Edit', old_string='tylko własny tekst', new_string='x'), mode='deny')
        self.assertClean(self.write_payload(path, content='nowa treść\n'), mode='deny')

    def test_agents_md_with_crlf_block_is_still_recognised(self):
        path = self.put('AGENTS.md', AGENTS.replace('\n', '\r\n'))
        self.assertFlagged(self.write_payload(path, 'Edit', old_string='generated codex line', new_string='x'))

    # --- (d) CLAUDE.md ---------------------------------------------------------------------------------------------------
    def test_claude_md_with_the_generator_marker_is_flagged(self):
        path = self.put('CLAUDE.md', '# Base\n\n<!-- SKILLSYNC:BASE-END -->\n\nprojektowa część\n')
        self.assertFlagged(self.write_payload(path, 'Edit', old_string='# Base', new_string='# Zmiana'))
        self.assertFlagged(self.write_payload(path), mode='deny')

    def test_claude_md_without_the_marker_is_skipped(self):
        path = self.put('CLAUDE.md', '# Ręczny plik\n\ntreść\n')
        self.assertClean(self.write_payload(path, 'Edit', old_string='treść', new_string='x'), mode='deny')
        self.assertClean(self.write_payload(path), mode='deny')

    # --- (e) header ------------------------------------------------------------------------------------------------------
    def test_file_with_the_generated_header_is_flagged_wherever_it_lives(self):
        path = self.put('tools/agent.toml', '# Generated by skillsync from shared agents/*.md and codex.yaml.\nname = "x"\n')
        self.assertFlagged(self.write_payload(path, 'Edit', old_string='name = "x"', new_string='name = "y"'))
        self.assertFlagged(self.write_payload(path), mode='deny')

    def test_toml_without_the_header_is_editable(self):
        path = self.put('tools/own.toml', '# own config\nname = "x"\n')
        self.assertClean(self.write_payload(path, 'Edit', old_string='"x"', new_string='"y"'), mode='deny')

    # --- modes -----------------------------------------------------------------------------------------------------------
    def test_warn_mode_exits_0_with_context_deny_exits_2_off_is_silent(self):
        payload = self.write_payload(descend(self.repo, '.codex/config.toml'))
        warn = self.run_hook(payload, mode='warn')
        self.assertEqual(warn.returncode, 0)
        self.assertIn('skillsync link', json.loads(warn.stdout.decode('utf-8'))['hookSpecificOutput']['additionalContext'])
        deny = self.run_hook(payload, mode='deny')
        self.assertEqual(deny.returncode, 2)
        self.assertEqual(deny.stdout.decode('utf-8').strip(), '')
        self.assertIn('skillsync link', deny.stderr.decode('utf-8'))
        off = self.run_hook(payload, mode='off')
        self.assertEqual((off.returncode, off.stdout.decode('utf-8').strip(), off.stderr.decode('utf-8').strip()), (0, '', ''))

    def test_missing_mode_never_blocks(self):
        done = self.run_hook(self.write_payload(descend(self.repo, '.codex/config.toml')), mode=None)
        self.assertEqual(done.returncode, 0, self.stderr)

    def test_unknown_mode_never_blocks(self):
        done = self.run_hook(self.write_payload(descend(self.repo, '.codex/config.toml')), extra=['--mode', 'bogus'])
        self.assertEqual(done.returncode, 0, self.stderr)

    # --- fail-open and data-shaped input ---------------------------------------------------------------------------------
    def test_garbage_input_is_fail_open_even_in_deny_mode(self):
        for raw in ('{broken', '', '   ', '[]', 'null', '"x"', '\x00\x01', '{"tool_name": "Write"}',
                    '{"tool_name": "Write", "tool_input": "x"}', '{"tool_name": "Write", "tool_input": {"file_path": 5}}'):
            with self.subTest(raw=raw):
                done = self.run_hook(raw=raw, mode='deny')
                self.assertEqual(done.returncode, 0, self.stderr)
                self.assertEqual(done.stdout.decode('utf-8').strip(), '')

    def test_other_tools_are_ignored_even_on_generated_paths(self):
        for tool in ('Bash', 'Read', 'Task', 'MultiEdit', 'Glob'):
            with self.subTest(tool=tool):
                self.assertClean(self.write_payload(descend(self.repo, '.claude/agents/x.md'), tool), mode='deny')

    def test_windows_paths_are_data_and_never_crash_or_block(self):
        for path in ('C:\\proj\\.claude\\agents\\x.md', 'c:\\PROJ\\.CLAUDE\\Agents\\X.md', '\\\\server\\share\\.codex\\config.toml',
                     'C:/proj/.github/copilot-instructions.md'):
            with self.subTest(path=path):
                done = self.run_hook(self.write_payload(path), mode='deny')
                self.assertEqual(done.returncode, 0, self.stderr)
                self.assertNotIn('Traceback', self.stderr)

    def test_utf8_path_and_content_outside_ascii(self):
        path = self.put('docs/zażółć gęślą.md', 'x')
        self.assertClean(self.write_payload(path, content='zażółć ✓'), mode='deny')
        flagged = self.write_payload(descend(self.repo, '.claude/agents/żółw.md'), content='zażółć ✓')
        self.assertFlagged(flagged)

    def test_non_git_directory_is_fail_open(self):
        plain = child(self.root, 'plain')
        plain.mkdir()
        payload = self.write_payload(descend(plain, '.claude/agents/x.md'))
        payload['cwd'] = str(plain)
        done = self.run_hook(payload, mode='deny')
        self.assertEqual(done.returncode, 0, self.stderr)


if __name__ == '__main__':
    unittest.main()
