"""`skillsync completion install|uninstall`: put the generated completion scripts in the user's data directories (CORE-COMPLETION).

Our own files (bash script, zsh function, PowerShell script) are written whole; the user's startup files (`.zshrc`, the PowerShell profile) get exactly
one block between fixed markers. Startup files are read and written as bytes (line endings and BOM kept), written atomically (temp file in the directory
of the real target + `os.replace`), and copied once to `<target>.skillsync-bak` before the first edit. Exit codes: 0 PASS/NOT_RUN, 1 FAIL, 2 BLOCKED.
"""
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile

from .completion import SCHEMA, SHELLS, render, sh_quote

START = b'# >>> skillsync completion >>>'
END = b'# <<< skillsync completion <<<'
BOM = b'\xef\xbb\xbf'
HEADER_PREFIX = b'# skillsync completion (generated by skillsync '
BACKUP_SUFFIX = '.skillsync-bak'
PS_SCRIPT = 'skillsync-completion.ps1'
PS_PROFILE = 'Microsoft.PowerShell_profile.ps1'
ENV_SWITCH = 'SKILLSYNC_NO_COMPLETION'
TRUE_VALUES = ('1', 'true', 'yes', 'on')
FALSE_VALUES = ('0', 'false', 'no', 'off', '')
PS_HOSTS = ('pwsh', 'powershell')
PS_QUERY = '$PROFILE.CurrentUserCurrentHost'
WIN = sys.platform == 'win32'


class Blocked(Exception):
    pass


# -- paths

def _valid(value, label):
    if not value or any(ord(char) < 32 or ord(char) == 127 for char in value):
        raise Blocked(f'{label} is empty or contains control characters')
    if not os.path.isabs(value):
        raise Blocked(f'{label} is not an absolute path: {value!r}')
    if '..' in re.split(r'[\\/]', value):
        raise Blocked(f'{label} contains "..": {value!r}')
    return os.path.normpath(value)


def _home():
    if 'HOME' in os.environ:
        return _valid(os.environ['HOME'], 'HOME')
    if WIN and os.environ.get('USERPROFILE'):
        return _valid(os.environ['USERPROFILE'], 'USERPROFILE')
    if WIN:
        raise Blocked('HOME is not set')
    return _valid(os.path.expanduser('~') if os.environ.get('HOME') is None else '', 'HOME')


def _optional(name):
    value = os.environ.get(name)
    return _valid(value, name) if value else None


class Targets:
    """Destination paths, validated lazily so that only the variables a chosen shell needs can block."""

    def __init__(self):
        self.home = _home()

    @property
    def xdg(self):
        return _optional('XDG_DATA_HOME') or os.path.join(self.home, '.local', 'share')

    @property
    def bash_file(self):
        return os.path.join(self.xdg, 'bash-completion', 'completions', 'skillsync')

    @property
    def zsh_file(self):
        return os.path.join(self.xdg, 'zsh', 'site-functions', '_skillsync')

    @property
    def zshrc(self):
        return os.path.join(_optional('ZDOTDIR') or self.home, '.zshrc')

    @property
    def local(self):
        return _optional('LOCALAPPDATA') or os.path.join(self.home, 'AppData', 'Local')

    @property
    def ps_script(self):
        return os.path.join(self.local if WIN else self.xdg, 'skillsync', 'completion', PS_SCRIPT)

    def default_profile(self, host):
        if WIN:
            return os.path.join(self.home, 'Documents', 'PowerShell' if host == 'pwsh' else 'WindowsPowerShell', PS_PROFILE)
        return os.path.join(self.home, '.config', 'powershell', PS_PROFILE)


# -- bytes and atomic writes

def _read(path):
    try:
        with open(path, 'rb') as handle:
            return handle.read()
    except FileNotFoundError:
        return None


def _real(path):
    return os.path.realpath(path)


def _default_mode():
    mask = os.umask(0)
    os.umask(mask)
    return 0o666 & ~mask


def _remove_quietly(path):
    try:
        os.remove(path)
    except OSError:
        pass


def _temp_file(directory, data, mode):
    os.makedirs(directory, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=directory, prefix='.skillsync-tmp-')
    try:
        with os.fdopen(fd, 'wb') as handle:
            handle.write(data)
            handle.flush()
            os.fsync(handle.fileno())
        os.chmod(tmp, mode)
    except BaseException:
        _remove_quietly(tmp)
        raise
    return tmp


def _make_backup(target, raw, mode):
    """Copy of the original next to the target, created atomically and never overwritten."""
    bak = target + BACKUP_SUFFIX
    if os.path.lexists(bak):
        return
    tmp = _temp_file(os.path.dirname(target), raw, mode)
    try:
        try:
            os.link(tmp, bak)
        except FileExistsError:
            pass
        except OSError:
            try:
                os.rename(tmp, bak)
            except FileExistsError:
                pass
    finally:
        _remove_quietly(tmp)


def write_file(target, data, backup=None):
    """Atomic write to `target` (already resolved); `backup` = original bytes to keep once, `None` = no backup."""
    try:
        mode = os.stat(target).st_mode & 0o7777
    except FileNotFoundError:
        mode = _default_mode()
    tmp = _temp_file(os.path.dirname(target), data, mode)
    try:
        if backup is not None:
            _make_backup(target, backup, mode)
        os.replace(tmp, target)
    except BaseException:
        _remove_quietly(tmp)
        raise


# -- the block in a startup file

def _split_bom(raw):
    return (BOM, raw[3:]) if raw.startswith(BOM) else (b'', raw)


def _dominant_eol(body, default):
    crlf = body.count(b'\r\n')
    lf = body.count(b'\n') - crlf
    if crlf == 0 and lf == 0:
        return default
    return b'\r\n' if crlf > lf else b'\n'


def _marker_matches(marker, body):
    return list(re.finditer(rb'(?m)^' + re.escape(marker) + rb'[ \t]*\r?$', body))


def _find_block(body):
    starts, ends = _marker_matches(START, body), _marker_matches(END, body)
    if not starts and not ends:
        return None
    if len(starts) != 1 or len(ends) != 1:
        raise ValueError(f'expected one skillsync completion block, found {len(starts)} start and {len(ends)} end markers; fix the file by hand')
    if ends[0].start() < starts[0].start():
        raise ValueError('the end marker of the skillsync completion block comes before its start marker; fix the file by hand')
    end = ends[0].end()
    if body[end:end + 1] == b'\n':
        end += 1
    return starts[0].start(), end


def _result(shell, path, result, detail=''):
    return {'shell': shell, 'path': path, 'result': result, 'detail': detail}


def install_block(shell, path, lines, is_ps, default_eol, dry):
    real = _real(path)
    raw = _read(real)
    if raw is None:
        bom, body, eol = (BOM if is_ps else b''), b'', default_eol
    else:
        bom, body = _split_bom(raw)
        eol = _dominant_eol(body, default_eol)
    try:
        found = _find_block(body)
    except ValueError as exc:
        return _result(shell, path, 'failed', str(exc))
    block = eol.join(lines) + eol
    if found:
        start, end = found
        if body[start:end].replace(b'\r\n', b'\n').rstrip(b'\n') == b'\n'.join(lines):
            return _result(shell, path, 'unchanged', 'block already present')
        new = body[:start] + block + body[end:]
    else:
        new = body + (eol if body and not body.endswith(b'\n') else b'') + block
    if is_ps and not bom and not block.isascii():
        return _result(shell, path, 'failed', 'the profile has no BOM and the block needs a non-ASCII path; Windows PowerShell 5.1 would misread it '
                                              '(save the profile as UTF-8 with BOM, or choose an ASCII data directory)')
    verb = 'create' if raw is None else 'update'
    if dry:
        return _result(shell, path, 'skipped', f'planned: {verb} {os.path.basename(path)} with the skillsync completion block')
    write_file(real, bom + new, backup=raw)
    return _result(shell, path, 'created' if raw is None else 'updated', 'block added' if not found else 'block replaced')


def remove_block(shell, path, dry):
    real = _real(path)
    raw = _read(real)
    if raw is None:
        return _result(shell, path, 'unchanged', 'file does not exist')
    bom, body = _split_bom(raw)
    try:
        found = _find_block(body)
    except ValueError as exc:
        return _result(shell, path, 'failed', str(exc))
    if not found:
        return _result(shell, path, 'unchanged', 'no block')
    start, end = found
    new_body = body[:start] + body[end:]
    original = _read(real + BACKUP_SUFFIX)
    candidate = bom + new_body
    if original is not None:
        for eol in (b'\r\n', b'\n'):
            if candidate.endswith(eol) and candidate[:-len(eol)] == original:
                candidate = original
                break
    if original is None and new_body == b'':
        if dry:
            return _result(shell, path, 'skipped', f'planned: remove {os.path.basename(path)} (only our block was in it)')
        os.remove(path)
        return _result(shell, path, 'removed', 'file removed (only our block was in it)')
    if dry:
        return _result(shell, path, 'skipped', f'planned: remove the skillsync completion block from {os.path.basename(path)}')
    write_file(real, candidate, backup=raw)
    return _result(shell, path, 'updated', 'block removed')


# -- our own files

def _is_ours(data, lines):
    _, body = _split_bom(data)
    return any(line.startswith(HEADER_PREFIX) for line in body.split(b'\n')[:lines])


def sync_file(shell, path, data, header_lines, dry):
    existing = _read(path)
    if existing == data:
        return _result(shell, path, 'unchanged', 'up to date')
    if existing is not None and not _is_ours(existing, header_lines):
        return _result(shell, path, 'failed', 'a file without the skillsync completion header is already there; left alone')
    verb = 'create' if existing is None else 'update'
    if dry:
        return _result(shell, path, 'skipped', f'planned: {verb} {path}')
    write_file(path, data)
    return _result(shell, path, 'created' if existing is None else 'updated', '')


def delete_file(shell, path, header_lines, dry):
    existing = _read(path)
    if existing is None:
        return _result(shell, path, 'unchanged', 'file does not exist')
    if not _is_ours(existing, header_lines):
        return _result(shell, path, 'failed', 'the file has no skillsync completion header (changed or not ours); left alone')
    if dry:
        return _result(shell, path, 'skipped', f'planned: remove {path}')
    os.remove(path)
    return _result(shell, path, 'removed', '')


def _remove_own_directories(script):
    inner = os.path.dirname(script)
    outer = os.path.dirname(inner)
    if os.path.basename(inner) == 'completion' and os.path.basename(outer) == 'skillsync':
        for directory in (inner, outer):
            try:
                os.rmdir(directory)
            except OSError:
                return


# -- PowerShell

def _control_free(text):
    return bool(text) and not any(ord(char) < 32 or ord(char) == 127 for char in text)


def query_profile(exe):
    """`$PROFILE.CurrentUserCurrentHost` of a host, or `None` when the answer is unusable."""
    try:
        proc = subprocess.run([exe, '-NoProfile', '-NonInteractive', '-Command', PS_QUERY], timeout=10, capture_output=True, text=True)
    except (OSError, subprocess.SubprocessError):
        return None
    answer = (proc.stdout or '').strip()
    if proc.returncode != 0 or not _control_free(answer):
        return None
    try:
        return _valid(answer, 'profile path')
    except Blocked:
        return None


def ps_profiles(targets, warnings):
    found = [(name, shutil.which(name)) for name in PS_HOSTS]
    found = [(name, exe) for name, exe in found if exe]
    candidates = []
    if found:
        for name, exe in found:
            answer = query_profile(exe)
            if answer is None:
                warnings.append(f'{name}: no usable answer for the profile path; using the default location')
                answer = targets.default_profile(name)
            candidates.append(answer)
    else:
        candidates = [targets.default_profile(name) for name in (PS_HOSTS if WIN else PS_HOSTS[:1])]
    unique = []
    for path in candidates:
        if os.path.normcase(path) not in [os.path.normcase(item) for item in unique]:
            unique.append(path)
    return unique


def _ps_literal(text):
    return "'" + text.replace("'", "''") + "'"


def _under(path, base):
    try:
        return os.path.normcase(os.path.commonpath([path, base])) == os.path.normcase(base)
    except ValueError:
        return False


def ps_script_expression(script, targets):
    bases = ([('$env:LOCALAPPDATA', targets.local)] if WIN else []) + [('$HOME', targets.home)]
    for variable, base in bases:
        if _under(script, base):
            rel = script[len(base):]
            if rel[:1] not in ('/', '\\'):
                rel = os.sep + rel
            if rel.isascii():
                return f'({variable} + {_ps_literal(rel)})'
    return _ps_literal(script)


def ps_block_lines(script, targets):
    expr = ps_script_expression(script, targets)
    return [START, f'if (Test-Path -LiteralPath {expr}) {{ . {expr} }}'.encode('utf-8'), END]


def zsh_block_lines(function_dir):
    quoted = sh_quote(function_dir)
    text = [START.decode(), f'fpath=({quoted} $fpath)', 'autoload -Uz _skillsync',
            'if (( $+functions[compdef] )); then compdef _skillsync skillsync; else autoload -Uz compinit && compinit -i; fi', END.decode()]
    return [line.encode('utf-8') for line in text]


# -- orchestration

def _switch_state(warnings):
    value = os.environ.get(ENV_SWITCH, '').strip().lower()
    if value in FALSE_VALUES:
        return False
    if value not in TRUE_VALUES:
        warnings.append(f'{ENV_SWITCH} has an unrecognised value {value!r}; treating it as set')
    return True


def _detect():
    found = [name for name in ('bash', 'zsh') if shutil.which(name)]
    if any(shutil.which(name) for name in PS_HOSTS):
        found.append('powershell')
    return found


def _guarded(function, shell, path, *args):
    try:
        return function(shell, path, *args)
    except OSError as exc:
        return _result(shell, path, 'failed', f'{type(exc).__name__}: {exc}')


def _install(shells, targets, subparsers, dry, warnings):
    actions = []
    for shell in shells:
        if shell == 'bash':
            actions.append(_guarded(sync_file, 'bash', targets.bash_file, render('bash', subparsers).encode('utf-8'), 1, dry))
        elif shell == 'zsh':
            actions.append(_guarded(sync_file, 'zsh', targets.zsh_file, render('zsh', subparsers).encode('utf-8'), 2, dry))
            actions.append(_guarded(install_block, 'zsh', targets.zshrc, zsh_block_lines(os.path.dirname(targets.zsh_file)), False, b'\n', dry))
        else:
            script = targets.ps_script
            data = BOM + render('powershell', subparsers).encode('utf-8')
            actions.append(_guarded(sync_file, 'powershell', script, data, 1, dry))
            lines = ps_block_lines(script, targets)
            default_eol = b'\r\n' if WIN else b'\n'
            for profile in ps_profiles(targets, warnings):
                actions.append(_guarded(install_block, 'powershell', profile, lines, True, default_eol, dry))
    return actions


def _uninstall(shells, targets, dry, warnings):
    actions = []
    for shell in shells:
        if shell == 'bash':
            actions.append(_guarded(delete_file, 'bash', targets.bash_file, 1, dry))
        elif shell == 'zsh':
            actions.append(_guarded(delete_file, 'zsh', targets.zsh_file, 2, dry))
            actions.append(_guarded(remove_block, 'zsh', targets.zshrc, dry))
        else:
            script = targets.ps_script
            removed = _guarded(delete_file, 'powershell', script, 1, dry)
            actions.append(removed)
            if removed['result'] == 'removed':
                _remove_own_directories(script)
            for profile in ps_profiles(targets, warnings):
                actions.append(_guarded(remove_block, 'powershell', profile, dry))
    return actions


def _validate(shells, targets):
    """Resolve every path the chosen shells need before the first write, so a bad variable blocks the whole run."""
    needed = {'bash': ('bash_file',), 'zsh': ('zsh_file', 'zshrc'), 'powershell': ('ps_script',)}
    for shell in shells:
        for name in needed[shell]:
            getattr(targets, name)


def _skipped_actions(shells, targets):
    paths = {'bash': lambda: targets.bash_file, 'zsh': lambda: targets.zsh_file, 'powershell': lambda: targets.ps_script}
    actions = []
    for shell in shells:
        try:
            path = paths[shell]()
        except Blocked:
            path = ''
        actions.append(_result(shell, path, 'skipped', f'{ENV_SWITCH} is set'))
    return actions


def _status(actions):
    if any(item['result'] == 'failed' for item in actions):
        return 'FAIL'
    return 'PASS' if actions else 'NOT_RUN'


def _report(status, dry, actions, warnings):
    return {'schema': SCHEMA, 'status': status, 'dry_run': dry, 'actions': actions, 'warnings': warnings}


def _emit(report, args, quiet):
    if args.json:
        print(json.dumps(report, indent=2))
        return
    if not quiet:
        for item in report['actions']:
            line = f"{item['shell']}: {item['result']}: {item['path']}" + (f" ({item['detail']})" if item['detail'] else '')
            print(line, file=sys.stderr if item['result'] == 'failed' else sys.stdout)
    for warning in report['warnings']:
        print(f'warning: {warning}', file=sys.stderr)


def run(args, operation, subparsers):
    warnings = []
    dry = bool(args.dry_run)
    auto = operation == 'install' and bool(getattr(args, 'auto', False))
    explicit = list(dict.fromkeys(args.shell or []))
    try:
        targets = Targets()
        if operation == 'uninstall':
            shells = explicit or list(SHELLS)
        else:
            shells = explicit or _detect()
        if auto and _switch_state(warnings):
            actions = _skipped_actions(shells, targets)
            report = _report('NOT_RUN', dry, actions, warnings)
            _emit(report, args, False)
            return 0
        if not shells:
            warnings.append('no supported shell (bash, zsh, pwsh, powershell) found on PATH; nothing to do')
            report = _report('NOT_RUN', dry, [], warnings)
            _emit(report, args, auto)
            return 0
        _validate(shells, targets)
        actions = _install(shells, targets, subparsers, dry, warnings) if operation == 'install' else _uninstall(shells, targets, dry, warnings)
    except Blocked as exc:
        _emit(_report('BLOCKED', dry, [], warnings + [str(exc)]), args, False)
        return 2
    report = _report(_status(actions), dry, actions, warnings)
    quiet = auto and all(item['result'] == 'unchanged' for item in actions)
    _emit(report, args, quiet)
    return 1 if report['status'] == 'FAIL' else 0
