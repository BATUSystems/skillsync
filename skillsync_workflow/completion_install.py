"""`skillsync completion install|uninstall`: put the generated completion scripts in the user's data directories (CORE-COMPLETION).

Our own files (bash script, zsh function, PowerShell script) are written whole; the user's startup files (`.zshrc`, the PowerShell profile) get exactly
one block between fixed markers. Startup files are read and written as bytes (line endings and BOM kept), written atomically (temp file in the directory
of the real target + `os.replace`; owner and extended attributes are carried over, a file with several hard links is written in place), checked once more
right before the write (a change made by someone else in between fails the action) and copied once to `<target>.skillsync-bak` before the first edit.
Exit codes: 0 PASS/NOT_RUN, 1 FAIL, 2 BLOCKED.
"""
import base64
import binascii
import json
import os
import re
import shutil
import stat
import subprocess
import sys
import tempfile

from .completion import SCHEMA, SHELLS, render, sh_quote

START = b'# >>> skillsync completion >>>'
END = b'# <<< skillsync completion <<<'
BOM = b'\xef\xbb\xbf'
HEADER_PREFIX = b'# skillsync completion (generated by skillsync '
BACKUP_SUFFIX = '.skillsync-bak'
PS_SCRIPT = 'skillsync-completion.ps1'
PS_PROFILE = 'profile.ps1'   # CurrentUserAllHosts: read by every host, also the console of the VS Code extension
ENV_SWITCH = 'SKILLSYNC_NO_COMPLETION'
TRUE_VALUES = ('1', 'true', 'yes', 'on')
FALSE_VALUES = ('0', 'false', 'no', 'off', '')
PS_HOSTS = ('pwsh', 'powershell')
# One call, two ASCII lines (so the code page of the host does not matter): the profile path as base64 of its UTF-8 bytes and the effective policy.
PS_QUERY = ("'P64:' + [Convert]::ToBase64String([Text.Encoding]::UTF8.GetBytes($PROFILE.CurrentUserAllHosts)); "
            "'POLICY:' + (Get-ExecutionPolicy)")
BLOCKING_POLICIES = ('restricted', 'allsigned')
POLICY_MARK = 'PowerShell ExecutionPolicy is '
POLICY_FIX = 'Set-ExecutionPolicy -Scope CurrentUser RemoteSigned'
WIN = sys.platform == 'win32'


class Blocked(Exception):
    pass


# -- paths

def _valid(value, label):
    if not value or any(ord(char) < 32 or ord(char) == 127 for char in value):
        raise Blocked(f'{label} is empty or contains control characters')
    if not os.path.isabs(value):
        raise Blocked(f'{label} is not an absolute path: {value!r}')
    if '..' in re.split(r'[\\/]', value):
        raise Blocked(f'{label} contains "..": {value!r}')
    return os.path.normpath(value)


def _home():
    """Windows: USERPROFILE first (as PowerShell and `expanduser` do), then HOME; elsewhere HOME, or the account's home when it is unset."""
    if WIN:
        for name in ('USERPROFILE', 'HOME'):
            if os.environ.get(name):
                return _valid(os.environ[name], name)
        raise Blocked('neither USERPROFILE nor HOME is set')
    if 'HOME' in os.environ:
        return _valid(os.environ['HOME'], 'HOME')
    return _valid(os.path.expanduser('~'), 'HOME')


def _optional(name):
    value = os.environ.get(name)
    return _valid(value, name) if value else None


class Targets:
    """Destination paths, validated lazily so that only the variables a chosen shell needs can block."""

    def __init__(self):
        self.home = _home()

    @property
    def xdg(self):
        return _optional('XDG_DATA_HOME') or os.path.join(self.home, '.local', 'share')

    @property
    def bash_file(self):
        return os.path.join(self.xdg, 'bash-completion', 'completions', 'skillsync')

    @property
    def zsh_file(self):
        return os.path.join(self.xdg, 'zsh', 'site-functions', '_skillsync')

    @property
    def zshrc(self):
        return os.path.join(_optional('ZDOTDIR') or self.home, '.zshrc')

    @property
    def local(self):
        return _optional('LOCALAPPDATA') or os.path.join(self.home, 'AppData', 'Local')

    @property
    def config(self):
        return _optional('XDG_CONFIG_HOME') or os.path.join(self.home, '.config')

    @property
    def ps_script(self):
        return os.path.join(self.local if WIN else self.xdg, 'skillsync', 'completion', PS_SCRIPT)

    def default_profile(self, host):
        if WIN:
            return os.path.join(self.home, 'Documents', 'PowerShell' if host == 'pwsh' else 'WindowsPowerShell', PS_PROFILE)
        return os.path.join(self.config, 'powershell', PS_PROFILE)


# -- bytes and atomic writes

class Changed(OSError):
    """The target was changed by someone else between our read and our write."""


def _snapshot(path):
    """`(bytes, (size, mtime_ns))` of a file read in one go, `(None, None)` when it does not exist."""
    try:
        with open(path, 'rb') as handle:
            info = os.fstat(handle.fileno())
            return handle.read(), (info.st_size, info.st_mtime_ns)
    except FileNotFoundError:
        return None, None


def _read(path):
    return _snapshot(path)[0]


def _real(path):
    return os.path.realpath(path)


def _dangling(path):
    return os.path.islink(path) and not os.path.exists(path)


def _default_mode():
    mask = os.umask(0)
    os.umask(mask)
    return 0o666 & ~mask


def _remove_quietly(path):
    try:
        os.remove(path)
    except OSError:
        pass


def _temp_file(directory, data, mode):
    os.makedirs(directory, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=directory, prefix='.skillsync-tmp-')
    try:
        with os.fdopen(fd, 'wb') as handle:
            handle.write(data)
            handle.flush()
            os.fsync(handle.fileno())
        os.chmod(tmp, mode)
    except BaseException:
        _remove_quietly(tmp)
        raise
    return tmp


def _make_backup(target, raw, mode):
    """Copy of the original next to the target, created atomically and never overwritten."""
    bak = target + BACKUP_SUFFIX
    if os.path.lexists(bak):
        return
    tmp = _temp_file(os.path.dirname(target), raw, mode)
    try:
        try:
            os.link(tmp, bak)
        except FileExistsError:
            pass
        except OSError:
            try:
                os.rename(tmp, bak)
            except FileExistsError:
                pass
    finally:
        _remove_quietly(tmp)


def _check_unchanged(target, expect):
    """`expect` = what the caller read at the start (`(bytes, (size, mtime_ns))`); any difference now means somebody else wrote the file."""
    if expect is None:
        return
    raw, signature = expect
    now_raw, now_signature = _snapshot(target)
    if now_raw != raw or now_signature != signature:
        raise Changed(f'{target} changed during the operation, run it again')


def _carry_attributes(target, tmp, info, mode):
    """The replacement keeps the owner and the extended attributes of the file it replaces (best effort; failures are ignored)."""
    if info is None:
        return
    try:
        now = os.stat(tmp)
        if hasattr(os, 'chown') and (now.st_uid, now.st_gid) != (info.st_uid, info.st_gid):
            os.chown(tmp, info.st_uid, info.st_gid)
    except OSError:
        pass
    try:
        names = list(os.listxattr(target))
    except (AttributeError, OSError):
        names = []
    for name in names:
        try:
            os.setxattr(tmp, name, os.getxattr(target, name))
        except (AttributeError, OSError):
            pass
    try:
        os.chmod(tmp, mode)   # changing the owner can clear the set-id bits
    except OSError:
        pass


def _write_in_place(target, data):
    with open(target, 'r+b') as handle:
        handle.write(data)
        handle.truncate()
        handle.flush()
        os.fsync(handle.fileno())


def write_file(target, data, backup=None, expect=None):
    """Atomic write to `target` (already resolved); `backup` = original bytes to keep once, `None` = no backup; `expect` = the snapshot read at the start."""
    try:
        info = os.stat(target)
    except FileNotFoundError:
        info = None
        mode = _default_mode()
    else:
        mode = info.st_mode & 0o7777
        readonly = bool(getattr(info, 'st_file_attributes', 0) & getattr(stat, 'FILE_ATTRIBUTE_READONLY', 0))
        if readonly or not os.access(target, os.W_OK):
            raise PermissionError(f'{target} is read-only (for example a store of a dotfiles manager); nothing was changed')
    in_place = info is not None and getattr(info, 'st_nlink', 1) > 1   # a rename would cut the other hard links off
    tmp = None if in_place else _temp_file(os.path.dirname(target), data, mode)
    try:
        _check_unchanged(target, expect)
        if backup is not None:
            _make_backup(target, backup, mode)
        _check_unchanged(target, expect)
        if in_place:
            _write_in_place(target, data)
        else:
            _carry_attributes(target, tmp, info, mode)
            os.replace(tmp, target)
    except BaseException:
        if tmp:
            _remove_quietly(tmp)
        raise


# -- the block in a startup file

def _unsupported_encoding(raw):
    """Message when the file is not a byte-oriented (ASCII/UTF-8/ANSI) text: UTF-16/32 or NUL bytes. Appending UTF-8 text would corrupt it."""
    if raw.startswith((b'\xff\xfe', b'\xfe\xff', b'\x00\x00\xfe\xff')):
        return 'the file starts with a UTF-16 or UTF-32 byte order mark; it is not edited (save it as UTF-8 and run the command again)'
    if b'\x00' in raw:
        return 'the file contains NUL bytes (UTF-16/32 text or binary data); it is not edited (save it as UTF-8 and run the command again)'
    return None


def _split_bom(raw):
    return (BOM, raw[3:]) if raw.startswith(BOM) else (b'', raw)


def _dominant_eol(body, default):
    crlf = body.count(b'\r\n')
    lf = body.count(b'\n') - crlf
    if crlf == 0 and lf == 0:
        return default
    return b'\r\n' if crlf > lf else b'\n'


def _marker_matches(marker, body):
    return list(re.finditer(rb'(?m)^' + re.escape(marker) + rb'[ \t]*\r?$', body))


def _find_block(body):
    starts, ends = _marker_matches(START, body), _marker_matches(END, body)
    if not starts and not ends:
        return None
    if len(starts) != 1 or len(ends) != 1:
        raise ValueError(f'expected one skillsync completion block, found {len(starts)} start and {len(ends)} end markers; fix the file by hand')
    if ends[0].start() < starts[0].start():
        raise ValueError('the end marker of the skillsync completion block comes before its start marker; fix the file by hand')
    end = ends[0].end()
    if body[end:end + 1] == b'\n':
        end += 1
    return starts[0].start(), end


def _result(shell, path, result, detail=''):
    return {'shell': shell, 'path': path, 'result': result, 'detail': detail}


def _outside_block(body, found):
    return body[:found[0]] + body[found[1]:] if found else body


def install_block(shell, path, lines, is_ps, default_eol, dry):
    """`lines` is the block or, for a block that depends on the rest of the file, a function of the bytes outside the block."""
    if _dangling(path):
        return _result(shell, path, 'failed', 'the file is a dangling symbolic link (its target does not exist); nothing was created, fix the link and run the command again')
    real = _real(path)
    raw, signature = _snapshot(real)
    problem = _unsupported_encoding(raw) if raw is not None else None
    if problem:
        return _result(shell, path, 'failed', problem)
    if raw is None:
        bom, body, eol = (BOM if is_ps else b''), b'', default_eol
    else:
        bom, body = _split_bom(raw)
        eol = _dominant_eol(body, default_eol)
    try:
        found = _find_block(body)
    except ValueError as exc:
        return _result(shell, path, 'failed', str(exc))
    if callable(lines):
        lines = lines(_outside_block(body, found))
    block = eol.join(lines) + eol
    if found:
        start, end = found
        if body[start:end].replace(b'\r\n', b'\n').rstrip(b'\n') == b'\n'.join(lines):
            return _result(shell, path, 'unchanged', 'block already present')
        new = body[:start] + block + body[end:]
    else:
        new = body + (eol if body and not body.endswith(b'\n') else b'') + block
    if is_ps and not bom and not block.isascii():
        return _result(shell, path, 'failed', 'the profile has no BOM and the block needs a non-ASCII path; Windows PowerShell 5.1 would misread it '
                                              '(save the profile as UTF-8 with BOM, or choose an ASCII data directory)')
    verb = 'create' if raw is None else 'update'
    if dry:
        return _result(shell, path, 'skipped', f'planned: {verb} {os.path.basename(path)} with the skillsync completion block')
    write_file(real, bom + new, backup=raw, expect=(raw, signature))
    return _result(shell, path, 'created' if raw is None else 'updated', 'block added' if not found else 'block replaced')


def remove_block(shell, path, dry):
    real = _real(path)
    raw, signature = _snapshot(real)
    if raw is None:
        return _result(shell, path, 'unchanged', 'the file is a dangling symbolic link; left alone' if _dangling(path) else 'file does not exist')
    problem = _unsupported_encoding(raw)
    if problem:
        return _result(shell, path, 'failed', problem)
    bom, body = _split_bom(raw)
    try:
        found = _find_block(body)
    except ValueError as exc:
        return _result(shell, path, 'failed', str(exc))
    if not found:
        return _result(shell, path, 'unchanged', 'no block')
    start, end = found
    new_body = body[:start] + body[end:]
    original = _read(real + BACKUP_SUFFIX)
    candidate = bom + new_body
    if original is not None:
        for eol in (b'\r\n', b'\n'):
            if candidate.endswith(eol) and candidate[:-len(eol)] == original:
                candidate = original
                break
    if original is None and new_body == b'':
        if dry:
            return _result(shell, path, 'skipped', f'planned: remove {os.path.basename(path)} (only our block was in it)')
        os.remove(real)   # the file we created; a symlink the user put at `path` stays
        return _result(shell, path, 'removed', 'file removed (only our block was in it)')
    if dry:
        return _result(shell, path, 'skipped', f'planned: remove the skillsync completion block from {os.path.basename(path)}')
    write_file(real, candidate, backup=raw, expect=(raw, signature))
    return _result(shell, path, 'updated', 'block removed')


# -- our own files

def _is_ours(data, lines):
    _, body = _split_bom(data)
    return any(line.startswith(HEADER_PREFIX) for line in body.split(b'\n')[:lines])


def sync_file(shell, path, data, header_lines, dry):
    existing = _read(path)
    if existing == data:
        return _result(shell, path, 'unchanged', 'up to date')
    if existing is not None and not _is_ours(existing, header_lines):
        return _result(shell, path, 'failed', 'a file without the skillsync completion header is already there; left alone')
    verb = 'create' if existing is None else 'update'
    if dry:
        return _result(shell, path, 'skipped', f'planned: {verb} {path}')
    write_file(path, data)
    return _result(shell, path, 'created' if existing is None else 'updated', '')


def delete_file(shell, path, header_lines, dry):
    existing = _read(path)
    if existing is None:
        return _result(shell, path, 'unchanged', 'file does not exist')
    if not _is_ours(existing, header_lines):
        return _result(shell, path, 'failed', 'the file has no skillsync completion header (changed or not ours); left alone')
    if dry:
        return _result(shell, path, 'skipped', f'planned: remove {path}')
    os.remove(path)
    return _result(shell, path, 'removed', '')


def _remove_own_directories(script):
    inner = os.path.dirname(script)
    outer = os.path.dirname(inner)
    if os.path.basename(inner) == 'completion' and os.path.basename(outer) == 'skillsync':
        for directory in (inner, outer):
            try:
                os.rmdir(directory)
            except OSError:
                return


# -- PowerShell

def query_host(exe):
    """Ask a PowerShell host for its profile path and effective execution policy: `(profile, policy, problem)`.

    `problem` is a reason (text) when the profile path cannot be used; `policy` is `None` when the host did not say."""
    try:
        proc = subprocess.run([exe, '-NoProfile', '-NonInteractive', '-Command', PS_QUERY], timeout=10, capture_output=True,
                              stdin=subprocess.DEVNULL)
    except subprocess.TimeoutExpired:
        return None, None, 'the host did not answer within 10 seconds'
    except (OSError, subprocess.SubprocessError) as exc:
        return None, None, f'the host could not be run ({type(exc).__name__})'
    if proc.returncode != 0:
        return None, None, f'the host exited with code {proc.returncode}'
    encoded = legacy = policy = None
    for raw_line in (proc.stdout or b'').splitlines():
        try:
            line = raw_line.decode('utf-8').strip()
        except UnicodeDecodeError:
            continue
        if line.startswith('P64:'):
            encoded = encoded if encoded is not None else line[4:]
        elif line.startswith('POLICY:'):
            policy = policy if policy is not None else line[7:].strip()
        elif legacy is None and os.path.isabs(line):
            legacy = line
    if encoded is not None:
        try:
            answer = base64.b64decode(encoded, validate=True).decode('utf-8')
        except (binascii.Error, ValueError):   # UnicodeDecodeError is a ValueError
            return None, policy, 'the profile path in the answer cannot be decoded'
    else:
        answer = legacy
    if not answer:
        return None, policy, 'the answer has no profile path'
    try:
        return _valid(answer, 'profile path'), policy, None
    except Blocked as exc:
        return None, policy, str(exc)


def _unique(paths):
    unique = []
    for path in paths:
        if os.path.normcase(path) not in [os.path.normcase(item) for item in unique]:
            unique.append(path)
    return unique


def ps_plan(targets, warnings, install, auto):
    """What to do for PowerShell: a list of `(path, skip_reason, is_policy)`; `skip_reason` is `None` for a profile to work on.

    Hosts on PATH answer for themselves; a host without a usable answer is skipped (no guessing), and so is a host whose execution policy blocks
    scripts (`install` only). The default locations are used only when no host is on PATH."""
    found = [(name, shutil.which(name)) for name in PS_HOSTS]
    found = [(name, exe) for name, exe in found if exe]
    if not found:
        return [(path, None, False) for path in _unique(targets.default_profile(name) for name in (PS_HOSTS if WIN else PS_HOSTS[:1]))]
    plan, seen = [], []
    for name, exe in found:
        profile, policy, problem = query_host(exe)
        if problem:
            warnings.append(f'{name}: no usable answer for the profile path ({problem}); the host was skipped and nothing was changed for it')
            plan.append((exe, f'no usable answer for the profile path ({problem}); the host was skipped', False))
        elif install and policy and policy.lower() in BLOCKING_POLICIES:
            reason = (f'{POLICY_MARK}{policy}, so a profile script would not load; nothing was written for {name}. '
                      f'Run "{POLICY_FIX}" in PowerShell (the policy is not changed for you), then run `skillsync completion install`')
            if not auto:
                warnings.append(f'{name}: {reason}')
            plan.append((profile, reason, True))
        elif os.path.normcase(profile) in seen:
            continue
        else:
            seen.append(os.path.normcase(profile))
            plan.append((profile, None, False))
    return plan


def _is_policy_skip(item):
    return item['result'] == 'skipped' and item['detail'].startswith(POLICY_MARK)


PS_QUOTES = "'\u2018\u2019\u201a\u201b"   # PowerShell reads all of these as a single quote inside '...'


def _ps_literal(text):
    return "'" + ''.join(char + char if char in PS_QUOTES else char for char in text) + "'"


def _under(path, base):
    try:
        return os.path.normcase(os.path.commonpath([path, base])) == os.path.normcase(base)
    except ValueError:
        return False


def ps_script_expression(script, targets):
    bases = ([('$env:LOCALAPPDATA', targets.local)] if WIN else []) + [('$HOME', targets.home)]
    for variable, base in bases:
        if _under(script, base):
            rel = script[len(base):]
            if rel[:1] not in ('/', '\\'):
                rel = os.sep + rel
            if rel.isascii():
                return f'({variable} + {_ps_literal(rel)})'
    return _ps_literal(script)


def ps_block_lines(script, targets):
    expr = ps_script_expression(script, targets)
    return [START, f'if (Test-Path -LiteralPath {expr}) {{ . {expr} }}'.encode('utf-8'), END]


ZSH_FRAMEWORKS = re.compile(rb'oh-my-zsh|zinit|antidote|zplug|prezto', re.IGNORECASE)
ZSH_COMPINIT = re.compile(rb'(?<!\w)compinit(?!\w)')


def zsh_calls_compinit_elsewhere(outside):
    """The rest of the startup file runs `compinit` itself (or a plugin manager does): the block must not call it a second time."""
    return bool(ZSH_COMPINIT.search(outside) or ZSH_FRAMEWORKS.search(outside))


def zsh_block_lines(function_dir, outside=b''):
    """Variant A (the file or a framework runs `compinit`, possibly later): register only. Variant B: also run `compinit -i` when nobody did."""
    quoted = sh_quote(function_dir)
    if zsh_calls_compinit_elsewhere(outside):
        text = [START.decode(), f'fpath=({quoted} $fpath)', 'autoload -Uz _skillsync', '(( $+functions[compdef] )) && compdef _skillsync skillsync', END.decode()]
    else:
        text = [START.decode(), f'fpath=({quoted} $fpath)', 'autoload -Uz _skillsync',
                'if (( $+functions[compdef] )); then compdef _skillsync skillsync; else autoload -Uz compinit && compinit -i; fi', END.decode()]
    return [line.encode('utf-8') for line in text]


# -- orchestration

def _switch_state(warnings):
    value = os.environ.get(ENV_SWITCH, '').strip().lower()
    if value in FALSE_VALUES:
        return False
    if value not in TRUE_VALUES:
        warnings.append(f'{ENV_SWITCH} has an unrecognised value {value!r}; treating it as set')
    return True


def _detect():
    found = [name for name in ('bash', 'zsh') if shutil.which(name)]
    if any(shutil.which(name) for name in PS_HOSTS):
        found.append('powershell')
    return found


def _guarded(function, shell, path, *args):
    try:
        return function(shell, path, *args)
    except Changed as exc:
        return _result(shell, path, 'failed', str(exc))
    except OSError as exc:
        return _result(shell, path, 'failed', f'{type(exc).__name__}: {exc}')


def _install(shells, targets, subparsers, dry, warnings, auto=False):
    actions = []
    for shell in shells:
        if shell == 'bash':
            actions.append(_guarded(sync_file, 'bash', targets.bash_file, render('bash', subparsers).encode('utf-8'), 1, dry))
        elif shell == 'zsh':
            actions.append(_guarded(sync_file, 'zsh', targets.zsh_file, render('zsh', subparsers).encode('utf-8'), 2, dry))
            function_dir = os.path.dirname(targets.zsh_file)
            actions.append(_guarded(install_block, 'zsh', targets.zshrc, lambda outside: zsh_block_lines(function_dir, outside), False, b'\n', dry))
        else:
            script = targets.ps_script
            plan = ps_plan(targets, warnings, True, auto)
            if any(reason is None for _, reason, _ in plan):
                data = BOM + render('powershell', subparsers).encode('utf-8')
                actions.append(_guarded(sync_file, 'powershell', script, data, 1, dry))
            lines = ps_block_lines(script, targets)
            default_eol = b'\r\n' if WIN else b'\n'
            for profile, reason, _ in plan:
                if reason is None:
                    actions.append(_guarded(install_block, 'powershell', profile, lines, True, default_eol, dry))
                else:
                    actions.append(_result('powershell', profile, 'skipped', reason))
    return actions


def _uninstall(shells, targets, dry, warnings):
    actions = []
    for shell in shells:
        if shell == 'bash':
            actions.append(_guarded(delete_file, 'bash', targets.bash_file, 1, dry))
        elif shell == 'zsh':
            actions.append(_guarded(delete_file, 'zsh', targets.zsh_file, 2, dry))
            actions.append(_guarded(remove_block, 'zsh', targets.zshrc, dry))
        else:
            script = targets.ps_script
            removed = _guarded(delete_file, 'powershell', script, 1, dry)
            actions.append(removed)
            if removed['result'] == 'removed':
                _remove_own_directories(script)
            for profile, reason, _ in ps_plan(targets, warnings, False, False):
                actions.append(_guarded(remove_block, 'powershell', profile, dry) if reason is None else _result('powershell', profile, 'skipped', reason))
    return actions


def _validate(shells, targets):
    """Resolve every path the chosen shells need before the first write, so a bad variable blocks the whole run."""
    needed = {'bash': ('bash_file',), 'zsh': ('zsh_file', 'zshrc'), 'powershell': ('ps_script',) if WIN else ('ps_script', 'config')}
    for shell in shells:
        for name in needed[shell]:
            getattr(targets, name)


def _skipped_actions(shells):
    """One `skipped` action per shell for the switch; paths are informational, so an invalid variable only leaves the path empty."""
    try:
        targets = Targets()
    except Blocked:
        targets = None
    paths = {'bash': lambda: targets.bash_file, 'zsh': lambda: targets.zsh_file, 'powershell': lambda: targets.ps_script}
    actions = []
    for shell in shells:
        try:
            path = paths[shell]() if targets else ''
        except Blocked:
            path = ''
        actions.append(_result(shell, path, 'skipped', f'{ENV_SWITCH} is set'))
    return actions


def _status(actions):
    if any(item['result'] == 'failed' for item in actions):
        return 'FAIL'
    return 'PASS' if actions else 'NOT_RUN'


def _report(status, dry, actions, warnings):
    return {'schema': SCHEMA, 'status': status, 'dry_run': dry, 'actions': actions, 'warnings': warnings}


def _emit(report, args, quiet):
    if args.json:
        print(json.dumps(report, indent=2))
        return
    if quiet:   # nothing changed; only the PowerShell policy note is worth a line, because it tells what to do
        shown = [item for item in report['actions'] if _is_policy_skip(item)]
    else:
        shown = report['actions']
    for item in shown:
        line = f"{item['shell']}: {item['result']}: {item['path']}" + (f" ({item['detail']})" if item['detail'] else '')
        print(line, file=sys.stderr if item['result'] == 'failed' else sys.stdout)
    for warning in report['warnings']:
        print(f'warning: {warning}', file=sys.stderr)


def install_for_setup(subparsers, dry):
    """The `completion` step of `skillsync setup`: `(result, detail, warnings)` with result in `done|unchanged|planned|skipped`.
    Never raises and never blocks: a failure is `skipped` plus a warning (K13)."""
    if subparsers is None:
        return 'skipped', 'no parser: the command tree is not available', []
    warnings = []
    try:
        if _switch_state(warnings):
            return 'skipped', f'{ENV_SWITCH} is set', warnings
        targets = Targets()
        shells = _detect()
        if not shells:
            return 'skipped', 'no supported shell (bash, zsh, pwsh, powershell) found on PATH', warnings
        _validate(shells, targets)
        actions = _install(shells, targets, subparsers, dry, warnings, auto=True)
    except Exception as exc:   # completion must never fail the machine setup
        warnings.append(f'shell completion was not installed: {exc}; run `skillsync completion install` later')
        return 'skipped', 'installation failed (see warnings)', warnings
    failed = [item for item in actions if item['result'] == 'failed']
    if failed:
        warnings.extend(f"shell completion ({item['shell']}) failed: {item['detail']}; run `skillsync completion install` later" for item in failed)
        return 'skipped', 'installation failed (see warnings)', warnings
    active = [item for item in actions if item['result'] != 'skipped' or item['detail'].startswith('planned:')]
    policy = next((item['detail'] for item in actions if _is_policy_skip(item)), None)
    names = ', '.join(dict.fromkeys(item['shell'] for item in active))
    if not active:
        return 'skipped', policy or 'no usable PowerShell profile (see warnings)', warnings
    note = f'; {policy}' if policy else ''
    if dry:
        return 'planned', f'would install completion for {names}{note}', warnings
    if all(item['result'] == 'unchanged' for item in active):
        return 'unchanged', f'completion is already installed for {names}{note}', warnings
    return 'done', f'completion installed for {names}{note}', warnings


def run(args, operation, subparsers):
    warnings = []
    dry = bool(args.dry_run)
    auto = operation == 'install' and bool(getattr(args, 'auto', False))
    explicit = list(dict.fromkeys(args.shell or []))
    if auto and _switch_state(warnings):   # decided before any path is computed: a bad HOME must not block a disabled feature
        report = _report('NOT_RUN', dry, _skipped_actions(explicit or _detect()), warnings)
        _emit(report, args, False)
        return 0
    try:
        targets = Targets()
        shells = explicit or (list(SHELLS) if operation == 'uninstall' else _detect())
        if not shells:
            warnings.append('no supported shell (bash, zsh, pwsh, powershell) found on PATH; nothing to do')
            report = _report('NOT_RUN', dry, [], warnings)
            _emit(report, args, auto)
            return 0
        _validate(shells, targets)
        actions = _install(shells, targets, subparsers, dry, warnings, auto) if operation == 'install' else _uninstall(shells, targets, dry, warnings)
    except Blocked as exc:
        _emit(_report('BLOCKED', dry, [], warnings + [str(exc)]), args, False)
        return 2
    report = _report(_status(actions), dry, actions, warnings)
    quiet = auto and all(item['result'] == 'unchanged' or _is_policy_skip(item) for item in actions)
    _emit(report, args, quiet)
    return 1 if report['status'] == 'FAIL' else 0
