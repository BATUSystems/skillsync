def remove_template_notices(html, icons=True):
    """`(html, kinds)`: removes the two recognised notice comments of an old template: `template-adaptation` (inside
    `<head>`, text starting with the adaptation prefix) and, when `icons`, `icon-license` (text starting with the icon
    licence prefix, anywhere). A comment that fills whole lines goes with its indentation and line end; otherwise
    only the comment goes. Other comments and the rest of the file stay byte for byte."""
    head = _HEAD_OPEN.search(html)
    head_close = _HEAD_CLOSE.search(html, head.end()) if head else None
    head_span = (head.end(), head_close.start() if head_close else len(html)) if head else None
    spans, kinds = [], []
    for match in _COMMENT_SPAN.finditer(html):
        text = match.group('text').lstrip()
        kind = None
        if text.startswith(_NOTICE_ADAPTATION[1]) and head_span and head_span[0] <= match.start() < head_span[1]:
            kind = _NOTICE_ADAPTATION[0]
        elif icons and text.startswith(_NOTICE_ICON_LICENSE[1]):
            kind = _NOTICE_ICON_LICENSE[0]
        if kind is None:
            continue
        start, end = match.start(), match.end()
        line_start = html.rfind('\n', 0, start) + 1
        line_end = html.find('\n', end)
        before, after = html[line_start:start], html[end:line_end if line_end >= 0 else len(html)]
        if not before.strip(' \t') and not after.strip(' \t\r') and line_end >= 0:
            start, end = line_start, line_end + 1
        spans.append((start, end))
        if kind not in kinds:
            kinds.append(kind)
    for start, end in reversed(spans):
        html = html[:start] + html[end:]
    return html, kinds


# The icon licence line the old template wrote into `README.md` (one fixed sentence, optionally a list item) and any
# other mention of the old icon library, which is only reported: free text written by the author is not changed.
_ICON_LIBRARY = 'lu' + 'cide'
_README_ICON_LICENSE = re.compile(
    r"^[ \t]*(?:[-*][ \t]+)?Ikony pochodzą z osadzonego sprite['’]a SVG \(" + _ICON_LIBRARY + r"\b[^\n]*(?:\n|$)",
    re.MULTILINE | re.IGNORECASE)


def remove_readme_notices(text, icons=True):
    """`(text, kinds, found)`: when `icons`, removes the whole fixed icon licence line of the old template
    (`readme-icon-license`); `found` lists 1-based line numbers of the remaining lines that still name the old icon
    library, for a manual review. The rest of the file stays byte for byte."""
    kinds = []
    if icons:
        text, count = _README_ICON_LICENSE.subn('', text)
        if count:
            kinds.append('readme-icon-license')
    found = [number for number, line in enumerate(text.split('\n'), 1) if _ICON_LIBRARY in line.lower()]
    return text, kinds, found


_LINK_TAG = re.compile(r'<link(?=[\s/>])(?:"[^"]*"|\'[^\']*\'|[^>"\'])*>', re.IGNORECASE)


def _link_attributes(tag):
    """`(relative path of a local href or None, True for rel containing "stylesheet")` of a `<link>` tag; an href with a
    scheme, `//` or a leading `/` is not a file of the prototype (None)."""
    name, sheet = None, False
    for attribute in _ATTRIBUTE.finditer(tag[5:]):
        key = attribute.group(1).lower()
        value = next((v for v in attribute.groups()[1:] if v is not None), '')
        if key == 'href':
            path = value.split('#', 1)[0].split('?', 1)[0].strip()
            while path.startswith('./'):
                path = path[2:]
            name = None if (':' in path or path.startswith('/')) else path
        elif key == 'rel':
            sheet = 'stylesheet' in value.lower().split()
    return name, sheet


def add_project_css_link(html):
    """`(html, status)`: puts `<link rel="stylesheet" href="project.css">` in `<head>` right after the LAST stylesheet
    link (own line with the same indentation when that link has its own line), so `project.css` is the last sheet;
    without any stylesheet link before `</head>`. Status `added`, `present` (a link to `project.css` exists) or
    `no_head` (text unchanged)."""
    head = _HEAD_OPEN.search(html)
    if not head:
        return html, 'no_head'
    close = _HEAD_CLOSE.search(html, head.end())
    end = close.start() if close else len(html)
    masked = _mask_comments(html)
    links = [(match, _link_attributes(match.group(0))) for match in _LINK_TAG.finditer(masked, head.end(), end)]
    if any(attributes[0] == PROJECT_CSS for _, attributes in links):
        return html, 'present'
    after = next((match.end() for match, attributes in reversed(links) if attributes[1]), None)
    newline = '\r\n' if '\r\n' in html else '\n'
    if after is not None:
        line_start = html.rfind('\n', 0, after) + 1
        indent = re.match(r'[ \t]*', html[line_start:after]).group(0)
        text = (newline + indent + PROJECT_CSS_LINK) if html[line_start:after].strip(' \t') else PROJECT_CSS_LINK
        return html[:after] + text + html[after:], 'added'
    return html[:end] + '  ' + PROJECT_CSS_LINK + newline + html[end:], 'added'


_CSS_PRELUDE = re.compile(r'([^{}]*)\{')
_CSS_CLASS = re.compile(r'\.(-?[_a-zA-Z][\w-]*)')


def css_selector_classes(css):
    """Set of class names used in the selectors (rule preludes) of `css`; comments, strings and `[…]` are ignored."""
    classes = set()
    for match in _CSS_PRELUDE.finditer(strip_css_comments(css)):
        prelude = re.sub(r'"[^"]*"|\'[^\']*\'|\[[^\]]*\]', '', match.group(1))
        classes.update(_CSS_CLASS.findall(prelude))
    return classes


def _stage_for_hashes(directory, replacements, index_text):
    """Temporary copy of the hashed files of the prototype (asset files and `index.html`) with the planned
    changes applied (`replacements`: {relative name: bytes}); the caller removes it. Used to compute screen hashes
    after a migration without writing anything (also for `--dry-run`)."""
    stage = Path(tempfile.mkdtemp(prefix='skillsync-migrate-'))
    try:
        for relative in server.asset_files(str(directory)):
            target = stage.joinpath(*relative.split('/'))
            target.parent.mkdir(parents=True, exist_ok=True)
            source = Path(directory).joinpath(*relative.split('/'))
            try:
                os.link(source, target)
            except OSError:
                shutil.copyfile(source, target)
        for name, data in replacements.items():
            if os.path.lexists(stage / name):
                os.unlink(stage / name)   # may be a hard link to the prototype file
            (stage / name).write_bytes(data)
        (stage / 'index.html').write_bytes(index_text.encode('utf-8', 'surrogateescape'))
    except BaseException:
        shutil.rmtree(stage, ignore_errors=True)
        raise
    return stage


def _classes_lost_from(old, library_css, project_css):
    """Sorted classes used by the selectors of the old `screens.css` (bytes) and absent from every CSS file of the
    library (`library_css`: list of bytes: engine stylesheets and the default theme) and from the project's
    `project.css` (when it exists)."""
    classes = css_selector_classes(old.decode('utf-8', 'replace'))
    for data in library_css:
        if not classes:
            return []
        classes -= css_selector_classes(data.decode('utf-8', 'replace'))
    if classes:
        data, _ = read_regular_bytes(project_css, MAX_COMMENTS_READ)
        if data is not None:
            classes -= css_selector_classes(data.decode('utf-8', 'replace'))
    return sorted(classes)


def _acceptance_lost(directory, slug, hashes_before, paths, final_html, warnings, extra_files=None):
    """`{lost, screens}`: screens whose acceptance (`comments.json`) is valid before the migration and stale after it.

    The hashes after come from a temporary copy with the library engine files and the final `index.html`
    (`assets_hash` leaves out `prototype.js` and `index.html`, the head and the section still count), so the
    result is the same with and without `--dry-run`."""
    empty = {'lost': 0, 'screens': []}
    if hashes_before is None or not os.path.lexists(directory / server.COMMENTS_FILE):
        return empty
    data, reason = read_regular_bytes(directory / server.COMMENTS_FILE, MAX_COMMENTS_READ)
    if data is None:
        warnings.append(f'acceptance: comments.json: {reason}')
        return empty
    try:
        fold = server.fold_operations(server.parse_document(data.decode('utf-8'), slug).operations)
    except (UnicodeDecodeError, server.CommentsFileError):
        warnings.append('acceptance: comments.json unreadable, stale acceptances not counted')
        return empty
    valid = [screen for screen, entry in fold['acceptance'].items() if hashes_before.get(screen) == entry['hash']]
    if not valid:
        return empty
    stage = None
    try:
        replacements = {name: paths[f'repo/{name}'].read_bytes() for name in STATIC_FILES}
        replacements.update(extra_files or {})
        stage = _stage_for_hashes(directory, replacements, final_html)
        after = server.screen_hashes(str(stage))['screens']
    except OSError as error:
        warnings.append(f'acceptance: hashes after migration not computed ({error})')
        return empty
    finally:
        if stage is not None:
            shutil.rmtree(stage, ignore_errors=True)
    lost = sorted(screen for screen in valid if after.get(screen) != fold['acceptance'][screen]['hash'])
    return {'lost': len(lost), 'screens': lost}


def migrate_prototype(root, manifest, layerset, slug, dry_run=False, assets=None, allow_skipped=False):
    """`migrate`: v1 → v2 in the order of the spec ("Migracja"), every step idempotent.

    1 read `comments.js` (C1-U1a), 2 `ids --fix`, 3 convert operations with v1 anchors,
    4 write `comments.json` — steps 1-4 are skipped when `comments.json` exists
    (`already_migrated`); 5 copy the v2 engine and drop `<script src="comments.js">`,
    6 delete `comments.js`, complete `.gitignore` and `.gitattributes` of the prototype.
    The conversion runs before any write: when an operation cannot be stored in v2 the
    command is BLOCKED with the reasons and writes nothing; `allow_skipped` goes on and keeps
    the original as `comments.v1.js` (not loaded by the page) instead of deleting it.
    """
    repo = Path(root).resolve()
    settings = _settings(repo, manifest)
    directory = _prototype_directory(repo, settings, slug)
    paths = asset_paths(layerset, [f'repo/{name}' for name in STATIC_FILES + ('.gitignore', '.gitattributes')],
                        assets)
    steps, changed, warnings = [], [], []
    report = {'status': 'PASS', 'path': _relative(directory, repo), 'dryRun': bool(dry_run)}
    comments_json = directory / server.COMMENTS_FILE
    comments_js = directory / server.LEGACY_COMMENTS_FILE
    kept_js = directory / LEGACY_COMMENTS_KEPT
    already = os.path.lexists(comments_json)
    html = _read_index_html(directory)
    try:
        hashes_before = server.screen_hashes(str(directory))['screens']
    except OSError:
        hashes_before = None

    def record(step, action, path=None, **extra):
        item = {'step': step, 'action': action}
        if path is not None:
            item['path'] = _relative(path, repo)
            if action not in ('skipped', 'unchanged'):
                changed.append(item['path'])
        item.update(extra)
        steps.append(item)

    # Plan everything in memory first: nothing is written when the conversion would lose data.
    has_js = os.path.lexists(comments_js)
    operations, problems, document_warnings = _read_v1_operations(comments_js, slug) if has_js else ([], [], [])
    warnings += document_warnings
    original = html
    fixed, added = (html, []) if already else server.fix_proto_ids(html)
    converted, skipped, anchors = convert_v1_operations(operations, fixed)
    skipped = problems + skipped
    if already and has_js:
        # A comments.js left next to comments.json may only go when all its operations are in v2.
        existing, reason = read_regular_bytes(comments_json, MAX_COMMENTS_READ)
        if existing is None:
            raise PrototypeError(f'comments.json: {reason}')
        try:
            stored = server.parse_document(existing.decode('utf-8'), slug)
        except UnicodeDecodeError:
            raise PrototypeError('comments.json: not UTF-8') from None
        except server.CommentsFileError as error:
            raise PrototypeError(f'comments.json: {error.message}') from None
        stored_ids = {operation.get('id') for operation in stored.operations}
        skipped += [{'id': operation['id'], 'type': operation['type'], 'reason': 'missing from comments.json'}
                    for operation in converted if operation['id'] not in stored_ids]
    without_script = _COMMENTS_SCRIPT.sub('', fixed)
    locked, lock_added = ensure_theme_lock_metas(without_script)
    # The sprite is read and merged while planning: an unreadable sprite stops the command before any write.
    sprite = {'status': 'skipped', 'replaced': [], 'added': [],
                               'message': 'sprite: icons are merged on the next `migrate` (a v1 prototype has '
                                          'comments.json only after this migration)'}
    if already:
        sprite_path = optional_asset_path(layerset, '/'.join(SPRITE_RELATIVE), assets)
        if sprite_path is None:
            sprite = {'status': 'missing_in_library', 'replaced': [], 'added': [], 'message': 'sprite: missing in the library'}
        else:
            try:
                sprite_text = _read_asset(sprite_path)
            except (OSError, UnicodeDecodeError) as error:
                raise PrototypeError(f'sprite.svg: {error} (nothing was written)') from None
            locked, replaced, appended, status = merge_icon_sprite(locked, sprite_text)
            sprite = {'status': status, 'replaced': replaced, 'added': appended}
            if status == 'no_container':
                sprite['message'] = ('sprite: index.html has no <svg> container with <symbol>; missing symbols '
                                     'were not inserted')
            elif status == 'no_symbols':
                sprite['message'] = 'sprite: the library sprite has no ic-* symbol'
    notices = []
    readme_text, readme_kinds, readme_found = None, [], []
    if already:
        icons_own = sprite['status'] in ('merged', 'unchanged')
        locked, notices = remove_template_notices(locked, icons=icons_own)
        readme_bytes, reason = read_regular_bytes(directory / 'README.md', MAX_COMMENTS_READ)
        if readme_bytes is not None:
            try:
                readme_original = readme_bytes.decode('utf-8')
            except UnicodeDecodeError:
                warnings.append('README.md: not UTF-8; icon licence notice not checked')
            else:
                readme_text, readme_kinds, readme_found = remove_readme_notices(readme_original, icons=icons_own)
                if readme_text == readme_original:
                    readme_text = None
        elif reason != 'missing':
            warnings.append(f'README.md: {reason}; icon licence notice not checked')
        for number in readme_found:
            warnings.append(f'README.md:{number} still names the old icon library; review it manually '
                            '(migrate removes only the fixed template line)')
    # Step 7 (D187): the generated theme files are refreshed like `sync` does, so one `migrate` leaves the prototype
    # current. Planned here, before any write: a symbolic link or unreadable file stops the command.
    theme_paths = asset_paths(layerset, [f'theme/{name}' for name in THEME_FILES], assets)
    tokens_css, theme_css, theme_warnings = build_theme_files(settings, theme_paths, repo)
    warnings += theme_warnings
    theme_expected = {'tokens.css': tokens_css.encode('utf-8'), 'theme.css': theme_css.encode('utf-8')}
    theme_changed = {}
    for file_name in GENERATED_FILES:
        path = directory / file_name
        if os.path.lexists(path):
            info = os.lstat(path)
            if stat.S_ISLNK(info.st_mode) or not stat.S_ISREG(info.st_mode):
                raise PrototypeError(f'{file_name}: refusing a symbolic link or non-file (nothing was written)')
        current, reason = read_regular_bytes(path, len(theme_expected[file_name]))
        if current is None and reason not in ('missing', 'too large'):
            raise PrototypeError(f'{file_name}: {reason} (nothing was written)')
        if current != theme_expected[file_name]:
            theme_changed[file_name] = theme_expected[file_name]
    # Engine files are checked while planning too: a symbolic link or unreadable file stops before any write.
    engine_plan = {}
    for name in STATIC_FILES:
        source = paths[f'repo/{name}'].read_bytes()
        current, reason = read_regular_bytes(directory / name, max(len(source) + 1, MAX_COMMENTS_READ))
        if current is None and reason not in ('missing', 'too large'):
            raise PrototypeError(f'{name}: {reason} (nothing was written)')
        engine_plan[name] = (source, current)
    create_project_css = not os.path.lexists(directory / PROJECT_CSS)
    locked, link_status = add_project_css_link(locked)
    if link_status == 'no_head':
        warnings.append('index.html has no <head>; project.css link not added')
    if sprite.get('message') and sprite['status'] != 'skipped':
        warnings.append(sprite['message'])
    report['sprite'] = sprite
    report['notices_removed'] = notices + [kind for kind in readme_kinds if kind not in notices]
    report['notices_found'] = [{'file': 'README.md', 'line': number, 'kind': 'icon-library-mention'}
                               for number in readme_found]
    if skipped:
        report['skipped'] = skipped
        if not allow_skipped:
            first = next((item['reason'] for item in skipped if item['id'] is None), None)
            return {'status': 'BLOCKED', 'path': report['path'],
                    'reason': (f'{first}; ' if first else '') + _skipped_summary(skipped) + '; nothing was written '
                              '(fix comments.js or rerun with --allow-skipped to keep it as comments.v1.js)',
                    'skipped': skipped}
        if has_js and os.path.lexists(kept_js):
            raise PrototypeError(f'{LEGACY_COMMENTS_KEPT} already exists; move it away and rerun (nothing was written)')
        warnings.append(_skipped_summary(skipped) + ', skipped; '
                        f'the original stays as {LEGACY_COMMENTS_KEPT}')
    if already:
        record('1-4', 'skipped', reason='already_migrated')
    else:
        if has_js:
            record(1, 'read', comments_js, operations=len(operations))
        else:
            record(1, 'skipped', reason='no comments.js')
        if added:
            if not dry_run:
                _replace_index(directory, original, fixed)
            record(2, 'ids_fix', directory / 'index.html', added=len(added))
        else:
            record(2, 'unchanged', directory / 'index.html')
        record(3, 'convert', operations=len(converted), anchors=anchors, skipped=len(skipped))
        if not dry_run:
            with server.FileLock(str(comments_json) + server.LOCK_SUFFIX):
                if os.path.lexists(comments_json):
                    raise PrototypeError('comments.json appeared during migration; run migrate again')
                server.atomic_write_bytes(comments_json, server.serialize_document(slug, converted).encode('utf-8'))
        record(4, 'write', comments_json, operations=len(converted))
    html = fixed
    for name in STATIC_FILES:
        source, current = engine_plan[name]
        target = directory / name
        if current == source:
            continue
        if name == 'screens.css' and current is not None:
            library_css = [paths[f'repo/{item}'].read_bytes() for item in STATIC_FILES if item.endswith('.css')]
            default_theme = optional_asset_path(layerset, 'theme/default.css', assets)
            if default_theme is not None:
                library_css.append(default_theme.read_bytes())
            lost_classes = _classes_lost_from(current, library_css, directory / PROJECT_CSS)
            if lost_classes:
                report['project_styles_warning'] = {
                    'classes': lost_classes,
                    'message': ('klasy tylko w dotychczasowym screens.css (nie ma ich w żadnym pliku CSS biblioteki): przenieś ich reguły '
                                'do project.css; nie kopiuję ich automatycznie, bo stary plik może zawierać kod '
                                'biblioteki')}
        if not dry_run:
            server.atomic_write_bytes(target, source)
        record(5, 'copy_engine', target)
    if create_project_css:
        if not dry_run:
            server.atomic_write_bytes(directory / PROJECT_CSS, PROJECT_CSS_TEXT.encode('utf-8'))
        record(5, 'create_project_css', directory / PROJECT_CSS)
    if without_script != html:
        record(5, 'remove_comments_script', directory / 'index.html')
    if sprite['replaced'] or sprite['added']:
        record(5, 'sprite_merge', directory / 'index.html', replaced=sprite['replaced'], added=sprite['added'])
    if link_status == 'added':
        record(5, 'link_project_css', directory / 'index.html')
    if notices:
        record(5, 'remove_notices', directory / 'index.html', kinds=notices)
    if lock_added:
        record(5, 'theme_lock_meta', directory / 'index.html', added=lock_added)
    elif lock_added is None:
        warnings.append('index.html has no <head>; color-scheme and darkreader-lock meta not added')
    if locked != html and not dry_run:
        _replace_index(directory, html, locked)
    if readme_text is not None:
        if not dry_run:
            _write_text(directory / 'README.md', readme_text)
        record(5, 'remove_notices', directory / 'README.md', kinds=readme_kinds)
    if has_js:
        if skipped:
            if not dry_run:
                _move_without_replacing(comments_js, kept_js)
            record(6, 'keep_original', kept_js)
        else:
            if not dry_run:
                os.unlink(comments_js)
            record(6, 'delete', comments_js)
    for name, lines in (('.gitignore', GITIGNORE_LINES), ('.gitattributes', (GITATTRIBUTES_LINE,))):
        text = _ensure_lines(directory / name, lines, _read_asset(paths[f'repo/{name}']))
        if text is not None:
            if not dry_run:
                _write_text(directory / name, text)
            record(6, 'update', directory / name)
    for file_name, data in theme_changed.items():
        if not dry_run:
            atomic_write(directory / file_name, data.decode('utf-8'))
        record(7, 'sync_tokens', directory / file_name)
    report['tokens_synced'] = True
    report['tokens_files'] = [_relative(directory / file_name, repo) for file_name in theme_changed]
    report['result'] = 'already_migrated' if already and not changed else 'migrated'
    extra_files = dict(theme_changed)
    if create_project_css:
        extra_files[PROJECT_CSS] = PROJECT_CSS_TEXT.encode('utf-8')
    report['acceptance'] = _acceptance_lost(directory, slug, hashes_before, paths, locked, warnings, extra_files or None)
    report['steps'] = steps
    report['files'] = sorted(set(changed))
    if warnings:
        report['warnings'] = warnings
    return report


def _user_error(error):
    return PrototypeError(f'{error.code}: {error.message}')


def _cli_password(args):
    """Explicit password from `--password-prompt` (getpass, twice) or `--password-stdin` (first line)."""
    if getattr(args, 'password_prompt', False):
        first = getpass.getpass('Hasło: ')
        if first != getpass.getpass('Powtórz hasło: '):
            raise PrototypeError('password_mismatch: passwords differ')
        return first
    if getattr(args, 'password_stdin', False):
        line = sys.stdin.readline()
        line = line[:-1] if line.endswith('\n') else line
        line = line[:-1] if line.endswith('\r') else line
        if not line:
            raise PrototypeError('empty_password: no password on standard input')
        return line
    return None


def _users(repo, value):
    users = server.UsersFile(str(users_file_path(repo, value)))
    warnings = []
    if users.exists():
        problem = users.permissions_problem()
        if problem:
            raise PrototypeError(problem)
        if os.name == 'nt':
            warnings.append(server.PRIVATE_CHECK_SKIPPED)
    return users, warnings


def user_command(root, args):
    """`user add|passwd|remove|list|import`; the default password comes only from the machine config."""
    repo = Path(root).resolve()
    users, warnings = _users(repo, args.users)
    action = args.user_command
    report = {'status': 'PASS', 'action': action, 'users_file': _relative_or_absolute(users.path, repo)}
    try:
        if action in ('passwd', 'remove', 'list') and not users.exists():
            raise PrototypeError(f'users_file_missing: {report["users_file"]} does not exist')
        if action in ('add', 'passwd'):
            password = _cli_password(args)
            default = None
            if password is None:
                default, extra = default_password()
                warnings += extra
            if action == 'add':
                record, extra = server.add_user(users, args.login, role=args.role, password=password,
                                                default_password=default, name=args.name)
            else:
                record, extra = server.set_password(users, args.login, password=password, default_password=default)
            report['user'] = record
            warnings += extra
        elif action == 'remove':
            report['user'] = server.remove_user(users, args.login)
        elif action == 'list':
            report['users'] = server.list_users(users)
        else:
            source = users_file_path(repo, args.file)
            text, reason = read_regular_text(source, MAX_PROTOTYPE_JSON * 16)
            if text is None:
                raise PrototypeError(f'import file {args.file}: {reason}')
            logins, invalid = server.parse_import_lines(text)
            if invalid:
                raise PrototypeError('invalid_login: the import file has invalid addresses',
                                     [f'line {item["line"]}: {item["error"]}' for item in invalid])
            default, extra = default_password()
            warnings += extra
            outcome, extra = server.import_users(users, logins, role=args.role, default_password=default)
            report.update(outcome)
            warnings += extra
    except server.UserError as error:
        raise _user_error(error) from None
    except server.LockTimeout:
        raise PrototypeError('lock_timeout: the users file is locked') from None
    if warnings:
        report['warnings'] = warnings
    return report


def _relative_or_absolute(path, repo):
    try:
        return Path(path).resolve().relative_to(repo).as_posix()
    except ValueError:
        return str(path)


def _in_git_worktree(path):
    try:
        process = subprocess.run(['git', '-C', str(path), 'rev-parse', '--is-inside-work-tree'],
                                 stdout=subprocess.PIPE, stderr=subprocess.DEVNULL, stdin=subprocess.DEVNULL,
                                 timeout=10, check=False)
    except (OSError, subprocess.SubprocessError):
        return False
    return process.returncode == 0 and process.stdout.strip() == b'true'


def serve_prototypes(root, manifest, args, err=None):
    """`serve`: foreground server on `root` of the manifest; BLOCKED (exit 2) when it may not start."""
    err = err or sys.stderr
    repo = Path(root).resolve()
    settings = _settings(repo, manifest)
    source_writes = not args.no_source_writes and _in_git_worktree(settings['root'])
    config = server.ServerConfig(settings['root'], users_file_path(repo, args.users), host=args.host, port=args.port,
                                 secure_cookies=args.secure_cookies, trust_proxy=args.trust_proxy,
                                 login_to_view=args.login_to_view, source_writes=source_writes, log=err)
    try:
        instance = server.make_server(config)
    except server.StartupError as error:
        report = {'status': 'BLOCKED', 'reason': 'serve refused to start', 'errors': error.errors}
        if error.warnings:
            report['warnings'] = error.warnings
        return report
    except OSError as error:
        return {'status': 'BLOCKED', 'reason': f'cannot listen on {args.host}:{args.port} ({error.strerror or error})'}
    notes = list(settings['warnings']) + instance.app.warnings
    if not args.no_source_writes and not source_writes:
        notes.append(f'{_relative(settings["root"], repo)} nie leży w kopii roboczej gita: przywracanie z UI wyłączone '
                     '(source writes off)')
    for warning in notes:
        err.write(f'ostrzeżenie: {warning}\n')
    err.write(f'Serwer prototypów: {instance.url} (Ctrl+C kończy)\n')
    err.flush()
    try:
        instance.serve_forever()
    except KeyboardInterrupt:
        pass
    finally:
        instance.server_close()
    return {'status': 'PASS', 'url': instance.url, 'root': _relative(settings['root'], repo), 'stopped': True}


# ── Iterations, restore, agent operations, merge (F2) ────────────────────────

COMMIT_MESSAGE = 'prototyp {slug}: stan przed iteracją {number}'
_GIT_IN_PROGRESS = ('MERGE_HEAD', 'rebase-merge', 'rebase-apply', 'CHERRY_PICK_HEAD', 'REVERT_HEAD')


def _git(repo, args, timeout=60):
    """`git -C <repo> …`; None when git is missing."""
    try:
        return subprocess.run(['git', '-C', str(repo)] + list(args), stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                              stdin=subprocess.DEVNULL, timeout=timeout, check=False)
    except FileNotFoundError:
        return None
    except (OSError, subprocess.SubprocessError) as error:
        raise PrototypeError(f'git {args[0]}: {error}') from None


def _git_output(process):
    if process is None:
        return 'git is not available'
    text = (process.stderr or b'').decode('utf-8', 'replace').strip() or (process.stdout or b'').decode('utf-8', 'replace').strip()
    return text[-600:] or f'exit {process.returncode}'


def commit_before_iteration(repo, directory, slug, number):
    """K40: commit of `<root>/<slug>/` before freezing iteration `number` (flag
    `prototype.commit_before_iteration`).  Returns `(sha or None, warnings)`.

    `git -C <project>` with a pathspec relative to the project: `status --porcelain --` detects
    changes (untracked files too), `add -A --` (`.gitignore` respected, so the prototype
    `.gitignore` keeps `comments.json.lock` out), `commit --only -m … --` (other staged files stay out; hooks run, no `--no-verify`,
    no push).  Outside a git working copy (or without git) = warning, no commit.  A merge,
    rebase, cherry-pick or revert in progress, an unresolved conflict and any failure of
    `git add`/`git commit` raise `PrototypeError` (BLOCKED before the freeze).
    """
    repo = Path(repo)
    pathspec = _relative(directory, repo) + '/'
    inside = _git(repo, ['rev-parse', '--is-inside-work-tree'], timeout=10)
    if inside is None:
        return None, ['git is not available: no commit before the iteration (prototype.commit_before_iteration)']
    if inside.returncode != 0 or inside.stdout.strip() != b'true':
        return None, [f'{pathspec} is not in a git working copy: no commit before the iteration']
    for marker in _GIT_IN_PROGRESS:
        located = _git(repo, ['rev-parse', '--git-path', marker], timeout=10)
        if located is None or located.returncode != 0:
            continue
        candidate = Path(located.stdout.decode('utf-8', 'replace').strip())
        if not candidate.is_absolute():
            candidate = repo / candidate
        if candidate.exists():
            raise PrototypeError(f'git: {marker} is in progress; finish or abort it first '
                                 '(no commit, nothing frozen)')
    unmerged = _git(repo, ['diff', '--name-only', '--diff-filter=U'], timeout=30)
    if unmerged is not None and unmerged.returncode == 0 and unmerged.stdout.strip():
        raise PrototypeError('git: unresolved conflicts in the working copy; resolve them first (no commit, nothing frozen)')
    status = _git(repo, ['status', '--porcelain', '--', pathspec], timeout=60)
    if status is None or status.returncode != 0:
        raise PrototypeError(f'git status failed: {_git_output(status)} (no commit, nothing frozen)')
    if not status.stdout.strip():
        return None, []
    # The lock file stays out through the prototype `.gitignore` (`init`, `migrate`); an explicit
    # `:(exclude)` of an ignored path makes `git add` fail ("paths are ignored").
    added = _git(repo, ['add', '-A', '--', pathspec], timeout=120)
    if added is None or added.returncode != 0:
        raise PrototypeError(f'git add failed: {_git_output(added)} (no commit, nothing frozen)')
    staged = _git(repo, ['diff', '--cached', '--quiet', '--', pathspec], timeout=60)
    if staged is not None and staged.returncode == 0:
        return None, []
    message = COMMIT_MESSAGE.format(slug=slug, number=number)
    commit = _git(repo, ['commit', '--only', '-m', message, '--', pathspec], timeout=600)
    if commit is None or commit.returncode != 0:
        raise PrototypeError(f'git commit failed: {_git_output(commit)} (nothing frozen)')
    head = _git(repo, ['rev-parse', 'HEAD'], timeout=10)
    sha = head.stdout.decode('ascii', 'replace').strip() if head is not None and head.returncode == 0 else None
    return sha, []


def _server_blocked(error, **extra):
    """BLOCKED report of a `PrototypeServerError` (code, message and details)."""
    report = {'status': 'BLOCKED', 'error': error.code, 'reason': f'{error.code}: {error.message}'}
    report.update(error.details or {})
    report.update(extra)
    return report


def _prototype_blocked(error, warnings):
    """BLOCKED of a `PrototypeError` raised after recovery (e.g. the K40 commit) with what recovery wrote (S1-2)."""
    report = {'status': 'BLOCKED', 'reason': str(error)}
    if error.errors:
        report['errors'] = error.errors
    if getattr(error, 'recovery_notes', None):
        report['recovery'] = error.recovery_notes
    if warnings:
        report['warnings'] = warnings
    return report


def _store(directory, slug):
    return server.CommentsStore(str(directory), slug)


def _prototype_context(root, manifest, slug):
    repo = Path(root).resolve()
    settings = _settings(repo, manifest)
    directory = _prototype_directory(repo, settings, slug)
    return repo, settings, directory, _store(directory, slug)


def _commit_hook(settings, repo, directory, slug, warnings):
    if not settings['commit_before_iteration']:
        return None

    def before_freeze(number):
        sha, extra = commit_before_iteration(repo, directory, slug, number)
        warnings.extend(extra)
        return sha
    return before_freeze


def iterate_prototype(root, manifest, slug):
    """`iterate`: `ids --check` must pass (FAIL = exit 1), commit of K40 at the flag, freeze of the
    current iteration N to `iterations/N/` and the operation `iteration {number: N}` (`by: agent`)."""
    repo, settings, directory, store = _prototype_context(root, manifest, slug)
    warnings = list(settings['warnings'])
    hook = _commit_hook(settings, repo, directory, slug, warnings)
    try:
        result = server.perform_iterate(store, str(directory), by='agent', before_freeze=hook)
    except server.IdsCheckFailed as error:
        report = {'status': 'FAIL', 'reason': 'ids --check fails: run `skillsync prototype ids --fix` first',
                  'missing': error.info.get('missing', []), 'duplicates': error.info.get('duplicates', []),
                  'invalid': error.info.get('invalid', [])}
        if getattr(error, 'recovery_notes', None):
            report['recovery'] = error.recovery_notes
        if warnings:
            report['warnings'] = warnings
        return report
    except server.PrototypeServerError as error:
        return _server_blocked(error, **({'warnings': warnings} if warnings else {}))
    except PrototypeError as error:
        return _prototype_blocked(error, warnings)
    warnings.extend(result['warnings'])
    report = {'status': 'PASS', 'slug': slug, 'iteration': result['number'],
              'path': _relative(directory / result['path'], repo) + '/', 'hash': result['hash'],
              'commit': result['commit'], 'current': result['current'], 'recovered': result['recovered'],
              'operation': result['operation']}
    if result['recovery']['removed']:
        report['removed'] = result['recovery']['removed']
    if warnings:
        report['warnings'] = warnings
    return report


def _privileged_who(repo, users_value, who):
    """`--who`: an account of the users file with the role acceptor or developer."""
    login = server.normalize_login(who)
    users, warnings = _users(repo, users_value)
    if not users.exists():
        raise PrototypeError(f'users_file_missing: {_relative_or_absolute(users.path, repo)} does not exist '
                             '(--who must be an account with the role acceptor or developer)')
    try:
        record = users.get(login)
    except server.UserError as error:
        raise _user_error(error) from None
    if record is None:
        raise PrototypeError(f'unknown_user: {login} is not in the users file')
    return login, record, warnings


def restore_prototype(root, manifest, slug, screen=None, source=None, reason=None, who=None, dry_run=False,
                      resume=False, users=None):
    """`restore` (K37): `--dry-run` = effects only, `--resume` = finish an interrupted restore,
    otherwise commit of K40 at the flag, freeze of C, `iteration` + `restore`, new `index.html`."""
    repo, settings, directory, store = _prototype_context(root, manifest, slug)
    warnings = list(settings['warnings'])
    if resume:
        try:
            outcome = server.resume_restore(store, str(directory), by='agent')
        except server.PrototypeServerError as error:
            return _server_blocked(error)
        report = {'status': 'PASS', 'slug': slug, 'resume': outcome['state'], 'removed': outcome['removed'],
                  'appended': outcome['appended'], 'redone': outcome['redone']}
        warnings.extend(outcome['warnings'])
        if warnings:
            report['warnings'] = warnings
        return report
    missing = [flag for flag, value in (('--screen', screen), ('--from', source), ('--reason', reason), ('--who', who))
               if value is None]
    if missing:
        raise PrototypeError('restore needs ' + ', '.join(missing) + ' (or --resume)')
    if not server.SCREEN_ID_RE.fullmatch(screen):
        raise PrototypeError(f'Invalid screen id {screen!r}')
    if source < 1:
        raise PrototypeError('--from must be an iteration number (1 or more)')
    if not reason.strip() or server.text_length(reason) > server.MAX_REASON:
        raise PrototypeError(f'--reason must have 1-{server.MAX_REASON} characters')
    login, record, user_warnings = _privileged_who(repo, users, who)
    warnings.extend(user_warnings)
    if record['role'] not in server.PRIVILEGED_ROLES:
        raise PrototypeError(f'forbidden: {login} has the role {record["role"]}; restore needs acceptor or developer')
    try:
        if dry_run:
            preview = server.preview_restore(store, str(directory), screen, source)
            warnings.extend(preview.pop('warnings'))
            report = dict({'status': 'PASS', 'slug': slug, 'dryRun': True, 'screen': screen, 'from': source}, **preview)
        else:
            hook = _commit_hook(settings, repo, directory, slug, warnings)
            result = server.perform_restore(store, str(directory), screen, source, reason, by='agent', who=login,
                                            before_freeze=hook, recovery_by='agent')
            warnings.extend(result['warnings'])
            plan = result['plan']
            if result['unchanged']:
                report = {'status': 'PASS', 'result': 'unchanged', 'slug': slug, 'screen': screen, 'from': source,
                          'current': result['current'], 'version': result['version'],
                          'note': f'screen {screen} in iteration {source} is the same as the current one: nothing written'}
                if warnings:
                    report['warnings'] = warnings
                return report
            report = {'status': 'PASS', 'result': 'restored', 'slug': slug, 'screen': screen, 'from': source,
                      'frozen': result['operations'][0]['payload']['number'], 'current': result['current'],
                      'commit': result['commit'], 'threadsBack': plan['threadsBack'],
                      'threadsLost': plan['threadsLost'], 'acceptanceLost': plan['acceptanceLost'],
                      'operations': result['operations'],
                      'note': 'CSS and <head> stay as in the current version; only the screen section was replaced'}
    except server.PrototypeServerError as error:
        return _server_blocked(error, **({'warnings': warnings} if warnings else {}))
    except PrototypeError as error:
        return _prototype_blocked(error, warnings)
    if warnings:
        report['warnings'] = warnings
    return report


# ── Acceptance from the terminal (F3) ────────────────────────────────────────

def _blocked(code, reason, **extra):
    report = {'status': 'BLOCKED', 'error': code, 'reason': f'{code}: {reason}'}
    report.update(extra)
    return report


def _stdin_is_tty():
    try:
        return bool(sys.stdin.isatty())
    except (AttributeError, ValueError):
        return False


def accept_prototype(root, manifest, slug=None, screens=None, all_screens=False, project=False, by=None, users=None):
    """`accept` (K24, K43): acceptance of screens of the current files by a human at a terminal.

    Scope `screen` (`slug` + `--screen` …), `all` (`slug` + `--all`) or `project` (every v2 prototype, in
    the order of `slug`, each under its own lock).  Order of checks: stdin is a TTY (`tty_required`, before
    any prompt), `--by` has the role acceptor or developer (`forbidden`), no `mustChange`
    (`password_change_required`), the password read with `getpass` (`invalid_credentials`).  Written as
    `by: agent` with `who` = the login and `via: cli`.  The password and its hash never reach the output.
    BLOCKED (exit 2) carries `error`; a failure in `project` lists `accepted` and `pending`.  Screens whose
    section is ambiguous (duplicate id, unclosed) are left out of `all`/`project` and listed in `skippedScreens`.
    """
    if not _stdin_is_tty():
        return _blocked('tty_required', 'accept needs a terminal: the password of --by is read from the TTY')
    screens = list(screens or [])
    if project:
        if slug is not None or screens or all_screens:
            raise PrototypeError('--project takes no slug, --screen or --all')
    elif slug is None or bool(screens) == bool(all_screens):
        raise PrototypeError('accept needs <slug> with --screen sN (repeatable) or --all, or --project')
    for screen in screens:
        if not server.SCREEN_ID_RE.fullmatch(screen):
            raise PrototypeError(f'Invalid screen id {screen!r}')
    if not isinstance(by, str) or not by.strip():
        raise PrototypeError('accept needs --by LOGIN')
    repo = Path(root).resolve()
    settings = _settings(repo, manifest)
    login = server.normalize_login(by)
    account, warnings = _users(repo, users)
    record = account.get(login) if account.exists() else None
    if record is None or record['role'] not in server.PRIVILEGED_ROLES:
        return _blocked('forbidden', f'--by must be an account with the role acceptor or developer '
                        f'(checked in {_relative_or_absolute(account.path, repo)})')
    if record['mustChange']:
        return _blocked('password_change_required', f'{login} must change the password first (sign in to the server)')
    try:
        password = getpass.getpass(f'Hasło {login}: ')
    except (EOFError, KeyboardInterrupt):
        return _blocked('tty_required', 'the password was not entered')
    if not server.verify_password(password, record['password']):
        return _blocked('invalid_credentials', 'wrong password')
    del password
    scope = 'project' if project else ('all' if all_screens else 'screen')
    if project:
        targets = list(enumerate_prototypes(settings['root']))
    else:
        targets = [(slug, _prototype_directory(repo, settings, slug))]
    accepted, skipped, skipped_screens = [], [], []
    pending = [name for name, _directory in targets]
    for name, directory in targets:
        store = _store(directory, name)
        state = store.state()
        if state == 'v1':
            if not project:
                return _server_blocked(server.NeedsMigration())
            skipped.append(name)
            pending.remove(name)
            continue

        def build(snapshot, directory=directory, name=name):
            info = server.screen_hashes(str(directory))
            hashes = info['screens']
            wanted = screens if scope == 'screen' else sorted(hashes, key=server._utf16_key)
            if scope != 'screen':
                skipped_screens.extend({'slug': name, 'screen': item['screen'], 'reason': item['problem']}
                                       for item in server.unique_problems(info['ambiguous']))
            unknown = [screen for screen in wanted if screen not in hashes]
            if unknown:
                raise server.OperationError(400, 'unknown_screen', server.unknown_screen_message(unknown, info['ambiguous']),
                                            {'screens': unknown})
            if not wanted:
                return []
            return {'type': 'accept', 'by': 'agent',
                    'payload': {'scope': scope, 'screens': {screen: hashes[screen] for screen in wanted},
                                'iteration': snapshot.fold['currentIteration'], 'via': 'cli', 'who': login}}

        try:
            result = store.transaction(build)
        except (server.PrototypeServerError, OSError) as error:
            if isinstance(error, server.PrototypeServerError):
                report = _server_blocked(error)
            else:
                report = _blocked('write_failed', str(error) or type(error).__name__)
            if project:
                report.update({'accepted': accepted, 'pending': pending})
            return report
        pending.remove(name)
        if result.operations:
            accepted.append({'slug': name, 'screens': sorted(result.operations[0]['payload']['screens'],
                                                            key=server._utf16_key)})
        else:
            skipped.append(name)
    report = {'status': 'PASS', 'accepted': accepted, 'skipped': skipped, 'who': login, 'via': 'cli'}
    if skipped_screens:
        report['skippedScreens'] = skipped_screens
    if warnings:
        report['warnings'] = warnings
    return report


# ── Gate: accepted prototypes before the implementation (K26) ────────────────

GATE_PROTOTYPE_LINE = re.compile(r'Prototyp:[ \t]*`?([^\s`]+)`?[ \t]*')
# `— <osoba>, <data>`: any name or nick of the person who allowed the bypass (no dash or comma inside).
GATE_BYPASS_LINE = re.compile(r'Bramka prototypu: pominięta — (?P<reason>.+?) — (?P<by>[^\s—,][^—,\n]*?), '
                              r'(?P<date>[0-9]{4}-[0-9]{2}-[0-9]{2})[ \t]*')
# Near misses (typos, bullets, bold, a space before the colon) are refused instead of being ignored (fail closed).
_NEAR_PROTOTYPE = re.compile(r'(?i)^[ \t]*(?:(?:[-*+>]|[0-9]+[.)])[ \t]*)*[*_]{0,2}prototype?[*_]{0,2}[ \t]*:')
_NEAR_BYPASS = re.compile(r'(?i)^\W*bramka\s+prototypu')
MAX_GATE_PLAN = 1024 * 1024


def _plan_header(text):
    """The plan header: the text before the first line starting with `## `."""
    lines = []
    for line in text.splitlines():
        if line.startswith('## '):
            break
        lines.append(line.rstrip('\r'))
    return lines


def _gate_line_kind(line):
    """`'prototype'`, `'bypass'` or None: a header line that is, or nearly is, a gate line."""
    if line.lstrip().startswith('#'):
        return None
    if _NEAR_PROTOTYPE.match(line):
        return 'prototype'
    if _NEAR_BYPASS.match(line):
        return 'bypass'
    return None


def plan_has_gate_lines(text):
    """True when the plan header has a `Prototyp:` or a `Bramka prototypu:` line, also a malformed one."""
    return any(_gate_line_kind(line) for line in _plan_header(text))


def _gate_path(repo, value):
    """Directory of a `Prototyp:` path (relative to the project, inside it, no symlinks) or None."""
    try:
        path = contained(repo, value)
    except (ValueError, OSError):
        return None
    current = repo
    for part in Path(value).parts:
        current = current / part
        if current.is_symlink():
            return None
    if not path.is_dir() or not os.path.lexists(path / 'prototype.json'):
        return None
    return path


def prototype_gate(root, manifest, plan=None, slugs=None):
    """`gate` (K26): every screen (without `data-prototype-example`) of the named prototypes needs a current
    acceptance.  Prototypes come from the `Prototyp:` lines of the plan header or from `slugs` (under
    `prototype.root`).  PASS; FAIL (exit 1) with `missing: [{slug, path, screen, reason}]` (`brak`,
    `nieaktualna`, `needs_migration`, `brak_ekranow`, `niejednoznaczny_ekran` for a duplicate id or an unclosed screen); BLOCKED (exit 2) with `error` for a bad plan, line or
    prototype.  A header line `Bramka prototypu: pominięta — <powód> — <osoba>, <RRRR-MM-DD>` turns FAIL into
    PASS with `bypassed`.  Shared by `readiness --plan`.
    """
    repo = Path(root).resolve()
    if bool(plan) == bool(slugs):
        raise PrototypeError('gate needs --plan FILE or one or more prototype slugs (not both)')
    targets, bypass, report = [], None, {}
    if plan:
        plan_path = contained(repo, plan)
        text, reason = read_regular_text(plan_path, MAX_GATE_PLAN)
        if text is None:
            return _blocked('plan_unreadable', f'{plan}: {reason}')
        report['plan'] = _relative_or_absolute(plan_path, repo)
        bypasses = 0
        for line in _plan_header(text):
            kind = _gate_line_kind(line)
            if kind == 'prototype':
                match = GATE_PROTOTYPE_LINE.fullmatch(line)
                if not match:
                    return _blocked('invalid_prototype_line', f'Prototyp: line must hold one path: {line[:200]}')
                if match.group(1) not in targets:
                    targets.append(match.group(1))
            elif kind == 'bypass':
                match = GATE_BYPASS_LINE.fullmatch(line)
                bypasses += 1
                valid_date = False
                if match:
                    try:
                        date.fromisoformat(match.group('date'))
                        valid_date = True
                    except ValueError:
                        pass
                if not match or not valid_date or bypasses > 1:
                    return _blocked('invalid_bypass_line', 'expected one line: Bramka prototypu: pominięta — <powód> '
                                    '— <osoba>, <RRRR-MM-DD>')
                bypass = {'reason': match.group('reason'), 'by': match.group('by'), 'date': match.group('date')}
        resolved = []
        for value in targets:
            directory = _gate_path(repo, value)
            if directory is None:
                return _blocked('prototype_not_found', f'{value} is not a prototype directory of this project',
                                path=value)
            resolved.append((directory.name, directory))
    else:
        settings = _settings(repo, manifest)
        resolved = []
        for slug in dict.fromkeys(slugs):
            if not is_prototype_dir(settings['root'], slug):
                return _blocked('prototype_not_found', f'no prototype {slug} under {_relative(settings["root"], repo)}',
                                path=slug)
            resolved.append((slug, settings['root'] / slug))
    prototypes, missing, acceptances = [], [], []
    for slug, directory in resolved:
        path = _relative(directory, repo)
        store = _store(directory, slug)
        if store.state() == 'v1':
            prototypes.append({'path': path, 'slug': slug, 'format': 1, 'iteration': None, 'screens': None})
            missing.append({'slug': slug, 'path': path, 'screen': None, 'reason': 'needs_migration'})
            continue
        try:
            fold = store.snapshot().fold
            info = server.screen_hashes(str(directory))
            hashes = info['screens']
        except server.PrototypeServerError as error:
            return _blocked(error.code, f'{path}: {error.message}', path=path)
        except OSError as error:
            return _blocked('prototype_unreadable', f'{path}: {error.strerror or error}', path=path)
        state = server.acceptance_state(fold, hashes)
        prototypes.append({'path': path, 'slug': slug, 'format': 2, 'iteration': fold['currentIteration'],
                           'screens': len(hashes)})
        problems = server.unique_problems(info['ambiguous'])
        if not hashes and not problems:
            missing.append({'slug': slug, 'path': path, 'screen': None, 'reason': 'brak_ekranow'})
        for screen in sorted(hashes, key=server._utf16_key):
            entry = state.get(screen)
            if entry is None:
                missing.append({'slug': slug, 'path': path, 'screen': screen, 'reason': 'brak'})
            elif not entry['valid']:
                missing.append({'slug': slug, 'path': path, 'screen': screen, 'reason': 'nieaktualna'})
            else:
                acceptances.append({'slug': slug, 'screen': screen, 'who': entry['who'], 'at': entry['at'],
                                    'via': entry['via'], 'iteration': entry['iteration']})
        for item in problems:
            missing.append({'slug': slug, 'path': path, 'screen': item['screen'], 'reason': 'niejednoznaczny_ekran'})
    status = 'FAIL' if missing and bypass is None else 'PASS'
    report.update({'status': status, 'prototypes': prototypes, 'missing': missing, 'acceptances': acceptances})
    if bypass is not None:
        report['bypassed'] = bypass
    if plan and not resolved and bypass is None:
        report['note'] = 'plan bez linii Prototyp:'
    return report


def _status_filter(value):
    if value is None or value == 'open':
        return ['open']
    if value == 'all':
        return list(server.STATUSES)
    statuses = [item.strip() for item in value.split(',') if item.strip()]
    unknown = [item for item in statuses if item not in server.STATUSES]
    if unknown or not statuses:
        raise PrototypeError(f'--status: unknown status {", ".join(unknown) or value!r} '
                             f'(use {", ".join(server.STATUSES)} or all)')
    return statuses


def _people_names(repo):
    users = server.UsersFile(str(users_file_path(repo)))
    try:
        if users.exists() and not users.permissions_problem():
            return users.names()
    except (server.UserError, OSError):
        pass
    return {}


def comments_prototype(root, manifest, slug, status=None):
    """`comments`: facts for decisions (D6), threads with `threadId`, number, screen, element,
    messages, votes with names, status, decisions and `hints`; read only."""
    repo, settings, directory, store = _prototype_context(root, manifest, slug)
    statuses = _status_filter(status)
    if store.state() == 'v1':
        raise PrototypeError('needs_migration: prototype v1 (comments.js): run `skillsync prototype migrate` first')
    try:
        snapshot = store.snapshot()
    except server.PrototypeServerError as error:
        return _server_blocked(error)
    fold = snapshot.fold
    screen_ids = proto_ids = None
    try:
        collected = server.collect_proto_ids(_read_index_html(directory))
        screen_ids = {item['id'] for item in collected['screens']}
        proto_ids = {screen: set(values) for screen, values in collected['byScreen'].items()}
    except PrototypeError:
        pass
    people = server.compute_labels(server.collect_logins(snapshot.operations), _people_names(repo))
    threads = [server.thread_facts(thread, people, screen_ids, proto_ids)
               for thread in fold['threads'] if thread['status'] in statuses]
    report = {'status': 'PASS', 'slug': slug, 'iteration': fold['currentIteration'], 'statuses': statuses,
              'counts': server.thread_counts(fold, screen_ids, proto_ids), 'threads': threads}
    warnings = list(settings['warnings'])
    if fold['iterationDuplicates']:
        warnings.append('comments.json: duplicated iteration number(s): '
                        + ', '.join(str(number) for number in fold['iterationDuplicates']))
    if warnings:
        report['warnings'] = warnings
    return report


def _agent_command(root, manifest, slug, thread, kind, payload):
    repo, settings, directory, store = _prototype_context(root, manifest, slug)
    if store.state() == 'v1':
        raise PrototypeError('needs_migration: prototype v1 (comments.js): run `skillsync prototype migrate` first')
    try:
        operation, found = server.agent_operation(store, thread, kind, payload)
    except server.PrototypeServerError as error:
        return _server_blocked(error)
    after = store.snapshot().fold['byId'].get(found['id'])
    report = {'status': 'PASS', 'slug': slug, 'threadId': found['id'], 'number': found['number'],
              'threadStatus': after['status'] if after else None, 'operation': operation}
    if settings['warnings']:
        report['warnings'] = list(settings['warnings'])
    return report


