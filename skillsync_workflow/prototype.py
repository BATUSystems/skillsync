def _merge_comments_handler(args):
    """Both forms of `merge-comments`; the driver form needs no project argument."""
    try:
        if args.driver is not None:
            if args.path is not None or args.slug is not None or args.other is not None:
                raise PrototypeError('merge-comments --driver takes only %O %A %B')
            report = merge_comments_driver(*args.driver)
        else:
            if args.path is None or args.slug is None or args.other is None:
                raise PrototypeError('merge-comments needs <path> <slug> <other-file> (or --driver %O %A %B)')
            root, manifest = read_project(args.path)
            report = merge_comments_prototype(root, manifest, args.slug, args.other)
    except server.PrototypeServerError as error:
        report = _server_blocked(error)
    except PrototypeError as error:
        report = {'status': 'BLOCKED', 'reason': str(error)}
        if error.errors:
            report['errors'] = error.errors
    except (OSError, ValueError, TypeError, RuntimeError, yaml.YAMLError) as error:
        report = {'status': 'BLOCKED', 'reason': str(error) or type(error).__name__}
    return emit(safe_report(report))


