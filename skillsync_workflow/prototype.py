def merge_comments_driver(ancestor, current, other):
    """`merge-comments --driver %O %A %B`: result = A + operations of B missing in A, written to A.
    `prototypeId` comes from the files (B must match A); a conflict leaves A untouched (exit 2)."""
    current_path, other_path = Path(current), Path(other)
    mine = _read_comments_file(current_path)
    theirs = _read_comments_file(other_path)
    if theirs.prototype_id != mine.prototype_id:
        raise PrototypeError(f'prototypeId differs: {mine.prototype_id} (A) and {theirs.prototype_id} (B)')
    try:
        merged, added = server.merge_operations(mine.operations, theirs.operations)
    except server.PrototypeServerError as error:
        return _server_blocked(error)
    if added:
        server.atomic_write_bytes(str(current_path), server.serialize_document(mine.prototype_id, merged).encode('utf-8'))
    return _merge_report(merged, added, _driver_directory(mine.prototype_id),
                         {'slug': mine.prototype_id, 'driver': True})


