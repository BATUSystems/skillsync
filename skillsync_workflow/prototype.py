def _gallery_writable(path):
    if not os.path.lexists(path):
        return
    info = os.lstat(path)
    if stat.S_ISLNK(info.st_mode):
        raise PrototypeError(f'Refusing to overwrite {path.name}: it is a symbolic link')
    if not stat.S_ISREG(info.st_mode):
        raise PrototypeError(f'Refusing to overwrite {path.name}: not a regular file')
    flags = os.O_RDONLY | getattr(os, 'O_NOFOLLOW', 0) | getattr(os, 'O_NONBLOCK', 0) | getattr(os, 'O_BINARY', 0)
    with os.fdopen(os.open(path, flags), 'rb') as handle:
        head = handle.read(4096).decode('utf-8', errors='replace')
    if head.split('\n', 1)[0].rstrip('\r') != HTML_MARKER:
        raise PrototypeError(f'Refusing to overwrite {path.name}: it was not generated by skillsync prototype')


