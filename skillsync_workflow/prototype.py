def _move_without_replacing(source, target):
    """Move `source` to `target` and fail when `target` exists (no TOCTOU overwrite).

    `os.link` + `os.unlink`; where hard links are unavailable (some Windows file systems),
    an exclusive create (`open(…, 'xb')`) of `target` with a copy and fsync, then unlink.
    """
    try:
        os.link(source, target)
    except FileExistsError:
        raise PrototypeError(f'{Path(target).name} already exists; move it away and rerun') from None
    except (OSError, NotImplementedError, AttributeError):
        data = Path(source).read_bytes()
        try:
            with open(target, 'xb') as handle:
                handle.write(data)
                handle.flush()
                os.fsync(handle.fileno())
        except FileExistsError:
            raise PrototypeError(f'{Path(target).name} already exists; move it away and rerun') from None
        shutil.copymode(source, target)
    os.unlink(source)


SPRITE_RELATIVE = ('icons', 'sprite.svg')
_SYMBOL_OPEN = re.compile(r'<symbol(?=[\s/>])(?P<attrs>(?:"[^"]*"|\'[^\']*\'|[^>"\'])*)>', re.IGNORECASE)
_SYMBOL_CLOSE = re.compile(r'</symbol\s*>', re.IGNORECASE)
_ATTRIBUTE = re.compile(r'([^\s"\'=/>]+)(?:\s*=\s*(?:"([^"]*)"|\'([^\']*)\'|([^\s"\'>]+)))?')
_HTML_COMMENT = re.compile(r'<!--.*?(?:-->|\Z)', re.DOTALL)
_SVG_OPEN = re.compile(r'<svg(?=[\s/>])', re.IGNORECASE)
_SVG_CLOSE = re.compile(r'</svg\s*>', re.IGNORECASE)
_SPRITE_ID_PREFIX = 'ic-'


def _mask_comments(text):
    """`text` with HTML comments replaced by spaces of the same length (offsets stay valid)."""
    return _HTML_COMMENT.sub(lambda match: ' ' * len(match.group(0)), text)


def _symbols(text):
    """`[(id, start, end)]` of the `<symbol id="…">…</symbol>` (or `<symbol id="…"/>`) elements of `text`
    outside HTML comments; `id` is read as a standalone attribute (double, single or no quotes)."""
    masked = _mask_comments(text)
    result, position = [], 0
    while True:
        match = _SYMBOL_OPEN.search(masked, position)
        if not match:
            return result
        position = match.end()
        attributes = match.group('attrs')
        self_closing = attributes.rstrip().endswith('/')
        identifier = None
        for attribute in _ATTRIBUTE.finditer(attributes):
            if attribute.group(1).lower() != 'id':
                continue
            double, single, bare = attribute.group(2), attribute.group(3), attribute.group(4)
            if bare is not None and self_closing and bare.endswith('/'):
                bare = bare[:-1]
            identifier = double if double is not None else single if single is not None else bare
            break
        end = match.end()
        if not self_closing:
            close = _SYMBOL_CLOSE.search(masked, match.end())
            if not close:
                continue
            end = close.end()
        if identifier is not None:
            result.append((identifier, match.start(), end))
        position = end


def _container_end(masked, symbol):
    """Offset of the `</svg>` closing the `<svg>` that holds `symbol` (start, end), else None: no `</svg>` between
    the opening tag and the symbol, no other `<svg>` between the symbol and the closing tag."""
    start, end = symbol
    opened = None
    for opened in _SVG_OPEN.finditer(masked, 0, start):
        pass
    if opened is None or _SVG_CLOSE.search(masked, opened.end(), start):
        return None
    close = _SVG_CLOSE.search(masked, end)
    if not close or _SVG_OPEN.search(masked, end, close.start()):
        return None
    return close.start()


def merge_icon_sprite(html, sprite_text):
    """`(html, replaced, added, status)`: the `ic-*` symbols of the library sprite replace the symbols of
    `index.html` with the same id (anywhere outside comments) or are appended after the last icon symbol of the
    sprite container (the `<svg>` that holds the project's symbols); project symbols with other ids and the rest
    of the file stay byte for byte. `status`: `unchanged`, `merged`, `no_symbols` (the library sprite has no
    `ic-*` symbol) or `no_container` (`index.html` has no `<symbol>` or no `<svg>…</svg>` around the last one, so
    missing symbols are not inserted blindly; symbols with an existing id are still replaced)."""
    newline = '\r\n' if '\r\n' in html else '\n'
    library = [(sid, sprite_text[start:end].replace('\r\n', '\n').replace('\n', newline))
               for sid, start, end in _symbols(sprite_text) if sid.startswith(_SPRITE_ID_PREFIX)]
    if not library:
        return html, [], [], 'no_symbols'
    present = _symbols(html)
    by_id = {}
    for sid, start, end in present:
        by_id.setdefault(sid, []).append((start, end))
    replaced, missing, edits = [], [], []
    for sid, text in library:
        spans = by_id.get(sid)
        if spans:
            changed = [(start, end) for start, end in spans if html[start:end] != text]
            if changed:
                edits.extend((start, end, text) for start, end in changed)
                replaced.append(sid)
        else:
            missing.append((sid, text))
    added, status = [], None
    if missing:
        icons = [item for item in present if item[0].startswith(_SPRITE_ID_PREFIX)]
        anchor = (icons or present or [None])[-1]
        if anchor is not None and _container_end(_mask_comments(html), anchor[1:]) is not None:
            end = anchor[2]
            line_start = html.rfind('\n', 0, anchor[1]) + 1
            indent = re.match(r'[ \t]*', html[line_start:anchor[1]]).group(0)
            edits.append((end, end, ''.join(newline + indent + text for _, text in missing)))
            added = [sid for sid, _ in missing]
        else:
            status = 'no_container'
    if status is None:
        status = 'merged' if edits else 'unchanged'
    for start, end, text in sorted(edits, key=lambda item: (item[0], item[1]), reverse=True):
        html = html[:start] + text + html[end:]
    return html, replaced, added, status


