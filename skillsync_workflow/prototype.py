def _skip_string(text, index):
    quote, index = text[index], index + 1
    while index < len(text):
        char = text[index]
        if char == '\\':
            index += 2
            continue
        if char == quote or char == '\n':
            return index + 1
        index += 1
    return index


def strip_css_comments(text):
    """Remove `/* … */` outside strings (an unclosed comment runs to the end)."""
    parts, index, start = [], 0, 0
    while index < len(text):
        char = text[index]
        if char in '"\'':
            index = _skip_string(text, index)
        elif text.startswith('/*', index):
            parts.append(text[start:index])
            close = text.find('*/', index + 2)
            index = start = len(text) if close < 0 else close + 2
        else:
            index += 1
    parts.append(text[start:])
    return ''.join(parts)


def parse_css_blocks(text, name='CSS'):
    """Parse comment-free CSS into items `('decl', text)` and `('block', prelude, items)`.

    Braces are counted outside strings; `;` splits statements outside strings and parentheses.
    An unclosed block raises `ValueError` naming the file; a stray `}` at top level is ignored.
    """
    length = len(text)

    def body(index, top):
        items, start, depth = [], index, 0
        while index < length:
            char = text[index]
            if char in '"\'':
                index = _skip_string(text, index)
                continue
            if char == '(':
                depth += 1
            elif char == ')':
                depth = max(0, depth - 1)
            elif char == ';' and depth == 0:
                items.append(('decl', text[start:index]))
                start = index + 1
            elif char == '{':
                prelude = text[start:index].strip()
                inner, index = body(index + 1, False)
                items.append(('block', prelude, inner))
                start, depth = index, 0
                continue
            elif char == '}':
                if not top:
                    items.append(('decl', text[start:index]))
                    return items, index + 1
                start = index + 1
            index += 1
        if not top:
            raise ValueError(f'Unclosed block in {name}')
        items.append(('decl', text[start:index]))
        return items, index

    try:
        return body(0, True)[0]
    except RecursionError:
        raise ValueError(f'CSS nesting too deep in {name}') from None


def _split_selectors(prelude):
    parts, start, depth, index = [], 0, 0, 0
    while index < len(prelude):
        char = prelude[index]
        if char in '"\'':
            index = _skip_string(prelude, index)
            continue
        if char in '([':
            depth += 1
        elif char in ')]':
            depth = max(0, depth - 1)
        elif char == ',' and depth == 0:
            parts.append(prelude[start:index])
            start = index + 1
        index += 1
    parts.append(prelude[start:])
    return parts


def normalize_selector(selector):
    """Canonical form for matching: collapsed whitespace, `[data-theme="dark"]` quoting."""
    value = re.sub(r'\s+', ' ', selector.strip())
    value = re.sub(r'\[([^\]]*)\]', lambda match: '[' + re.sub(r'\s*=\s*', '=', match.group(1).strip()) + ']', value)
    return re.sub(r'\[data-theme=(?:"dark"|\'dark\'|dark)\]', '[data-theme="dark"]', value)


def _declarations(items, layer):
    for item in items:
        if item[0] != 'decl':
            continue
        match = _CUSTOM_PROPERTY.fullmatch(item[1].strip())
        if match:
            layer[match.group(1)] = match.group(2).strip()


def _has_custom_properties(items):
    for item in items:
        if item[0] == 'decl' and _CUSTOM_PROPERTY.fullmatch(item[1].strip()):
            return True
        if item[0] == 'block' and _has_custom_properties(item[2]):
            return True
    return False


def _collect(items, light, dark, warnings, name):
    for item in items:
        if item[0] == 'decl':
            if re.match(r'@import\b', item[1].strip(), re.IGNORECASE):
                warnings.append(f'{name}: @import skipped (imported tokens are not read)')
            continue
        prelude, inner = item[1], item[2]
        if prelude.startswith('@'):
            at_rule = re.match(r'@([-\w]+)\s*(.*)', prelude, re.DOTALL)
            keyword = at_rule.group(1).lower() if at_rule else ''
            rest = at_rule.group(2).strip().lower() if at_rule else ''
            if keyword == 'layer':
                _collect(inner, light, dark, warnings, name)
            elif keyword == 'theme' and rest in ('', 'inline'):
                _declarations(inner, light)
            elif keyword == 'media' and re.search(r'prefers-color-scheme\s*:\s*dark', rest):
                warnings.append(f'{name}: @media (prefers-color-scheme: dark) skipped; use .dark or [data-theme="dark"]')
            elif keyword == 'media' and _has_custom_properties(inner):
                warnings.append(f'{name}: tokens inside @media {at_rule.group(2).strip()} skipped')
            continue
        selectors = {normalize_selector(selector) for selector in _split_selectors(prelude)}
        if selectors & LIGHT_SELECTORS:
            _declarations(inner, light)
        if selectors & DARK_SELECTORS:
            _declarations(inner, dark)


def extract_tokens(css, name='CSS'):
    """Return `(light, dark, warnings)`: ordered dicts of custom properties from a stylesheet.

    Light: `:root`, `@theme`, `@theme inline`; dark: `.dark` and `[data-theme=dark]` variants.
    `@layer` is entered; `@media`, `@supports` and other at-rules are skipped.
    """
    light, dark, warnings = {}, {}, []
    _collect(parse_css_blocks(strip_css_comments(css), name), light, dark, warnings, name)
    return light, dark, warnings


def _token_block(selector, tokens):
    lines = [f'{selector} {{'] + [f'  {key}: {value};' for key, value in tokens.items()] + ['}']
    return '\n'.join(lines) + '\n'


def compose_tokens_css(default_css, project_css=None, name='tokens_from'):
    """Return `(tokens_css, warnings)` for `tokens.css` (header, default theme, project layers)."""
    warnings = []
    content = CSS_HEADER + '\n' + default_css
    if project_css is not None:
        light, dark, warnings = extract_tokens(project_css, name)
        if not light and not dark:
            warnings.append(f'{name}: no tokens found')
        if not content.endswith('\n'):
            content += '\n'
        if light:
            content += '\n' + _token_block(':root', light)
        if dark:
            # The same dark values for a page without a user choice (no `data-theme`), as in the default theme.
            media = _token_block(':root:not([data-theme])', dark)
            content += ('\n' + _token_block(':root[data-theme="dark"]', dark) + '\n@media (prefers-color-scheme: dark) {\n'
                        + ''.join('  ' + line + '\n' for line in media.splitlines()) + '}\n')
    return content, warnings


def compose_theme_css(project_css=None):
    content = CSS_HEADER + '\n'
    return content + project_css if project_css is not None else content


def parse_required_tokens(text):
    return [line.strip() for line in text.splitlines() if line.strip() and not line.strip().startswith('#')]


def defined_tokens(css):
    return set(_DEFINED_TOKEN.findall(strip_css_comments(css)))


def missing_required_tokens(required, *stylesheets):
    defined = set()
    for css in stylesheets:
        defined |= defined_tokens(css)
    return [token for token in required if token not in defined]


