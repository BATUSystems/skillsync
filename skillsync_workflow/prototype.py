def _directory_asset_paths(directory, names):
    """Assets from the explicit `--assets` directory (not a layer)."""
    directory = Path(directory).expanduser().resolve()
    if not directory.is_dir():
        raise PrototypeError(f'Missing assets directory: {directory}')
    paths = {}
    for name in names:
        path = directory / name
        if not path.is_file():
            raise PrototypeError(f'Missing asset file: {name} (in {directory})')
        paths[name] = path
    return paths


def _layer_asset_paths(layerset, names):
    """Assets from `skills/prototype/assets/**` of the active layers: `LayerSet.skill_files` (built
    on `layer_files`: per file the later layer wins, links skipped, D73), the same rule as the generator."""
    files = require_layerset(layerset, 'prototype assets').skill_files(ASSETS_SKILL)
    assets = {rel[len(ASSETS_PREFIX):]: path for rel, (_layer, path) in files.items() if rel.startswith(ASSETS_PREFIX)}
    if not assets:
        raise PrototypeError(f'Missing assets directory: no active layer has {ASSETS_LAYER_DIR} '
                             f'(layers: {", ".join(layerset.ids) or "none"})')
    paths = {}
    for name in names:
        if name not in assets:
            raise PrototypeError(f'Missing asset file: {name} (in {ASSETS_LAYER_DIR} of the layers '
                                 f'{", ".join(layerset.ids)})')
        paths[name] = assets[name]
    return paths


def asset_paths(layerset, names, assets=None):
    """{asset name: Path}: from the `--assets` directory when given, else from the layers."""
    if assets:
        return _directory_asset_paths(assets, names)
    return _layer_asset_paths(layerset, names)


