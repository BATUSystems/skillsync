def ensure_theme_lock_metas(html):
    """`(html, added)`: inserts the missing `THEME_LOCK_METAS` into `<head>` (after the viewport meta, else after
    the charset meta, else right after `<head>`), idempotent; `added` lists the inserted names. Without `<head>`
    the text is unchanged and `added` is None."""
    head = _HEAD_OPEN.search(html)
    if not head:
        return html, None
    close = _HEAD_CLOSE.search(html, head.end())
    head_end = close.start() if close else len(html)
    missing = [(name, tag) for name, tag in THEME_LOCK_METAS
               if not _meta_named(name).search(html, head.end(), head_end)]
    if not missing:
        return html, []
    anchor = (_meta_named('viewport').search(html, head.end(), head_end)
              or _META_CHARSET.search(html, head.end(), head_end))
    position = anchor.end() if anchor else head.end()
    newline = '\r\n' if '\r\n' in html[:head_end] else '\n'
    insert = ''.join(newline + tag for _, tag in missing)
    return html[:position] + insert + html[position:], [name for name, _ in missing]


