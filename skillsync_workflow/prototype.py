def encodable(text):
    """True when `text` can be written as UTF-8 (no lone surrogates)."""
    try:
        text.encode('utf-8')
    except UnicodeEncodeError:
        return False
    return True


def safe_text(text):
    """`text` with lone surrogates shown as `\\udcxx` escapes, so it is always encodable."""
    return text if encodable(text) else text.encode('utf-8', 'backslashreplace').decode('utf-8')


def safe_report(value):
    """Recursively apply `safe_text` to strings (keys and values) of a JSON-like report."""
    if isinstance(value, dict):
        return {safe_report(key): safe_report(item) for key, item in value.items()}
    if isinstance(value, list):
        return [safe_report(item) for item in value]
    return safe_text(value) if isinstance(value, str) else value


def valid_slug(slug):
    return isinstance(slug, str) and SLUG_PATTERN.fullmatch(slug) is not None


def default_title(slug):
    text = slug.replace('-', ' ')
    return text[:1].upper() + text[1:]


def title_error(title):
    """Return a refusal reason for `--title`, or None when it is acceptable."""
    if not isinstance(title, str) or not title.strip():
        return '--title must be a nonempty string'
    if len(title) > TITLE_MAX:
        return f'--title must be at most {TITLE_MAX} characters'
    if any(unicodedata.category(char) in ('Cc', 'Cf', 'Cs', 'Zl', 'Zp') for char in title):
        return '--title must not contain control or format characters'
    return None


def html_escape(value):
    return ''.join(_HTML_ESCAPES.get(char, char) for char in str(value))


def render_template(template, fields):
    """Fill `{{TITLE}}`, `{{SLUG}}`, `{{REQUIREMENTS}}` in one pass with HTML escaping.

    The replacement is a function, so backslashes and group references in the data are literal,
    and inserted text is never scanned again for placeholders.
    """
    escaped = {name: html_escape(fields.get(name, '')) for name in ('TITLE', 'SLUG', 'REQUIREMENTS')}
    return _TEMPLATE_FIELD.sub(lambda match: escaped[match.group(1)], template)


class _LinkCollector(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.hrefs = []

    def handle_starttag(self, tag, attrs):
        if tag == 'link':
            for name, value in attrs:
                if name == 'href' and value is not None:
                    self.hrefs.append(value)
                    break


def stylesheet_links(html):
    """Return `href` values of `<link>` elements in document order."""
    parser = _LinkCollector()
    try:
        parser.feed(html)
        parser.close()
    except (AssertionError, ValueError):
        pass
    return parser.hrefs


def missing_theme_links(html):
    """Return `tokens.css`/`theme.css` that no `<link href>` references (by file name)."""
    names = set()
    for href in stylesheet_links(html):
        path = href.split('#', 1)[0].split('?', 1)[0].strip()
        names.add(path.rsplit('/', 1)[-1])
    return [name for name in GENERATED_FILES if name not in names]


class _ScreenCounter(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.count = 0

    def handle_starttag(self, tag, attrs):
        if tag != 'section':
            return
        names = {name for name, _ in attrs}
        if 'data-prototype-example' in names:
            return
        # Like a browser: only the first `class` attribute counts.
        for name, value in attrs:
            if name == 'class':
                if value and 'screen' in re.split(r'[ \t\n\f\r]+', value):
                    self.count += 1
                return

    def handle_startendtag(self, tag, attrs):
        self.handle_starttag(tag, attrs)


def count_screens(html):
    """Number of `<section>` elements whose first `class` has the token `screen`.

    Sections carrying a `data-prototype-example` attribute (any value, anywhere
    among the attributes) are sample screens and are not counted.
    """
    parser = _ScreenCounter()
    try:
        parser.feed(html)
        parser.close()
    except (AssertionError, ValueError):
        pass
    return parser.count


def js_truthy(value):
    """JavaScript truthiness of a JSON value: null, false, 0, 0.0 and "" are falsy."""
    if value is None or value is False:
        return False
    if isinstance(value, (int, float)) and not isinstance(value, bool):
        return value != 0 and not (isinstance(value, float) and math.isnan(value))
    if isinstance(value, str):
        return value != ''
    return True


_UNDEFINED = object()


def _js_strict_equal(left, right):
    """JavaScript `===` for JSON values (objects and arrays compare by identity)."""
    if left is _UNDEFINED or right is _UNDEFINED or left is None or right is None:
        return left is right
    if isinstance(left, bool) or isinstance(right, bool):
        return isinstance(left, bool) and isinstance(right, bool) and left == right
    if isinstance(left, (int, float)) and isinstance(right, (int, float)):
        return left == right
    if isinstance(left, str) and isinstance(right, str):
        return left == right
    return left is right


def _js_property(value, key):
    """`value[key]` of a JSON value; only objects have own properties."""
    return value.get(key, _UNDEFINED) if isinstance(value, dict) else _UNDEFINED


def _utf16_key(text):
    return text.encode('utf-16-be', 'surrogatepass')


def is_operation(operation):
    """Mirror of `prototype.js:isOperation` (P1)."""
    if not isinstance(operation, dict):
        return False
    for key in ('id', 'threadId', 'at'):
        value = operation.get(key)
        if not isinstance(value, str) or value == '':
            return False
    kind = operation.get('type')
    return any(kind == name for name in OPERATION_TYPES)


def normalize_operations(operations):
    """Mirror of `prototype.js:normalizeOperations`: drop invalid entries, first valid `id` wins."""
    seen, result = set(), []
    for operation in operations if isinstance(operations, list) else []:
        if not is_operation(operation) or operation['id'] in seen:
            continue
        seen.add(operation['id'])
        result.append(operation)
    return result


def sort_operations(operations):
    """Mirror of `prototype.js:sortOperations`: order by (`at`, `id`) as UTF-16 code units."""
    return sorted(operations, key=lambda operation: (_utf16_key(operation['at']), _utf16_key(operation['id'])))


def fold_operations(operations):
    """Mirror of `prototype.js:foldOperations`: thread states in creation order.

    Each thread is `{id, screen, anchor, label, resolved, messages}`.
    """
    ordered = sort_operations(normalize_operations(operations))
    deleted = {operation['threadId'] for operation in ordered if operation['type'] == 'delete'}
    threads, order = {}, []
    for operation in ordered:
        thread_id = operation['threadId']
        if thread_id in deleted:
            continue
        payload = operation.get('payload')
        if not isinstance(payload, dict):
            payload = {}
        thread = threads.get(thread_id)
        kind = operation['type']
        if kind == 'create':
            if thread is not None or not js_truthy(payload.get('message')) or not isinstance(payload.get('screen'), str):
                continue
            thread = {'id': thread_id, 'screen': payload['screen'],
                      'anchor': payload.get('anchor') if js_truthy(payload.get('anchor')) else '',
                      'label': payload.get('label') if js_truthy(payload.get('label')) else '',
                      'resolved': False, 'messages': [payload['message']]}
            threads[thread_id] = thread
            order.append(thread_id)
            continue
        if thread is None:
            continue
        if kind == 'reply' and js_truthy(payload.get('message')):
            message = payload['message']
            message_id = _js_property(message, 'id')
            if not any(_js_strict_equal(_js_property(item, 'id'), message_id) for item in thread['messages']):
                thread['messages'].append(message)
        elif kind == 'resolve':
            thread['resolved'] = True
        elif kind == 'reopen':
            thread['resolved'] = False
        elif kind == 'reanchor' and isinstance(payload.get('screen'), str):
            thread['screen'] = payload['screen']
            thread['anchor'] = payload.get('anchor') if js_truthy(payload.get('anchor')) else ''
            thread['label'] = payload.get('label') if js_truthy(payload.get('label')) else ''
    return [threads[thread_id] for thread_id in order]


def normalize_comments_document(value, slug):
    """Mirror of `prototype.js:normalizeCommentsDocument`: valid operations or `[]`."""
    if not isinstance(value, dict):
        return []
    version = value.get('version')
    if isinstance(version, bool) or not isinstance(version, (int, float)) or version != 1:
        return []
    if not isinstance(value.get('operations'), list):
        return []
    prototype_id = value.get('prototypeId')
    if js_truthy(prototype_id) and not (isinstance(prototype_id, str) and prototype_id == slug):
        return []
    return normalize_operations(value['operations'])


def _reject_constant(name):
    raise ValueError(f'Non-standard JSON constant: {name}')


def parse_comments_document(text):
    """Strict JSON from the first assignment to the last `;`; None when absent or invalid."""
    start = text.find(COMMENTS_ASSIGNMENT)
    if start < 0:
        return None
    start += len(COMMENTS_ASSIGNMENT)
    end = text.rfind(';')
    if end < start:
        return None
    try:
        return {'value': json.loads(text[start:end], parse_constant=_reject_constant)}
    except (ValueError, RecursionError):
        return None


def count_open_threads(text, slug):
    """Open threads in a `comments.js` text per the P1 engine; None without a parsable assignment."""
    parsed = parse_comments_document(text)
    if parsed is None:
        return None
    threads = fold_operations(normalize_comments_document(parsed['value'], slug))
    return sum(1 for thread in threads if not thread['resolved'])


