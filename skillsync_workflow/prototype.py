def _is_absolute(value):
    return os.path.isabs(value) or value.startswith(('/', '\\')) or re.match(r'[A-Za-z]:', value) is not None


def resolve_repo_path(root, value, label):
    """Resolve a manifest/CLI path inside the repository; return `(path, error)`.

    Absolute paths, lexical `..` escapes and symlinks leaving the repository (after realpath)
    are refused. The path does not have to exist.
    """
    if not isinstance(value, str) or not value.strip():
        return None, f'{label}: must be a nonempty string'
    if _is_absolute(value):
        return None, f'{label}: must be a path relative to the repository'
    normalized = os.path.normpath(value.replace('\\', '/'))
    if normalized == '..' or normalized.startswith('../'):
        return None, f'{label}: path escapes the repository'
    try:
        return contained(root, normalized), None
    except ValueError as error:
        reason = 'path escapes the repository (after resolving symlinks)' if 'escapes' in str(error) else str(error)
        return None, f'{label}: {reason}'
    except RuntimeError:
        return None, f'{label}: symbolic link loop'
    except OSError as error:
        return None, f'{label}: {error.strerror or error}'


def _path_kind(path, label):
    """Return `(kind, error)`: kind is `missing`, `dir`, `file` or `other` (symlinks followed);
    an OSError becomes a message with the key and the error name, never the absolute path."""
    try:
        mode = os.stat(path).st_mode
    except (FileNotFoundError, NotADirectoryError):
        return 'missing', None
    except OSError as error:
        return None, f'{label}: {error.strerror or type(error).__name__}'
    if stat.S_ISDIR(mode):
        return 'dir', None
    return ('file' if stat.S_ISREG(mode) else 'other'), None


def resolve_prototype_settings(section, root):
    """Validate the section and resolve its paths: dict with `errors`, `warnings`, `root`,
    `root_value`, `tokens_from`, `css`, `guidelines` (resolved `Path` or None) and
    `commit_before_iteration` (bool, default False; K40)."""
    settings = {'errors': [], 'warnings': [], 'root': None, 'root_value': DEFAULT_ROOT,
                'tokens_from': None, 'css': None, 'guidelines': None, 'commit_before_iteration': False}
    errors, warnings = settings['errors'], settings['warnings']
    if section is None:
        section = {}
    if not isinstance(section, dict):
        errors.append('prototype: must be a mapping')
        return settings
    for key in section:
        if key not in KNOWN_KEYS:
            warnings.append(f'prototype.{key}: unknown key (known: {", ".join(KNOWN_KEYS)})')
    if 'commit_before_iteration' in section:
        flag = section['commit_before_iteration']
        if not isinstance(flag, bool):
            errors.append('prototype.commit_before_iteration: must be true or false')
        else:
            settings['commit_before_iteration'] = flag
    root_value = section.get('root', DEFAULT_ROOT)
    path, error = resolve_repo_path(root, root_value, 'prototype.root')
    if error:
        errors.append(error)
    else:
        kind, error = _path_kind(path, 'prototype.root')
        if error:
            errors.append(error)
        elif kind not in ('missing', 'dir'):
            errors.append('prototype.root: exists and is not a directory')
        else:
            settings['root'], settings['root_value'] = path, root_value
    if 'theme' in section:
        theme = section['theme']
        if not isinstance(theme, dict):
            errors.append('prototype.theme: must be a mapping')
        else:
            for key in theme:
                if key not in THEME_KEYS:
                    warnings.append(f'prototype.theme.{key}: unknown key (known: {", ".join(THEME_KEYS)})')
            for key in THEME_KEYS:
                if key not in theme:
                    continue
                label = f'prototype.theme.{key}'
                path, error = resolve_repo_path(root, theme[key], label)
                kind = None
                if not error:
                    kind, error = _path_kind(path, label)
                if error:
                    errors.append(error)
                elif kind == 'missing':
                    errors.append(f'{label}: file does not exist: {theme[key]}')
                elif kind != 'file':
                    errors.append(f'{label}: not a regular file: {theme[key]}')
                else:
                    settings[key] = path
    if 'guidelines' in section:
        path, error = resolve_repo_path(root, section['guidelines'], 'prototype.guidelines')
        kind = None
        if not error:
            kind, error = _path_kind(path, 'prototype.guidelines')
        if error:
            errors.append(error)
        elif kind == 'missing':
            warnings.append(f'prototype.guidelines: file does not exist: {section["guidelines"]}')
        elif kind != 'file':
            warnings.append(f'prototype.guidelines: not a regular file: {section["guidelines"]}')
        else:
            settings['guidelines'] = path
    return settings


def validate_prototype(section, root):
    """Return `(errors, warnings)` for the optional `prototype:` section; each message starts with
    the key path. A missing (or null) section is valid and not inspected (the default `root` is
    checked by the CLI before any write); a missing `root` directory is valid."""
    if section is None:
        return [], []
    try:
        settings = resolve_prototype_settings(section, root)
    except OSError as error:
        return [f'prototype: {error.strerror or type(error).__name__}'], []
    except (ValueError, TypeError, RuntimeError) as error:
        return [safe_text(f'prototype: {error}')], []
    return [safe_text(item) for item in settings['errors']], [safe_text(item) for item in settings['warnings']]


# ── File system helpers ──────────────────────────────────────────────────────

def read_regular_bytes(path, limit):
    """Return `(data, reason)`; refuses symlinks, FIFOs, directories and files over `limit` bytes."""
    try:
        info = os.lstat(path)
    except FileNotFoundError:
        return None, 'missing'
    except OSError as error:
        return None, f'unreadable ({error.strerror or error})'
    if stat.S_ISLNK(info.st_mode):
        return None, 'is a symbolic link'
    if not stat.S_ISREG(info.st_mode):
        return None, 'not a regular file'
    if info.st_size > limit:
        return None, 'too large'
    flags = os.O_RDONLY | getattr(os, 'O_NOFOLLOW', 0) | getattr(os, 'O_NONBLOCK', 0) | getattr(os, 'O_BINARY', 0)
    try:
        descriptor = os.open(path, flags)
    except OSError as error:
        return None, f'unreadable ({error.strerror or error})'
    with os.fdopen(descriptor, 'rb') as handle:
        info = os.fstat(handle.fileno())
        if not stat.S_ISREG(info.st_mode):
            return None, 'not a regular file'
        data = handle.read(limit + 1)
    if len(data) > limit:
        return None, 'too large'
    return data, None


def read_regular_text(path, limit):
    data, reason = read_regular_bytes(path, limit)
    return (None, reason) if data is None else (data.decode('utf-8', errors='replace'), None)


def _umask():
    mask = os.umask(0)
    os.umask(mask)
    return mask


def atomic_write(path, content):
    """Write `content` (str) through a temporary file in the same directory and `os.replace`.

    A symlink or non-file target is refused; the temporary file is removed on any error.
    """
    path = Path(path)
    mode = 0o666 & ~_umask()
    if os.path.lexists(path):
        info = os.lstat(path)
        if stat.S_ISLNK(info.st_mode) or not stat.S_ISREG(info.st_mode):
            raise ValueError(f'Refusing to overwrite a symbolic link or non-file: {path.name}')
        mode = stat.S_IMODE(info.st_mode)
    descriptor, temporary = tempfile.mkstemp(prefix=f'.{path.name}.', suffix='.tmp', dir=path.parent)
    try:
        with os.fdopen(descriptor, 'w', encoding='utf-8', newline='\n') as handle:
            handle.write(content)
        os.chmod(temporary, mode)
        os.replace(temporary, path)
    except BaseException:
        try:
            os.unlink(temporary)
        except OSError:
            pass
        raise


def _relative(path, repo):
    relative = Path(path).relative_to(repo).as_posix()
    return relative or '.'


def is_prototype_dir(root, name):
    """Direct, non-symlink subdirectory named like a slug and holding `prototype.json` (any type)."""
    if not valid_slug(name):
        return False
    path = Path(root) / name
    try:
        info = os.lstat(path)
    except OSError:
        return False
    return stat.S_ISDIR(info.st_mode) and os.path.lexists(path / 'prototype.json')


def enumerate_prototypes(root):
    """Sorted `[(slug, path)]` of prototypes in `root`; empty when `root` is missing."""
    root = Path(root)
    if not root.is_dir():
        return []
    return [(name, root / name) for name in sorted(os.listdir(root)) if is_prototype_dir(root, name)]


def read_prototype_json(directory, slug):
    """Return `(data, error)`; `data` has the five string fields and `slug` equal to the directory."""
    text, reason = read_regular_text(Path(directory) / 'prototype.json', MAX_PROTOTYPE_JSON)
    if text is None:
        return None, f'prototype.json: {reason}'
    try:
        data = json.loads(text, parse_constant=_reject_constant)
    except (ValueError, RecursionError) as error:
        return None, f'prototype.json: invalid JSON ({error})'
    if not isinstance(data, dict):
        return None, 'prototype.json: must be a JSON object'
    for field in PROTOTYPE_FIELDS:
        if not isinstance(data.get(field), str):
            return None, f'prototype.json: field {field} must be a string'
        if not encodable(data[field]):
            return None, f'prototype.json: field {field} is not valid Unicode (lone surrogate)'
    if data['slug'] != slug:
        return None, f'prototype.json: slug {data["slug"]!r} does not match directory {slug!r}'
    return data, None


