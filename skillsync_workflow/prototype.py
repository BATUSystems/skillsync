def _blocked(code, reason, **extra):
    report = {'status': 'BLOCKED', 'error': code, 'reason': f'{code}: {reason}'}
    report.update(extra)
    return report


def _stdin_is_tty():
    try:
        return bool(sys.stdin.isatty())
    except (AttributeError, ValueError):
        return False


def accept_prototype(root, manifest, slug=None, screens=None, all_screens=False, project=False, by=None, users=None):
    """`accept` (K24, K43): acceptance of screens of the current files by a human at a terminal.

    Scope `screen` (`slug` + `--screen` …), `all` (`slug` + `--all`) or `project` (every v2 prototype, in
    the order of `slug`, each under its own lock).  Order of checks: stdin is a TTY (`tty_required`, before
    any prompt), `--by` has the role acceptor or developer (`forbidden`), no `mustChange`
    (`password_change_required`), the password read with `getpass` (`invalid_credentials`).  Written as
    `by: agent` with `who` = the login and `via: cli`.  The password and its hash never reach the output.
    BLOCKED (exit 2) carries `error`; a failure in `project` lists `accepted` and `pending`.  Screens whose
    section is ambiguous (duplicate id, unclosed) are left out of `all`/`project` and listed in `skippedScreens`.
    """
    if not _stdin_is_tty():
        return _blocked('tty_required', 'accept needs a terminal: the password of --by is read from the TTY')
    screens = list(screens or [])
    if project:
        if slug is not None or screens or all_screens:
            raise PrototypeError('--project takes no slug, --screen or --all')
    elif slug is None or bool(screens) == bool(all_screens):
        raise PrototypeError('accept needs <slug> with --screen sN (repeatable) or --all, or --project')
    for screen in screens:
        if not server.SCREEN_ID_RE.fullmatch(screen):
            raise PrototypeError(f'Invalid screen id {screen!r}')
    if not isinstance(by, str) or not by.strip():
        raise PrototypeError('accept needs --by LOGIN')
    repo = Path(root).resolve()
    settings = _settings(repo, manifest)
    login = server.normalize_login(by)
    account, warnings = _users(repo, users)
    record = account.get(login) if account.exists() else None
    if record is None or not server.has_privileged_role(record):
        return _blocked('forbidden', f'--by must be an account with the role acceptor or developer '
                        f'(checked in {_relative_or_absolute(account.path, repo)})')
    if record['mustChange']:
        return _blocked('password_change_required', f'{login} must change the password first (sign in to the server)')
    try:
        password = getpass.getpass(f'Hasło {login}: ')
    except (EOFError, KeyboardInterrupt):
        return _blocked('tty_required', 'the password was not entered')
    if not server.verify_password(password, record['password']):
        return _blocked('invalid_credentials', 'wrong password')
    del password
    scope = 'project' if project else ('all' if all_screens else 'screen')
    if project:
        targets = list(enumerate_prototypes(settings['root']))
    else:
        targets = [(slug, _prototype_directory(repo, settings, slug))]
    accepted, skipped, skipped_screens = [], [], []
    pending = [name for name, _directory in targets]
    for name, directory in targets:
        store = _store(directory, name)
        state = store.state()
        if state == 'v1':
            if not project:
                return _server_blocked(server.NeedsMigration())
            skipped.append(name)
            pending.remove(name)
            continue

        def build(snapshot, directory=directory, name=name):
            info = server.screen_hashes(str(directory))
            hashes = info['screens']
            wanted = screens if scope == 'screen' else sorted(hashes, key=server._utf16_key)
            if scope != 'screen':
                skipped_screens.extend({'slug': name, 'screen': item['screen'], 'reason': item['problem']}
                                       for item in server.unique_problems(info['ambiguous']))
            unknown = [screen for screen in wanted if screen not in hashes]
            if unknown:
                raise server.OperationError(400, 'unknown_screen', server.unknown_screen_message(unknown, info['ambiguous']),
                                            {'screens': unknown})
            if not wanted:
                return []
            return {'type': 'accept', 'by': 'agent',
                    'payload': {'scope': scope, 'screens': {screen: hashes[screen] for screen in wanted},
                                'iteration': snapshot.fold['currentIteration'], 'via': 'cli', 'who': login}}

        try:
            result = store.transaction(build)
        except (server.PrototypeServerError, OSError) as error:
            if isinstance(error, server.PrototypeServerError):
                report = _server_blocked(error)
            else:
                report = _blocked('write_failed', str(error) or type(error).__name__)
            if project:
                report.update({'accepted': accepted, 'pending': pending})
            return report
        pending.remove(name)
        if result.operations:
            accepted.append({'slug': name, 'screens': sorted(result.operations[0]['payload']['screens'],
                                                            key=server._utf16_key)})
        else:
            skipped.append(name)
    report = {'status': 'PASS', 'accepted': accepted, 'skipped': skipped, 'who': login, 'via': 'cli'}
    if skipped_screens:
        report['skippedScreens'] = skipped_screens
    if warnings:
        report['warnings'] = warnings
    return report


# ── Gate: accepted prototypes before the implementation (K26) ────────────────

GATE_PROTOTYPE_LINE = re.compile(r'Prototyp:[ \t]*`?([^\s`]+)`?[ \t]*')
# `— <osoba>, <data>`: any name or nick of the person who allowed the bypass (no dash or comma inside).
GATE_BYPASS_LINE = re.compile(r'Bramka prototypu: pominięta — (?P<reason>.+?) — (?P<by>[^\s—,][^—,\n]*?), '
                              r'(?P<date>[0-9]{4}-[0-9]{2}-[0-9]{2})[ \t]*')
# Near misses (typos, bullets, bold, a space before the colon) are refused instead of being ignored (fail closed).
_NEAR_PROTOTYPE = re.compile(r'(?i)^[ \t]*(?:(?:[-*+>]|[0-9]+[.)])[ \t]*)*[*_]{0,2}prototype?[*_]{0,2}[ \t]*:')
_NEAR_BYPASS = re.compile(r'(?i)^\W*bramka\s+prototypu')
MAX_GATE_PLAN = 1024 * 1024


def _plan_header(text):
    """The plan header: the text before the first line starting with `## `."""
    lines = []
    for line in text.splitlines():
        if line.startswith('## '):
            break
        lines.append(line.rstrip('\r'))
    return lines


def _gate_line_kind(line):
    """`'prototype'`, `'bypass'` or None: a header line that is, or nearly is, a gate line."""
    if line.lstrip().startswith('#'):
        return None
    if _NEAR_PROTOTYPE.match(line):
        return 'prototype'
    if _NEAR_BYPASS.match(line):
        return 'bypass'
    return None


def plan_has_gate_lines(text):
    """True when the plan header has a `Prototyp:` or a `Bramka prototypu:` line, also a malformed one."""
    return any(_gate_line_kind(line) for line in _plan_header(text))


def _gate_path(repo, value):
    """Directory of a `Prototyp:` path (relative to the project, inside it, no symlinks) or None."""
    try:
        path = contained(repo, value)
    except (ValueError, OSError):
        return None
    current = repo
    for part in Path(value).parts:
        current = current / part
        if current.is_symlink():
            return None
    if not path.is_dir() or not os.path.lexists(path / 'prototype.json'):
        return None
    return path


def prototype_gate(root, manifest, plan=None, slugs=None, phase=None):
    """`gate` (K26): every screen (without `data-prototype-example`) of the named prototypes needs a current
    acceptance.  Prototypes come from the `Prototyp:` lines of the plan header or from `slugs` (under
    `prototype.root`).  PASS; FAIL (exit 1) with `missing: [{slug, path, screen, reason}]` (`brak`,
    `nieaktualna`, `needs_migration`, `brak_ekranow`, `niejednoznaczny_ekran` for a duplicate id or an unclosed screen); BLOCKED (exit 2) with `error` for a bad plan, line or
    prototype.  A header line `Bramka prototypu: pominięta — <powód> — <osoba>, <RRRR-MM-DD>` turns FAIL into
    PASS with `bypassed`.  Shared by `readiness --plan`.

    Phases: a plan with a `[UI]` phase (table of steps, `plan_phases`) needs a `Prototyp:` line or the bypass
    (else BLOCKED `ui_phase_without_prototype`); `phase` (only with `plan`) must be a known phase id (else BLOCKED
    `unknown_phase`) and a phase without `[UI]` of such a plan passes with an empty `missing` list (or `bypassed` under an owner bypass).  A plan without
    `[UI]` phases keeps the whole-plan result and only gets `phase`.
    """
    repo = Path(root).resolve()
    if bool(plan) == bool(slugs):
        raise PrototypeError('gate needs --plan FILE or one or more prototype slugs (not both)')
    if phase is not None and not plan:
        raise PrototypeError('--phase needs --plan FILE')
    targets, bypass, report = [], None, {}
    phase_info = None
    if plan:
        plan_path = contained(repo, plan)
        text, reason = read_regular_text(plan_path, MAX_GATE_PLAN)
        if text is None:
            return _blocked('plan_unreadable', f'{plan}: {reason}')
        report['plan'] = _relative_or_absolute(plan_path, repo)
        phase_info = parse_plan_phases(text)
        bypasses = 0
        for line in _plan_header(text):
            kind = _gate_line_kind(line)
            if kind == 'prototype':
                match = GATE_PROTOTYPE_LINE.fullmatch(line)
                if not match:
                    return _blocked('invalid_prototype_line', f'Prototyp: line must hold one path: {line[:200]}')
                if match.group(1) not in targets:
                    targets.append(match.group(1))
            elif kind == 'bypass':
                match = GATE_BYPASS_LINE.fullmatch(line)
                bypasses += 1
                valid_date = False
                if match:
                    try:
                        date.fromisoformat(match.group('date'))
                        valid_date = True
                    except ValueError:
                        pass
                if not match or not valid_date or bypasses > 1:
                    return _blocked('invalid_bypass_line', 'expected one line: Bramka prototypu: pominięta — <powód> '
                                    '— <osoba>, <RRRR-MM-DD>')
                bypass = {'reason': match.group('reason'), 'by': match.group('by'), 'date': match.group('date')}
        resolved = []
        for value in targets:
            directory = _gate_path(repo, value)
            if directory is None:
                return _blocked('prototype_not_found', f'{value} is not a prototype directory of this project',
                                path=value)
            resolved.append((directory.name, directory))
        ui_phases = phase_info['ui_phases']
        if ui_phases:
            report.update({'phases': phase_info['phases'], 'uiPhases': ui_phases})
        if phase is not None and phase not in phase_info['phases']:
            return {**report, **_blocked('unknown_phase', f'{phase} is not a phase of the plan (known: '
                                         f'{", ".join(phase_info["phases"]) or "none"})')}
        if ui_phases:
            report.update({'phases': phase_info['phases'], 'uiPhases': ui_phases})
            if not targets and bypass is None:
                return {**report, **_blocked('ui_phase_without_prototype', 'the plan has [UI] phases ('
                        f'{", ".join(ui_phases)}) but no Prototyp: line and no bypass line',
                        **({'phase': phase} if phase is not None else {}))}
        if phase is not None:
            report['phase'] = phase
        if ui_phases and phase is not None and phase not in ui_phases and bypass is None:
            report.update({'status': 'PASS', 'prototypes': [], 'missing': [], 'acceptances': [],
                           'note': 'faza bez znacznika [UI]'})
            return report
    else:
        settings = _settings(repo, manifest)
        resolved = []
        for slug in dict.fromkeys(slugs):
            if not is_prototype_dir(settings['root'], slug):
                return _blocked('prototype_not_found', f'no prototype {slug} under {_relative(settings["root"], repo)}',
                                path=slug)
            resolved.append((slug, settings['root'] / slug))
    prototypes, missing, acceptances = [], [], []
    for slug, directory in resolved:
        path = _relative(directory, repo)
        store = _store(directory, slug)
        if store.state() == 'v1':
            prototypes.append({'path': path, 'slug': slug, 'format': 1, 'iteration': None, 'screens': None})
            missing.append({'slug': slug, 'path': path, 'screen': None, 'reason': 'needs_migration'})
            continue
        try:
            fold = store.snapshot().fold
            info = server.screen_hashes(str(directory))
            hashes = info['screens']
        except server.PrototypeServerError as error:
            return _blocked(error.code, f'{path}: {error.message}', path=path)
        except OSError as error:
            return _blocked('prototype_unreadable', f'{path}: {error.strerror or error}', path=path)
        state = server.acceptance_state(fold, hashes, info.get('aliases'))
        prototypes.append({'path': path, 'slug': slug, 'format': 2, 'iteration': fold['currentIteration'],
                           'screens': len(hashes)})
        problems = server.unique_problems(info['ambiguous'])
        if not hashes and not problems:
            missing.append({'slug': slug, 'path': path, 'screen': None, 'reason': 'brak_ekranow'})
        for screen in sorted(hashes, key=server._utf16_key):
            entry = state.get(screen)
            if entry is None:
                missing.append({'slug': slug, 'path': path, 'screen': screen, 'reason': 'brak'})
            elif not entry['valid']:
                missing.append({'slug': slug, 'path': path, 'screen': screen, 'reason': 'nieaktualna'})
            else:
                acceptances.append({'slug': slug, 'screen': screen, 'who': entry['who'], 'at': entry['at'],
                                    'via': entry['via'], 'iteration': entry['iteration']})
        for item in problems:
            missing.append({'slug': slug, 'path': path, 'screen': item['screen'], 'reason': 'niejednoznaczny_ekran'})
    status = 'FAIL' if missing and bypass is None else 'PASS'
    report.update({'status': status, 'prototypes': prototypes, 'missing': missing, 'acceptances': acceptances})
    if bypass is not None:
        report['bypassed'] = bypass
    if plan and not resolved and bypass is None:
        report['note'] = 'plan bez linii Prototyp:'
    return report


def _status_filter(value):
    if value is None or value == 'open':
        return ['open']
    if value == 'all':
        return list(server.STATUSES)
    statuses = [item.strip() for item in value.split(',') if item.strip()]
    unknown = [item for item in statuses if item not in server.STATUSES]
    if unknown or not statuses:
        raise PrototypeError(f'--status: unknown status {", ".join(unknown) or value!r} '
                             f'(use {", ".join(server.STATUSES)} or all)')
    return statuses


