def prototype_now(environ=None):
    """Creation time `RRRR-MM-DDTHH:MM:SSZ`; `SKILLSYNC_PROTOTYPE_NOW` (ISO 8601 with `Z` or offset)
    overrides the clock. An invalid value raises `PrototypeError`."""
    environ = os.environ if environ is None else environ
    value = environ.get(NOW_ENV)
    if value is None:
        moment = datetime.now(timezone.utc)
    else:
        text = value[:-1] + '+00:00' if value.endswith(('Z', 'z')) else value
        try:
            moment = datetime.fromisoformat(text)
        except ValueError:
            raise PrototypeError(f'{NOW_ENV} is not an ISO 8601 date-time: {value!r}') from None
        if moment.tzinfo is None or moment.utcoffset() is None:
            raise PrototypeError(f'{NOW_ENV} must include Z or a UTC offset: {value!r}')
    try:
        moment = moment.astimezone(timezone.utc)
    except OverflowError:
        raise PrototypeError(f'{NOW_ENV} is out of range after conversion to UTC: {value!r}') from None
    if not 1000 <= moment.year <= 9999:
        raise PrototypeError(f'{NOW_ENV} year must be between 1000 and 9999 in UTC: {value!r}')
    return moment.strftime('%Y-%m-%dT%H:%M:%SZ')


