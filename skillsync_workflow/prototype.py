def _run(action, assets=False):
    """CLI handler. Only actions reading prototype assets (`assets=True`: init, sync, migrate) resolve
    the layers, and only without `--assets`; the rest needs just the project and its manifest."""
    def handler(args):
        try:
            if assets and not args.assets:
                root, manifest, layerset = load_layer_project(args.path, args.layers)
            else:
                (root, manifest), layerset = read_project(args.path), None
            report = action(args, root, manifest, layerset)
        except server.PrototypeServerError as error:
            report = {'status': 'BLOCKED', 'reason': f'{error.code}: {error.message}'}
        except server.UserError as error:
            report = {'status': 'BLOCKED', 'reason': f'{error.code}: {error.message}'}
        except PrototypeError as error:
            report = {'status': 'BLOCKED', 'reason': str(error)}
            if error.errors:
                report['errors'] = error.errors
        except (OSError, ValueError, TypeError, RuntimeError, OverflowError, yaml.YAMLError, subprocess.SubprocessError) as error:
            report = {'status': 'BLOCKED', 'reason': str(error) or type(error).__name__}
        return emit(safe_report(report))
    return handler


