def _read_comments_file(path, slug=None):
    data, reason = read_regular_bytes(path, MAX_COMMENTS_READ)
    if data is None:
        raise PrototypeError(f'{path}: {reason}')
    try:
        return server.parse_document(data.decode('utf-8'), slug)
    except UnicodeDecodeError:
        raise PrototypeError(f'{path}: not UTF-8') from None
    except server.CommentsFileError as error:
        raise PrototypeError(f'{path}: {error.message}') from None


def _merge_report(merged, added, directory, extra=None):
    missing = server.missing_iterations(directory, merged) if directory is not None else None
    report = {'status': 'PASS', 'added': len(added), 'total': len(merged), 'missingIterations': missing}
    report.update(extra or {})
    warnings = []
    if missing:
        warnings.append('operations without iterations/<n>/ in the working copy: '
                        + ', '.join(f'{item["type"]} {item["number"]}' for item in missing))
    if missing is None:
        warnings.append('missingIterations not checked: the prototype directory was not found from the current directory')
    if warnings:
        report['warnings'] = warnings
    return report


def merge_comments_prototype(root, manifest, slug, other):
    """`merge-comments <path> <slug> <other>` (K29): appends to `comments.json` the operations of
    `other` (relative to the project) missing by `id`, in `other`'s order, under the prototype lock."""
    repo, settings, directory, store = _prototype_context(root, manifest, slug)
    if store.state() == 'v1':
        raise PrototypeError('needs_migration: prototype v1 (comments.js): run `skillsync prototype migrate` first')
    other_path = users_file_path(repo, other)
    incoming = _read_comments_file(other_path, slug)
    try:
        with store.lock():
            snapshot = store.snapshot()
            merged, added = server.merge_operations(snapshot.operations, incoming.operations)
            if added:
                data = server.serialize_document(slug, merged).encode('utf-8')
                server.atomic_write_bytes(store.path, data)
    except server.PrototypeServerError as error:
        return _server_blocked(error)
    return _merge_report(merged, added, str(directory), {'slug': slug})


def _driver_directory(prototype_id):
    """Working copy directory of `prototype_id` for the git driver (cwd = top of the repository)."""
    try:
        root, manifest = read_project('.')
        settings = resolve_prototype_settings(manifest.get('prototype'), Path(root))
    except (ValueError, OSError, yaml.YAMLError):
        return None
    if settings['errors'] or settings['root'] is None or not is_prototype_dir(settings['root'], prototype_id):
        return None
    return str(settings['root'] / prototype_id)


def merge_comments_driver(ancestor, current, other):
    """`merge-comments --driver %O %A %B`: result = A + operations of B missing in A, written to A.
    `prototypeId` comes from the files (B must match A); a conflict leaves A untouched (exit 2)."""
    current_path, other_path = Path(current), Path(other)
    mine = _read_comments_file(current_path)
    theirs = _read_comments_file(other_path)
    if theirs.prototype_id != mine.prototype_id:
        raise PrototypeError(f'prototypeId differs: {mine.prototype_id} (A) and {theirs.prototype_id} (B)')
    try:
        merged, added = server.merge_operations(mine.operations, theirs.operations)
    except server.PrototypeServerError as error:
        return _server_blocked(error)
    if added:
        server.atomic_write_bytes(str(current_path), server.serialize_document(mine.prototype_id, merged).encode('utf-8'))
    return _merge_report(merged, added, _driver_directory(mine.prototype_id),
                         {'slug': mine.prototype_id, 'driver': True})


