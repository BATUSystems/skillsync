def _read_asset(path):
    """UTF-8 text without newline translation (copies stay byte-exact)."""
    return Path(path).read_bytes().decode('utf-8')


def _read_project_text(path):
    """Project stylesheet as text: UTF-8 with an optional BOM dropped, no newline translation."""
    return Path(path).read_bytes().decode('utf-8-sig')


def _error_text(error, repo):
    """Readable error without absolute paths (OSError filenames shown relative to the project)."""
    if isinstance(error, OSError) and error.strerror:
        name = error.filename
        if name is None:
            return error.strerror
        try:
            shown = Path(os.fsdecode(name)).resolve().relative_to(repo).as_posix()
        except (ValueError, OSError):
            shown = Path(os.fsdecode(name)).name
        return f'{error.strerror}: {shown}'
    return str(error).replace(str(repo) + os.sep, '')


def build_theme_files(settings, theme_assets, repo):
    """Return `(tokens_css, theme_css, warnings)` from assets and the manifest theme files."""
    default_css = _read_asset(theme_assets['theme/default.css'])
    required = parse_required_tokens(_read_asset(theme_assets['theme/required-tokens.txt']))
    project_tokens = theme_css_source = None
    name = 'tokens_from'
    if settings['tokens_from'] is not None:
        name = _relative(settings['tokens_from'], repo)
        project_tokens = _read_project_text(settings['tokens_from'])
    if settings['css'] is not None:
        theme_css_source = _read_project_text(settings['css'])
    tokens_css, warnings = compose_tokens_css(default_css, project_tokens, name)
    theme_css = compose_theme_css(theme_css_source)
    missing = missing_required_tokens(required, tokens_css, theme_css)
    if missing:
        warnings.append(f'Missing required tokens: {", ".join(missing)}')
    return tokens_css, theme_css, warnings


def _check_root_ancestors(repo, root_value, root_path):
    """Every existing component of `root` must resolve inside the repository and be a directory."""
    current = Path(repo)
    for part in Path(os.path.normpath(root_value.replace('\\', '/'))).parts:
        if part in ('', '.'):
            continue
        current = current / part
        if not os.path.lexists(current):
            break
        real = Path(os.path.realpath(current))
        if not real.is_relative_to(repo):
            raise PrototypeError(f'prototype.root: {current.relative_to(repo).as_posix()} resolves outside the repository')
        if not real.is_dir():
            raise PrototypeError(f'prototype.root: {current.relative_to(repo).as_posix()} is not a directory')
    if not root_path.is_relative_to(repo):
        raise PrototypeError('prototype.root: path escapes the repository')


def _target_exists(path):
    """Existence check of a prototype target (directory, file or symlink); patchable in tests."""
    return os.path.lexists(path)


def _make_staging(root, slug):
    for _ in range(100):
        path = Path(root) / f'.{slug}-staging-{secrets.token_hex(6)}'
        try:
            os.mkdir(path)
            return path
        except FileExistsError:
            continue
    raise PrototypeError('Cannot create a staging directory')


def init_prototype(root, manifest, layerset, slug, requirements, title=None, assets=None, environ=None):
    repo = Path(root).resolve()
    settings = _settings(repo, manifest)
    warnings = list(settings['warnings'])
    if not valid_slug(slug):
        raise PrototypeError(f'Invalid slug {slug!r}: use lowercase letters, digits and single hyphens')
    if title is None:
        title = default_title(slug)
    reason = title_error(title)
    if reason:
        raise PrototypeError(reason)
    requirements_path, error = resolve_repo_path(repo, requirements, '--requirements')
    if error:
        raise PrototypeError(error)
    if not requirements_path.is_file():
        raise PrototypeError(f'--requirements: not an existing regular file in the repository: {safe_text(requirements)}')
    requirements_value = _relative(requirements_path, repo)
    try:
        requirements_value.encode('utf-8')
    except UnicodeEncodeError:
        raise PrototypeError('--requirements: path is not valid UTF-8') from None
    created = prototype_now(environ)
    paths = asset_paths(layerset, [f'repo/{name}' for name in STATIC_FILES + TEMPLATE_FILES]
                        + [f'theme/{name}' for name in THEME_FILES], assets)
    tokens_css, theme_css, theme_warnings = build_theme_files(settings, paths, repo)
    warnings += theme_warnings
    fields = {'TITLE': title, 'SLUG': slug, 'REQUIREMENTS': requirements_value}
    rendered = {name: render_template(_read_asset(paths[f'repo/{name}']), fields) for name in TEMPLATE_FILES}
    missing = missing_theme_links(rendered['index.html'])
    if missing:
        warnings.append(f'index.html does not link {", ".join(missing)}')
    metadata = {'slug': slug, 'title': title, 'requirements': requirements_value, 'created': created,
                'generated_by': GENERATED_BY}
    prototypes_root = settings['root']
    _check_root_ancestors(repo, settings['root_value'], prototypes_root)
    target = prototypes_root / slug
    if _target_exists(target):
        raise PrototypeError(f'Prototype already exists: {_relative(target, repo)}')
    os.makedirs(prototypes_root, exist_ok=True)
    staging = _make_staging(prototypes_root, slug)
    try:
        for name in STATIC_FILES:
            shutil.copyfile(paths[f'repo/{name}'], staging / name)
        contents = dict(rendered)
        contents['tokens.css'] = tokens_css
        contents['theme.css'] = theme_css
        contents[PROJECT_CSS] = PROJECT_CSS_TEXT
        contents['prototype.json'] = json.dumps(metadata, ensure_ascii=False, indent=2) + '\n'
        for name, content in contents.items():
            with open(staging / name, 'x', encoding='utf-8', newline='\n') as handle:
                handle.write(content)
        if _target_exists(target):
            raise PrototypeError(f'Prototype already exists: {_relative(target, repo)}')
        os.rename(staging, target)
    except BaseException:
        shutil.rmtree(staging, ignore_errors=True)
        raise
    files = sorted(_relative(target / name, repo) for name in os.listdir(target))
    report = {'status': 'PASS', 'path': _relative(target, repo), 'files': files}
    if warnings:
        report['warnings'] = warnings
    return report


def sync_prototypes(root, manifest, layerset, slug=None, check=False, assets=None):
    repo = Path(root).resolve()
    settings = _settings(repo, manifest)
    warnings = list(settings['warnings'])
    if slug is not None and not valid_slug(slug):
        raise PrototypeError(f'Invalid slug {slug!r}: use lowercase letters, digits and single hyphens')
    paths = asset_paths(layerset, [f'theme/{name}' for name in THEME_FILES], assets)
    tokens_css, theme_css, theme_warnings = build_theme_files(settings, paths, repo)
    warnings += theme_warnings
    prototypes_root = settings['root']
    if slug is not None:
        if not is_prototype_dir(prototypes_root, slug):
            raise PrototypeError(f'Prototype not found: {_relative(prototypes_root / slug, repo)}')
        targets = [(slug, prototypes_root / slug)]
    else:
        targets = enumerate_prototypes(prototypes_root)
    expected = {'tokens.css': tokens_css.encode('utf-8'), 'theme.css': theme_css.encode('utf-8')}
    processed, files, stale, failed = [], [], [], []
    for name, directory in targets:
        try:
            _, error = read_prototype_json(directory, name)
            if error:
                raise PrototypeError(error)
            current = {}
            for file_name in GENERATED_FILES:
                path = directory / file_name
                if os.path.lexists(path):
                    info = os.lstat(path)
                    if stat.S_ISLNK(info.st_mode) or not stat.S_ISREG(info.st_mode):
                        raise PrototypeError(f'{file_name}: refusing a symbolic link or non-file')
                data, reason = read_regular_bytes(path, len(expected[file_name]))
                if data is None and reason not in ('missing', 'too large'):
                    raise PrototypeError(f'{file_name}: {reason}')
                current[file_name] = data
            changed = [file_name for file_name in GENERATED_FILES if current[file_name] != expected[file_name]]
            if check:
                stale += [_relative(directory / file_name, repo) for file_name in changed]
            else:
                for file_name in changed:
                    atomic_write(directory / file_name, expected[file_name].decode('utf-8'))
                    files.append(_relative(directory / file_name, repo))
            processed.append(name)
        except (OSError, ValueError, TypeError, RuntimeError) as error:
            failed.append({'slug': name, 'path': _relative(directory, repo), 'error': _error_text(error, repo)})
    report = {'status': 'PASS', 'root': _relative(prototypes_root, repo)}
    if check:
        report['checked'] = processed
        report['stale'] = stale
        if stale:
            report['status'] = 'FAIL'
    else:
        report['synced'] = processed
        report['files'] = files
    if failed:
        report['status'] = 'BLOCKED'
        report['reason'] = f'{len(failed)} prototype(s) failed'
        report['failed'] = failed
    if warnings:
        report['warnings'] = warnings
    return report


MAX_COMMENTS_READ = 4 * server.MAX_FILE_BYTES


def prototype_comments_info(directory, slug, html=None):
    """`(fields, warnings)` of the comment log for `list`/`index`.

    `fields` = `{comments, commentsFormat, threads, iteration, acceptance}`: v2 (`comments.json`)
    gives the open-thread count (open/awaiting/decided), `commentsFormat: 2` and `threads`
    by status (`lost` resolved against `html` with the shared `data-proto-id` collector);
    v1 (`comments.js` only) gives the v1 count and `commentsFormat: 1`; no file gives nulls.
    `iteration` = current iteration of the v2 log (1 + largest `iteration.number`; null for v1);
    `acceptance` = `{screens, accepted, stale}` of the v2 log against the hashes of the current files
    (screens without examples; null for v1, no file or unreadable files).
    """
    directory = Path(directory)
    fields = {'comments': None, 'commentsFormat': None, 'threads': None, 'iteration': None, 'acceptance': None}
    warnings = []
    if os.path.lexists(directory / server.COMMENTS_FILE):
        fields['commentsFormat'] = 2
        data, reason = read_regular_bytes(directory / server.COMMENTS_FILE, MAX_COMMENTS_READ)
        if data is None:
            warnings.append(f'comments.json: {reason}')
            return fields, warnings
        if len(data) >= server.WARN_FILE_BYTES:
            warnings.append(f'comments.json has {len(data) // (1024 * 1024)} MiB (warning from 10 MiB, '
                            f'the server refuses writes from 20 MiB)')
        try:
            document = server.parse_document(data.decode('utf-8'), slug)
        except UnicodeDecodeError:
            warnings.append('comments.json: not UTF-8')
            return fields, warnings
        except server.CommentsFileError as error:
            warnings.append(f'comments.json: {error.message}')
            return fields, warnings
        fold = server.fold_operations(document.operations)
        fields['comments'] = server.open_thread_count(fold)
        fields['iteration'] = fold['currentIteration']
        screen_ids = proto_ids = None
        if html is not None:
            collected = server.collect_proto_ids(html)
            screen_ids = {screen['id'] for screen in collected['screens']}
            proto_ids = {screen: set(values) for screen, values in collected['byScreen'].items()}
        fields['threads'] = server.thread_counts(fold, screen_ids, proto_ids)
        try:
            hashes = server.screen_hashes(str(directory))
        except OSError:
            hashes = None
        if hashes is not None:
            state = server.acceptance_state(fold, hashes['screens'])
            valid = sum(1 for item in state.values() if item['valid'])
            fields['acceptance'] = {'screens': len(hashes['screens']), 'accepted': valid, 'stale': len(state) - valid}
        if os.path.lexists(directory / server.LEGACY_COMMENTS_FILE):
            warnings.append('comments.js left next to comments.json: run `skillsync prototype migrate` '
                            'to check it against comments.json and remove it')
        if fold['iterationDuplicates']:
            warnings.append('comments.json: duplicated iteration number(s): '
                            + ', '.join(str(number) for number in fold['iterationDuplicates']))
        return fields, warnings
    if os.path.lexists(directory / server.LEGACY_COMMENTS_FILE):
        fields['commentsFormat'] = 1
        fields['comments'] = prototype_comments(directory, slug)
        warnings.append('prototype v1 (comments.js): run `skillsync prototype migrate`')
    return fields, warnings


def _describe(slug, directory, repo):
    """`(entry, warnings)` of one prototype for `list` and `index`."""
    data, error = read_prototype_json(directory, slug)
    path = _relative(directory, repo)
    if error:
        return {'slug': slug, 'path': path, 'error': error}, []
    html, _ = read_regular_text(Path(directory) / 'index.html', MAX_SCAN_BYTES)
    entry = {'slug': slug, 'title': data['title'], 'requirements': data['requirements'], 'created': data['created'],
             'generated_by': data['generated_by'], 'path': path,
             'screens': None if html is None else count_screens(html)}
    fields, warnings = prototype_comments_info(directory, slug, html)
    entry.update(fields)
    return entry, [f'{path}: {warning}' for warning in warnings]


def list_prototypes(root, manifest):
    repo = Path(root).resolve()
    settings = _settings(repo, manifest)
    warnings = list(settings['warnings'])
    entries = []
    for slug, directory in enumerate_prototypes(settings['root']):
        entry, entry_warnings = _describe(slug, directory, repo)
        if 'error' in entry:
            warnings.append(f'{entry["path"]}: {entry["error"]}')
        warnings.extend(entry_warnings)
        entries.append(entry)
    report = {'status': 'PASS', 'root': _relative(settings['root'], repo), 'prototypes': entries}
    if warnings:
        report['warnings'] = warnings
    return report


