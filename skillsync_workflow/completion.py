"""`skillsync completion`: shell completion scripts generated from the argparse tree (CORE-COMPLETION).

The tree is read at the time the command runs, through `choices` of the registered sub-parsers action, so a command added by any other module enters
the script by itself. The scripts are standalone: they never start `skillsync` while the user presses Tab.
"""
import argparse
import json
import re
import sys

from . import __version__

SHELLS = ('bash', 'zsh', 'powershell')
ROOT_FLAGS = ('--help', '--version', '-h')
PATH_WORDS = frozenset({'path', 'project', 'file', 'dir', 'directory'})
SCHEMA = 1

_SUBPARSERS = None


def register(subparsers):
    global _SUBPARSERS
    _SUBPARSERS = subparsers
    parser = subparsers.add_parser('completion', help='Shell completion for bash, zsh and PowerShell (print a script, install or remove it)')
    actions = parser.add_subparsers(dest='completion_action', required=True)
    for shell in SHELLS:
        sub = actions.add_parser(shell, help=f'Print the {shell} completion script to stdout')
        sub.set_defaults(func=_cmd_print, shell=shell)
    for name, text in (('install', 'Install the completion script for the shells found on this machine'),
                       ('uninstall', 'Remove the completion script and its block in the shell startup file')):
        sub = actions.add_parser(name, help=text)
        sub.add_argument('--shell', action='append', choices=SHELLS, help='Limit to this shell (repeatable)')
        sub.add_argument('--dry-run', action='store_true', help='Show what would change; write nothing')
        sub.add_argument('--json', action='store_true')
        sub.add_argument('--auto', action='store_true', help='Called by an installer: honour SKILLSYNC_NO_COMPLETION, stay quiet when nothing changes')
        sub.set_defaults(func=_cmd_stub, action_name=name)


def _cmd_print(args):
    data = render(args.shell, _SUBPARSERS).encode('utf-8')
    sys.stdout.flush()
    sys.stdout.buffer.write(data)
    sys.stdout.buffer.flush()
    return 0


def _cmd_stub(args):
    message = f'completion {args.action_name}: not implemented yet'
    if args.json:
        print(json.dumps({'schema': SCHEMA, 'status': 'NOT_RUN', 'dry_run': args.dry_run, 'actions': [], 'warnings': [message]}, indent=2))
    else:
        print(message, file=sys.stderr)
    return 2


# -- the model of the tree

def path_words(text):
    text = re.sub(r'([a-z0-9])([A-Z])', r'\1 \2', str(text))
    text = re.sub(r'([A-Z]+)([A-Z][a-z])', r'\1 \2', text)
    return [word.lower() for word in re.split(r'[-_\s]+', text) if word]


def is_path(action):
    name = action.metavar if isinstance(action.metavar, str) else action.dest
    return bool(PATH_WORDS & set(path_words(name)))


def _flag_kind(action):
    if action.nargs == 0:
        return 'none'
    if action.choices:
        return 'choices'
    return 'path' if is_path(action) else 'value'


def _flags(parser):
    flags = {}
    for action in parser._actions:
        if action.option_strings and action.help != argparse.SUPPRESS:
            for flag in action.option_strings:
                flags[flag] = (_flag_kind(action), [str(item) for item in action.choices or ()])
    return flags


def _positionals(parser):
    choices, path = [], False
    for action in parser._actions:
        if action.option_strings or isinstance(action, argparse._SubParsersAction) or action.dest == 'help' or action.help == argparse.SUPPRESS:
            continue
        if action.choices:
            choices += [str(item) for item in action.choices]
        elif is_path(action):
            path = True
    return choices, path


def _children(parser):
    children = {}
    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction):
            children.update(action.choices)
    return children


def _walk(parser, path, nodes):
    children = _children(parser)
    choices, has_path = _positionals(parser)
    nodes[path] = {'subs': sorted(children), 'flags': _flags(parser), 'pos_choices': choices, 'pos_path': has_path}
    for name, child in children.items():
        _walk(child, path + (name,), nodes)


def build_model(subparsers):
    """`{command path (tuple): {subs, flags {flag: (kind, choices)}, pos_choices, pos_path}}`; the root `()` has the fixed flags of the main parser."""
    nodes = {}
    for name, child in subparsers.choices.items():
        _walk(child, (name,), nodes)
    nodes[()] = {'subs': sorted(subparsers.choices), 'flags': {flag: ('none', []) for flag in ROOT_FLAGS}, 'pos_choices': [], 'pos_path': False}
    return dict(sorted(nodes.items()))


def header():
    return f'# skillsync completion (generated by skillsync {__version__}; do not edit)'


# -- bash and zsh (the same data functions, different drivers)

def sh_quote(text):
    return "'" + str(text).replace("'", "'\\''") + "'"


def _sh_list(items):
    return '(' + ' '.join(sh_quote(item) for item in items) + ')'


def _sh_function(name, rows, default):
    lines = [f'{name}() {{', '    case "$1" in']
    lines += [f'        {sh_quote(key)}) {body} ;;' for key, body in rows]
    lines += [f'        *) {default} ;;', '    esac', '}']
    return '\n'.join(lines)


def _sh_data(model):
    key = ' '.join
    flag_rows = [(f'{key(path)}|{flag}', kind, choices) for path, node in model.items() for flag, (kind, choices) in node['flags'].items()]
    functions = [
        _sh_function('_skillsync_subs', [(key(p), f'_sk_reply={_sh_list(n["subs"])}') for p, n in model.items()], '_sk_reply=()'),
        _sh_function('_skillsync_flags', [(key(p), f'_sk_reply={_sh_list(sorted(n["flags"]))}') for p, n in model.items()], '_sk_reply=()'),
        _sh_function('_skillsync_kind', [(k, f'echo {kind}') for k, kind, _ in flag_rows if kind != 'none'], 'echo none'),
        _sh_function('_skillsync_choices', [(k, f'_sk_reply={_sh_list(c)}') for k, kind, c in flag_rows if kind == 'choices'], '_sk_reply=()'),
        _sh_function('_skillsync_pos', [(key(p), f'_sk_reply={_sh_list(n["pos_choices"])}') for p, n in model.items() if n['pos_choices']], '_sk_reply=()'),
        _sh_function('_skillsync_poskind', [(key(p), 'echo path') for p, n in model.items() if n['pos_path']], 'echo none'),
    ]
    return '\n\n'.join(functions)


_BASH_DRIVER = r'''_skillsync_add() {
    local s
    for s in "${_sk_reply[@]}"; do
        if [[ "$s" == "$cur"* ]]; then
            COMPREPLY+=("$s")
        fi
    done
}

_skillsync_files() {
    local IFS=$'\n'
    COMPREPLY+=($(compgen -f -- "$cur"))
}

_skillsync() {
    local cur prev node w s i kind
    cur="${COMP_WORDS[COMP_CWORD]}"
    prev=''
    if [ "$COMP_CWORD" -gt 1 ]; then
        prev="${COMP_WORDS[COMP_CWORD-1]}"
    fi
    node=''
    COMPREPLY=()
    i=1
    while [ "$i" -lt "$COMP_CWORD" ]; do
        w="${COMP_WORDS[i]}"
        if [[ "$w" == -* ]]; then
            kind=$(_skillsync_kind "$node|$w")
            if [ "$kind" != none ]; then
                i=$((i + 1))
            fi
        else
            _skillsync_subs "$node"
            for s in "${_sk_reply[@]}"; do
                if [ "$s" = "$w" ]; then
                    node="${node:+$node }$w"
                fi
            done
        fi
        i=$((i + 1))
    done
    kind=none
    if [[ "$prev" == -* ]]; then
        kind=$(_skillsync_kind "$node|$prev")
    fi
    case "$kind" in
        path) _skillsync_files; return 0 ;;
        choices) _skillsync_choices "$node|$prev"; _skillsync_add; return 0 ;;
        value) return 0 ;;
    esac
    if [[ "$cur" == -* ]]; then
        _skillsync_flags "$node"
        _skillsync_add
        return 0
    fi
    _skillsync_subs "$node"
    _skillsync_add
    _skillsync_pos "$node"
    _skillsync_add
    if [ "$(_skillsync_poskind "$node")" = path ]; then
        _skillsync_files
    fi
    return 0
}

complete -o filenames -F _skillsync skillsync
'''

_ZSH_DRIVER = r'''_skillsync() {
    local node='' w prev kind
    local -i i
    local -a _sk_reply
    for (( i = 2; i < CURRENT; i++ )); do
        w=$words[i]
        if [[ $w == -* ]]; then
            kind=$(_skillsync_kind "$node|$w")
            if [[ $kind != none ]]; then
                i=$(( i + 1 ))
            fi
        else
            _skillsync_subs "$node"
            if (( ${_sk_reply[(Ie)$w]} )); then
                node=${node:+$node }$w
            fi
        fi
    done
    kind=none
    if (( CURRENT > 2 )); then
        prev=$words[CURRENT-1]
        if [[ $prev == -* ]]; then
            kind=$(_skillsync_kind "$node|$prev")
        fi
    fi
    case $kind in
        path) _files; return ;;
        choices) _skillsync_choices "$node|$prev"; compadd -- "${_sk_reply[@]}"; return ;;
        value) return ;;
    esac
    if [[ $PREFIX == -* ]]; then
        _skillsync_flags "$node"
        compadd -- "${_sk_reply[@]}"
        return
    fi
    _skillsync_subs "$node"
    compadd -- "${_sk_reply[@]}"
    _skillsync_pos "$node"
    compadd -- "${_sk_reply[@]}"
    if [[ $(_skillsync_poskind "$node") == path ]]; then
        _files
    fi
}

_skillsync "$@"
'''


def render_bash(model):
    return '\n\n'.join([header(), _sh_data(model), _BASH_DRIVER.rstrip('\n')]) + '\n'


def render_zsh(model):
    return '\n'.join(['#compdef skillsync', header(), '', _sh_data(model), '', _ZSH_DRIVER.rstrip('\n')]) + '\n'


# -- PowerShell (ASCII only; Windows PowerShell 5.1 and 7)

def ps_quote(text):
    text = str(text)
    if text.isascii() and text.isprintable():
        return "'" + text.replace("'", "''") + "'"
    parts = []
    for char in text:
        parts.append("'" + char.replace("'", "''") + "'" if char.isascii() and char.isprintable() else f'[char]0x{ord(char):X}')
    return '(' + ' + '.join(parts) + ')'


def _ps_list(items):
    return '@(' + ', '.join(ps_quote(item) for item in items) + ')'


def _ps_data(model):
    lines = ['$skillsyncData = [System.Collections.Generic.Dictionary[string,object]]::new([System.StringComparer]::Ordinal)']

    def add(key, value):
        lines.append(f'$skillsyncData.Add({ps_quote(key)}, {value})')

    for path, node in model.items():
        key = ' '.join(path)
        add(f'S|{key}', _ps_list(node['subs']))
        add(f'F|{key}', _ps_list(sorted(node['flags'])))
        add(f'Q|{key}', _ps_list(node['pos_choices']))
        if node['pos_path']:
            add(f'P|{key}', ps_quote('path'))
        for flag, (kind, choices) in node['flags'].items():
            if kind != 'none':
                add(f'K|{key}|{flag}', ps_quote(kind))
            if kind == 'choices':
                add(f'C|{key}|{flag}', _ps_list(choices))
    return '\n'.join(lines)


_PS_DRIVER = r'''$skillsyncComplete = {
    param($wordToComplete, $commandAst, $cursorPosition)
    $words = @($commandAst.CommandElements | ForEach-Object { $_.ToString().Trim([char]39, [char]34) })
    if ($wordToComplete -ne '' -and $words.Count -gt 1) {
        $words = @($words[0..($words.Count - 2)])
    }
    $node = ''
    for ($i = 1; $i -lt $words.Count; $i++) {
        $w = $words[$i]
        if ($w.StartsWith('-')) {
            if ($skillsyncData.ContainsKey("K|$node|$w")) { $i++ }
        } elseif ($skillsyncData["S|$node"] -ccontains $w) {
            if ($node -eq '') { $node = $w } else { $node = "$node $w" }
        }
    }
    $prev = ''
    if ($words.Count -gt 1) { $prev = $words[$words.Count - 1] }
    if ($prev.StartsWith('-') -and $skillsyncData.ContainsKey("K|$node|$prev")) {
        if ($skillsyncData["K|$node|$prev"] -ne 'choices') { return }
        $items = @($skillsyncData["C|$node|$prev"])
    } elseif ($wordToComplete.StartsWith('-')) {
        $items = @($skillsyncData["F|$node"])
    } else {
        $items = @($skillsyncData["S|$node"]) + @($skillsyncData["Q|$node"])
    }
    foreach ($item in $items) {
        if ($item.StartsWith($wordToComplete, [System.StringComparison]::OrdinalIgnoreCase)) {
            $text = $item
            if ($text -match '[\s''"]') { $text = "'" + $text.Replace("'", "''") + "'" }
            [System.Management.Automation.CompletionResult]::new($text, $item, 'ParameterValue', $item)
        }
    }
}
Register-ArgumentCompleter -Native -CommandName skillsync -ScriptBlock $skillsyncComplete.GetNewClosure()
'''


def render_powershell(model):
    return '\n\n'.join([header(), _ps_data(model), _PS_DRIVER.rstrip('\n')]) + '\n'


RENDERERS = {'bash': render_bash, 'zsh': render_zsh, 'powershell': render_powershell}


def render(shell, subparsers):
    return RENDERERS[shell](build_model(subparsers))
